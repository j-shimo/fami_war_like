// 敵軍AIの思考パターン(行動方針)を表すパラメータ。Phaser には依存しない純粋な型定義。
//
// EnemyAi の判断は「生産で何を買うか」「どこへ向かうか」の 2 つに大きく分かれる。
// その方針をここで切り替えられるようにし、対戦キャラクターごとの実際の値は
// src/data/aiCharacters.ts にデータとして分離する(CLAUDE.md の方針)。

import type { UnitType } from '@/core/units/UnitType';

/** 生産の方針 */
export type AiProductionPolicy =
  /** 買える中で最も高価(強力)なユニットをその都度生産する */
  | 'strongest'
  /** 序盤を占領に振り、歩兵を多めにそろえてから強力なユニットを狙う */
  | 'infantryFirst'
  /** 編成表(roster)で決めた最低限の頭数をそろえ、その後に強力なユニットを狙う */
  | 'roster';

/** 攻撃も占領もできないユニットが、どこへ向かうかの方針 */
export type AiAdvancePolicy =
  /** 見えている最寄りの敵へ近づく(敵が見えなければ自軍所有でない最寄りの拠点へ) */
  | 'nearestEnemy'
  /** 占領できるユニットは未所有の拠点(中立優先)へ、それ以外は敵本拠地へ突き進む */
  | 'captureAndCharge'
  /**
   * 占領できるユニットは未所有の拠点(中立優先)へ向かうが、それ以外は攻め上がらず
   * 自軍の拠点のそばで構えて守る。攻めてきた敵は攻撃の判断(優先順位 1)で迎え撃つ。
   */
  | 'defendBase';

/** 目標までの距離の測り方 */
export type AiRouting =
  /** 直線距離(マンハッタン距離)で測る。山や海に阻まれると目標の手前で足踏みしやすい */
  | 'direct'
  /** 実際に通れるマスをたどった経路の長さで測る。障害物があれば回り道して向かう */
  | 'path';

/**
 * 編成表(roster)の 1 行。「この種別を最低 count 体はそろえる」という指定。
 * production が 'roster' のときだけ使い、一覧の先頭にあるものほど優先して生産する。
 */
export interface AiRosterEntry {
  /** そろえたいユニット種別 */
  readonly unitType: UnitType;
  /** そろえたい体数(生存数がこれを下回っているあいだは、この種別を優先して生産する) */
  readonly count: number;
}

/** 思考パターン 1 つぶんのパラメータ */
export interface AiBehavior {
  /** 生産の方針 */
  readonly production: AiProductionPolicy;
  /**
   * そろえたい歩兵の数(0 なら歩兵の頭数を気にしない)。
   * 生存している歩兵がこの数に届くまでは、歩兵を生産できる拠点では歩兵だけを生産する。
   * 歩兵が撃破されて数が減れば、また歩兵の生産に戻る。
   *
   * 生産の方針(production)によらず共通で効く。占領役が 1 体もいないと拠点が増えず、
   * 収入も伸びないまま高価なユニットだけが自陣に溜まってしまうため、
   * 'strongest'(いちばん高価なユニットを買う)でも最低限の占領役はここでそろえる。
   * 'infantryFirst' はこの数を多めに取り、序盤を占領に振る方針を表す。
   */
  readonly infantryQuota: number;
  /**
   * 最低限そろえたい編成(production が 'roster' のときだけ使う)。
   * 先頭から順に「生存数が count を下回っている種別」を探し、その拠点で生産できて
   * 資金が足りるものを優先して生産する。撃破されて数が減れば、また補充に戻る。
   */
  readonly roster: readonly AiRosterEntry[];
  /**
   * 歩兵がそろったあとの生産で、その拠点で生産できる最強ユニットのコストに対して
   * 何割以上のユニットだけを買うか(0 なら買えるものは何でも買う)。
   * これを下回るユニットしか買えないターンは生産を見送り、資金を貯めて次のターンに備える。
   */
  readonly powerCostRatio: number;
  /**
   * 「同じ種別をもう持っているなら、より強い種別のために資金を貯める」かどうか。
   *
   * true のとき、いま買える中で最強の種別をすでに 1 体以上持っていて、なおかつ
   * その拠点で作れる「より高価でまだ 1 体も持っていない種別」が残っていれば生産を見送る。
   * 同じユニットを並べるのではなく、ターンを重ねるごとに一段ずつ戦力を引き上げる。
   *
   * ただし戦力(ユニットの生産コストを残 HP の割合で割り引いた合計)で相手に負けている
   * あいだは貯めない。資金を抱えたまま押し切られるのを避けるため、劣勢のときは
   * いま買えるものを買って頭数を戻す。
   */
  readonly saveForUpgrade: boolean;
  /**
   * 間接攻撃(遠距離)ユニットを優先して生産するかどうか。
   *
   * true のとき、歩兵・編成表の頭数がそろったあとの生産で、その拠点で作れる
   * 間接攻撃ユニット(自走砲・ロケット砲・列車砲)のうち、いま買える最も高価なものを先に買う。
   * ただし優先するのは「自軍の間接攻撃ユニットが直接攻撃の戦闘ユニットより多くならない」
   * あいだだけで、多くなったあとは通常どおり強力なユニットを買う。
   * 遠距離を軸にしつつ、前に立つ戦車・偵察車も切らさないための歯止め。
   */
  readonly indirectPriority: boolean;
  /** 進軍の方針 */
  readonly advance: AiAdvancePolicy;
  /** 目標までの距離の測り方 */
  readonly routing: AiRouting;
  /**
   * 移動可能範囲内に複数の拠点があるとき、中立の拠点を優先して占領するか。
   * true でも敵本拠地の占領(勝利に直結する)より優先することはない。
   */
  readonly preferNeutralCapture: boolean;
  /**
   * 相性で不利な戦闘をしかけないかどうか。
   *
   * true のとき、想定される反撃が与ダメージ以上になる攻撃(相手のほうが有利な組み合わせ)は
   * しかけない。ただし相手を撃破できる攻撃は反撃を受けないため、不利な相性でもしかける。
   * 攻撃を見送ったユニットは、そのまま占領・接近の判断へ進む。
   */
  readonly avoidUnfavorableAttack: boolean;
  /**
   * 間接攻撃(遠距離)ユニットが間合いを取るかどうか。
   *
   * 間接攻撃ユニットは移動したターンは攻撃できず、最小射程より近づくと撃てなくなる。
   * true のとき、見えている敵がいれば「敵へ近づく」のではなく
   * 「その敵を射程(最小〜最大)に収めるマス」へ構え、次のターンから一方的に撃つ。
   * false では従来どおり敵へ近づき、隣接して撃てなくなることがある。
   */
  readonly indirectStandoff: boolean;
  /**
   * 夜戦で生産するユニットに求める視界の下限(マス)。0 なら視界を気にしない。
   *
   * 夜戦では視界の狭いユニットは自力で敵を見つけられず、高価でも持て余す
   * (重戦車・自走砲・ロケット砲・対空自走砲・対空ロケット砲・輸送車の視界は 1)。
   * 1 以上のとき、夜戦の生産候補からこの値に満たない種別を外し、
   * 目の利くユニットで編成をそろえる。候補が 1 つも残らない場合は外さない。
   * 昼戦ではマップ全体が明るいため参照しない。
   */
  readonly nightVisionFloor: number;
  /**
   * 味方と固まって進む距離(マス)。0 なら単独でも構わず前進する。
   *
   * 1 以上のとき、前進先はこの距離以内に味方がいるマスから選ぶ。
   * 足の速いユニットが 1 体だけ突出して各個撃破されるのを防ぎ、隊列を保って前線を押し上げる。
   * 条件を満たすマスが 1 つも無い(孤立している)場合は、従来どおり移動範囲全体から選ぶ。
   */
  readonly regroupRadius: number;
  /**
   * 空からの脅威に備えて持つ対空ユニット(対空戦車・対空自走砲・対空ロケット砲)の上限。
   *
   * 対空ユニットは「空の脅威」があるときだけ生産候補に入り、自軍の対空ユニットが
   * 上限に届いたら候補から外れる。上限は次のとおり決まる。
   * - 相手の飛行ユニットが見えている: この値と、見えている飛行ユニットの数の多いほう
   * - 見えていないが、相手(同盟軍を除く)が空港を持っている: この値
   * - どちらでもない: 0(対空ユニットを買わない)
   *
   * 対空戦車は地上ユニットも撃てるため、上限が無いと収入 1 万前後のマップでは
   * 「工場で買えるいちばん高価なユニット」として対空戦車ばかりが並んでしまう。
   * 夜戦では見えている敵だけを数えるが、拠点の持ち主は夜でも分かるため、
   * 見えないヘリへの備えは相手の空港で判断する。
   */
  readonly antiAirLimit: number;
  /**
   * 夜戦のときだけ最低限そろえたい編成(省略時は空 = 夜戦でも何も足さない)。
   *
   * production の方針によらず、夜戦では歩兵の目標数(infantryQuota)がそろったあと、
   * 強力なユニットより先にこの頭数を補充する。撃破されて数が減れば、また補充に戻る。
   * 生産の見送り基準(powerCostRatio)にも縛られないため、安い偵察車も買える。
   * 視界の狭い重装備ばかりを並べる指揮官が、暗闇で敵を 1 体も見つけられないまま
   * 一方的に撃たれるのを防ぐための「目」の確保に使う。昼戦では参照しない。
   * 行き先(相手ユニット・未所有の拠点)の無い種別は補充しない。
   */
  readonly nightRoster?: readonly AiRosterEntry[];
  /**
   * 気まぐれな生産をする確率(0〜1。省略時は 0 = 常に方針どおりに生産する)。
   *
   * 生産拠点ごとにこの確率で方針を無視し、その拠点で作れて資金の足りる種別から
   * でたらめに 1 つ選んで生産する。相手に 1 体も攻撃できない種別や、
   * 運ぶ相手のいない輸送ユニットを買ってしまうこともある(「変なもの」を買う)。
   * 買えるものが 1 つも無ければ、方針どおりの判断に戻る。
   * 海を渡る輸送ユニットが 1 体も無く、それを買う・その代金を貯めている場面では
   * 気まぐれを起こさない(代金を使い込んで海を越えられなくなるのを防ぐ)。
   */
  readonly oddProductionRate?: number;
  /**
   * 行動をしくじる確率(0〜1。省略時は 0 = 常に最善の手を選ぶ)。
   *
   * ユニットごとにこの確率で攻撃・占領などの判断をすべて飛ばし、
   * 移動できる範囲のでたらめなマスへ動いてそのまま待機する(その場で待機することもある)。
   * 目の前の敵を見逃したり、占領しかけの拠点から離れたりする「ミス」を表す。
   * 荷物を積んだ輸送ユニットはしくじらない(乗っているユニットごと迷子になるのを避ける)。
   */
  readonly blunderRate?: number;
}

