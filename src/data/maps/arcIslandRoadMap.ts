// 三日月(弧)の形をした島でできた 30x24(横30・縦24)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「湾ごしは目と鼻の先、陸路は島をぐるり」
//   - 陸地は左向きの三日月で、上の岬(row 0〜7)・右の背(col 20〜29)・下の岬(row 16〜23)が
//     ひと続きの弧を描く。弧の内側に抱え込まれた水面が湾で、湾の口は盤面の左端(col 0)にある。
//   - **島の外側(北・東・南)は盤面の外まで陸が続いている**。盤面に写っている水面は
//     湾とその口だけで、島の裏側へぐるりと回り込む外周の海路は存在しない。
//     海上ユニットのぶつかり合いはすべて湾の中で起きる。
//   - **先手の自軍は下の岬 (5,20)、後手の敵軍は上の岬 (5,3)**。湾をはさんで向かい合っており、
//     縦の直線距離は 17 マス。**輸送ヘリ(移動力 6)で本拠地から本拠地までちょうど 3 ターン**、
//     戦闘機(移動力 10)で 2 ターン、輸送艦(移動力 5)は港 (5,18) から敵軍の港 (5,5) まで
//     13 マスで 3 ターンかかる。
//   - 陸地は湾の口で切れているため、**陸路は弧をぐるりと回って歩兵 48・装軌車両 53 マス**。
//     **陸路で 16 ターン以上かかる相手に、船と飛行機なら 3 ターンで手が届く**ので、
//     このマップの読み合いは「遠い陸路をどう進めるか」ではなく、
//     「目の前の湾を渡る/渡らせない」に寄せてある。
//
// 岬(三日月の先端)と湾の口:
//   - 両軍の岬は西へ細く伸びて、先端は col 1〜2 まで届く。先端に近いほど幅が細くなり、
//     上の岬は (2,7)、下の岬は (2,16) の 1 マスで終わる。尖った先端どうしが湾を抱え込む形で、
//     そのすき間(盤面左端の col 0)が湾の口になる。
//   - **下の岬の先端 (1,18) は中立港**。自軍の工場 (4,20) から歩兵 4 マス(2 ターン)、
//     敵軍からは陸路 54 マスで、実質的に自軍がそのまま取れる 3 個目の港になる。
//     先端は三方を水に囲まれているので、ここから出した船はそのまま湾の口をふさげる。
//   - 岬の先をぐるりと回れば、島の外側の縁(row 0〜1 / row 22〜23)の水際へも船で近づける。
//     ただし縁は尾根(山と森)で拠点も街道も無く、上陸しても歩兵の足では前へ進めない。
//
// 弧に沿った街道と、街道を断ち切る森・山地帯:
//   - 街道は両軍の陣地から弧の形に沿って引いてある。自軍は本拠地の右どなりの工場から
//     row 20 を東へ (7,20)〜(23,20)、そこで北へ折れて col 23 を (23,19)〜(23,14) まで。
//     敵軍は row 3 を東へ (7,3)〜(23,3)、そこで南へ折れて col 23 を (23,4)〜(23,9) まで。
//   - **右の背の真ん中(row 10〜13)だけが 4 列の森・山地帯**で、街道はここで途切れている。
//     街道の終点までは両軍とも陣地から歩兵で 23 マスとまったく同じ距離で、その先の 4 マスだけが
//     道の無い区間になる。森・山地帯の縦断コストは col 23 の森づたいで歩兵 5・装軌車両 9。
//   - **装輪車両(偵察車・ロケット砲系)は森にも山にも入れないので、この 4 列をまったく
//     越えられない**。弧は湾の口で切れていて迂回路も無いため、装輪車両が相手の陣地へ向かうには
//     港で輸送艦に乗せて湾を渡るしかない(陸路の到達コストは両軍とも Infinity)。
//   - 街道のまわりには平地・森・中立都市が点在している。岬の水際や島の外側の縁には街道が無いので、
//     都市を拾いながら進むと自然に街道から離れることになる。
//
// 先手の自軍から伸びた街道の先(森・山地帯へ入る直前):
//   - 街道の終点 (23,14) のまわり、row 14〜17・col 20〜25 に中立拠点が固まっている。
//     **中立研究所 2 個 (21,15)/(21,17)・中立都市 3 個 (21,14)/(25,15)/(24,17)・
//     中立空港 1 個 (21,16)・中立港 1 個 (20,15)** の 7 個で、研究所・空港・研究所が
//     col 21 に縦 3 マスで並ぶ。
//   - **中立港 (20,15) は湾に面した内周の港**。島の外側には水面が無いので、ここで作った船は
//     そのまま湾へ出る。自軍から歩兵 19・敵軍から 28 と自軍のほうが近く、取れば
//     「湾の奥にもう 1 つの母港を構える」ことになる。
//   - どれも自軍のほうが近い(研究所 20 と 18 対 敵軍 27 と 29、空港 19 対 28、港 19 対 28)。
//     研究所を占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)ので、
//     **自軍は街道を伸ばし切れば新型戦車 2 両ぶんの戦力を受け取れる**。
//   - ただし固まりは自軍の陣地から歩兵で 18〜24 マス(6〜8 ターン)離れており、
//     取りにいくあいだ本拠地は手薄になる。中立空港 (21,16) と中立港 (20,15) を取れば
//     前線で飛行ユニット・海上ユニットを作れるようになるので、
//     「遠征して前線を作る」か「湾ぎわを固める」かの選択になる。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、開始時の拠点を完全に対等(両軍とも
//   本拠地 1 + 隣接する工場 3 + 1〜2 マス離れた港 2 + 2 マス離れた空港 1 = 7 拠点・収入 7000・
//   初期資金 0)にしたうえで、盤面に残す中立拠点の距離だけで釣り合わせている。
//   - **先手の自軍には一撃の戦力**: 街道の先の中立研究所 2 個 (21,15)/(21,17) と、
//     岬の先端の中立港 (1,18)。研究所は自軍 20/18・敵軍 27/29 と自軍が明確に近い。
//   - **後手の敵軍には伸び続ける収入**: 先に届く中立拠点を自軍 21 個・敵軍 25 個にしてある。
//     取り切ったときの収入は自軍 28000・敵軍 32000 で、後手が 4000 G ぶん上回る。
//   - 立ち上がりのターンは両軍そろえてある。陣地のいちばん近くの中立拠点までは
//     自軍 (4,19) も敵軍 (4,4) も移動コスト 1(歩兵 1 ターン)。
//   ハンデを増減させたいときは、上の岬(row 0〜7)の中立都市を増減させるか、
//   街道の先の中立研究所 2 個のどちらかを都市に戻して調整する。
//
// 初期ユニットは 0・初期資金も 0(initialFunds)。1 ターン目に使えるのは収入 7000 G だけで、
// 工場で地上ユニット、空港で飛行ユニット、港で海上ユニットのどれから手を付けるかが最初の一手になる。

