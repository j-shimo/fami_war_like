// 「C」を左右反転した形の島(弧島)でできた 30x24(横30・縦24)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「湾ごしは目と鼻の先、陸路は島をぐるり」
//   - 陸地は「C」を左右反転した弧(上の腕 row 2〜7・右の背 col 20〜26・下の腕 row 16〜21)で、
//     左の真ん中(row 8〜15・col 0〜19)がまるごと開いている。この開き口から入り込んだ水が
//     盤面中央の湾で、外海とひと続きにつながっている。
//   - **先手の自軍は下の腕の左端 (5,18)、後手の敵軍は上の腕の左端 (5,5)**。湾をはさんで
//     向かい合っているので直線ではわずか 13 マスだが、陸地は左で切れているため、
//     **陸路は弧をぐるりと回って歩兵 43・装軌車両 52 マス**かかる。
//   - 引き換えに、両軍とも開始時から**港 2 個と空港 1 個**を持っている。湾を突っ切る海路は
//     自軍の港 (5,16) から敵軍の港 (5,7) まで 9(輸送艦は移動力 5 なので 2 ターン)、
//     空路は自軍の空港 (5,20) から敵軍の本拠地まで 15(戦闘機なら 2 ターン)。
//     **陸路で 14 ターン以上かかる相手に、船と飛行機なら 2〜3 ターンで手が届く**。
//     このマップの読み合いは「遠い陸路をどう進めるか」ではなく、
//     「目の前の湾を渡る/渡らせない」に寄せてある。
//
// 弧に沿った街道と、街道を断ち切る森・山地帯:
//   - 街道は両軍の陣地から弧の形に沿って引いてある。自軍は本拠地の右どなりの工場から
//     row 18 を東へ (7,18)〜(23,18)、そこで北へ折れて col 23 を (23,17)〜(23,14) まで。
//     敵軍は row 5 を東へ (7,5)〜(23,5)、そこで南へ折れて col 23 を (23,6)〜(23,9) まで。
//   - **右の背の真ん中(row 10〜13)だけが 4 列の森・山地帯**で、街道はここで途切れている。
//     街道の終点までは両軍とも陣地から歩兵で 20 マスとまったく同じ距離で、その先の 4 マスだけが道の無い
//     区間になる。森・山地帯の縦断コストは col 23 の森づたいで歩兵 5・装軌車両 9。
//   - **装輪車両(偵察車・ロケット砲系)は森にも山にも入れないので、この 4 列をまったく
//     越えられない**。弧は左で切れていて迂回路も無いため、装輪車両が相手の陣地へ向かうには
//     港で輸送艦に乗せて海を回るしかない(陸路の到達コストは両軍とも Infinity)。
//   - 街道のまわりには平地・森・中立都市が点在している。腕の北岸・南岸には街道が無いので、
//     都市を拾いながら進むと自然に街道から離れることになる。
//
// 先手の自軍から伸びた街道の先(森・山地帯へ入る直前):
//   - 街道の終点 (23,14) のまわり、row 14〜17・col 19〜26 に中立拠点が固まっている。
//     **中立研究所 2 個 (21,15)/(21,17)・中立都市 3 個 (21,14)/(25,15)/(24,17)・
//     中立空港 1 個 (21,16)・中立港 1 個 (26,15)** の 7 個で、研究所・空港・研究所が
//     col 21 に縦 3 マスで並ぶ。
//   - どれも自軍のほうが近い(研究所 17 と 16 対 敵軍 25 と 27、空港 16 対 26、港 22 対 29)。
//     研究所を占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)ので、
//     **自軍は街道を伸ばし切れば新型戦車 2 両ぶんの戦力を受け取れる**。
//   - ただし固まりは自軍の陣地から歩兵で 16〜22 マス(6〜8 ターン)離れており、
//     取りにいくあいだ本拠地は手薄になる。中立空港 (21,16) と中立港 (26,15) を取れば
//     前線で飛行ユニット・海上ユニットを作れるようになるので、
//     「遠征して前線を作る」か「湾ぎわを固める」かの選択になる。
//
// 先手の自軍の陣地の少し左上の中立港:
//   - 湾の口にあたる (3,16) が中立港。自軍の工場 (4,18) から歩兵で 2 マス(1 ターン)、
//     敵軍からは陸路 43 マスで、実質的に自軍がそのまま取れる 3 個目の港になる。
//   - 取れば自軍は湾の口に港 3 個(自前の (3,18)/(5,16) と合わせて)を並べることになり、
//     湾を渡る船をまとめて出せる。後手の敵軍にとっては「湾の対岸に艦隊の巣ができる」ことを
//     意味するので、敵軍側も上の腕の港 (5,7) から早めに海へ出ておきたい。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、開始時の拠点を完全に対等(両軍とも
//   本拠地 1 + 隣接する工場 3 + 1 マス離れた港 2 + 1 マス離れた空港 1 = 7 拠点・収入 7000・
//   初期資金 0)にしたうえで、盤面に残す中立拠点の距離だけで釣り合わせている。
//   - **先手の自軍には一撃の戦力**: 街道の先の中立研究所 2 個 (21,15)/(21,17) と、
//     陣地の左上の中立港 (3,16)。研究所は自軍 17/16・敵軍 25/27 と自軍が明確に近い。
//   - **後手の敵軍には伸び続ける収入**: 先に届く中立拠点を自軍 17 個・敵軍 21 個にしてある。
//     取り切ったときの収入は自軍 24000・敵軍 28000 で、後手が 4000 G ぶん上回る。
//   - 立ち上がりのターンは両軍そろえてある。陣地のいちばん近くの中立拠点までは
//     自軍 (4,17) も敵軍 (4,6) も移動コスト 1(歩兵 1 ターン)。
//   ハンデを増減させたいときは、上の腕(row 2〜7)の中立都市を増減させるか、
//   街道の先の中立研究所 2 個のどちらかを都市に戻して調整する。
//
// 初期ユニットは 0・初期資金も 0(initialFunds)。1 ターン目に使えるのは収入 7000 G だけで、
// 工場で地上ユニット、空港で飛行ユニット、港で海上ユニットのどれから手を付けるかが最初の一手になる。

