// 4 つの軍勢が盤面の真ん中の高台を奪い合う 26x26(横26・縦26)の 4P マップ。4Pマップ区分(group: 'four')の 4 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「山に囲まれた中央の高台に、研究所 2 個と空港 1 個。車両が上がれる入口は 4 つの峠だけ」
//   これまでの 4P マップ 3 枚はどれも「四隅の陣地とそのまわりの取り合い」だった。
//   このマップは盤面の真ん中に、4 軍が等しく狙える奪い合いの場所を置く。
//   先に高台を取った軍は、残る 3 軍の的になる。出遅れた軍が漁夫の利を狙える展開を作る。
//
// 陣地(4 軍とも本拠地 1 + 工場 3 = 収入 4000・初期資金 0 の対等な立ち上がり):
//   1P の陣地を 90 度ずつ回して 4 隅に置いてあり、陣地の形と陣地まわりの地形は 4 軍とも同じ。
//     - 1P(青・左上): 本拠地 (2,2) / 工場 (3,2)(2,3)(3,3)
//     - 2P(赤・右上): 本拠地 (23,2) / 工場 (22,2)(23,3)(22,3)
//     - 3P(緑・左下): 本拠地 (2,23) / 工場 (3,23)(2,22)(3,22)
//     - 4P(黄・右下): 本拠地 (23,23) / 工場 (22,23)(23,22)(22,22)
//   4Pモードで「なし」を選んだ軍勢の陣地は、本拠地が中立の都市に・工場が中立の工場になる
//   (src/data/maps/armySlots.ts)。
//
// 環状道路:
//   row 4・row 21・col 4・col 21 を結ぶ四角い道路が盤面をひと回りし、4 軍の陣地の角をつなぐ。
//   隣り合う陣地どうし(1P〜2P・1P〜3P・2P〜4P・3P〜4P)は本拠地から本拠地まで歩兵 20・
//   装軌車両 21・装輪車両 23。対角の陣地(1P〜4P・2P〜3P)はどれも 40 と遠い。
//
// 中央の高台:
//   col 7〜18・row 7〜18 を厚さ 2 マスの山の輪がぐるりと囲み(峠を除いて山 72 マス)、内側の 8x8(col 9〜16・row 9〜16)が高台。
//   山には車両(装軌・装輪)が入れないので、車両が高台へ上がれるのは 4 つの峠だけ。
//   歩兵は山を越えて上がれる(山 2 マスでコスト 4)。
//   高台の中の中立拠点は 3 個だけ。
//     - 西の研究所 (10,13) … 1P と 3P が狙う
//     - 東の研究所 (16,12) … 2P と 4P が狙う
//     - 中央の空港 (13,13) … 4 軍とも近い。盤面で唯一の空港で、ここを取った軍だけが飛行ユニットを作れる
//   (盤面に空港はあるので、対空自走砲・対空ロケット砲は初めから作れる。
//   docs/GameDesign.md「マップに空港がない場合の生産制限」)
//
// 峠(車両の入口。手番の遅い軍ほど近い):
//   陣地は 4 軍とも同じ形だが、峠だけは回転させずに置き場所をずらしてある。
//   どの峠も環状道路から高台の中まで道路でつながっている。
//     - 1P: 西の壁 row 12 (7,12)(8,12)。高台の入口 (9,12) まで工場から 15
//     - 2P: 北の壁 col 14 (14,7)(14,8)。高台の入口 (14,9) まで工場から 14
//     - 3P: 南の壁 col 10 (10,17)(10,18)。高台の入口 (10,16) まで工場から 13
//     - 4P: 東の壁 row 16 (17,16)(18,16)。高台の入口 (16,16) まで工場から 12
//   (数字は歩兵・装軌車両・装輪車両のどれでも同じ移動コスト。峠へは道路で行ける)
//   峠は風車の羽根のように 4 方向へ向いていて、1P の西の峠と 3P の南の峠は西の研究所に、
//   2P の北の峠と 4P の東の峠は東の研究所に近い。
//
// 高台の拠点までの距離(最寄りの工場から。歩兵の移動コスト):
//   西の研究所  1P 17・3P 16(2P 22・4P 21)
//   東の研究所  2P 17・4P 16(1P 22・3P 23)
//   中央の空港  1P 20・2P 19・3P 19・4P 18
//   研究所はどちらの組も、後手の軍(3P・4P)が 1 マス近い。ただし歩兵の移動力は 3 なので、
//   生産の次のターンから歩けばどちらの軍も 7 ターン目に着き、同じターンなら手番の早い軍
//   (1P・2P)が先に踏める。1 マスの差は「後手が歩兵を寄り道させる余裕」くらいの効きにとどめてある。
//   空港は 4P だけが 7 ターン目(残る 3 軍は 8 ターン目)に着く。
//   手番の最後の 4P が高台にいちばん早く上がれるぶん、真っ先に残る 3 軍の的になる。
//
// 中立都市 24 個(陣地と同じく 90 度ずつ回して 4 軍で同じ並び):
//   1P の近く: (5,2) 2・(1,6) 4・(6,6) 6・(8,5) 7・(2,10) 7・(11,2) 8(かっこ内は 1P の工場からの歩兵の移動コスト)
//   2P・3P・4P の近くにも同じ距離で 6 個ずつある。
//   陣地のすぐ隣の都市は 4 軍とも 1 ターン(移動コスト 2)で届く。
//   都市は対等にそろえ、手番のハンデは峠の近さ(高台の拠点までの距離)だけで付けている。
//
// 先手番のハンデの調整:
//   峠の位置を壁に沿って 1 マス動かすと、その軍の高台までの距離が 1 ずつ変わる。
//   陣地まわりは 4 軍で同じなので、効きを読みやすい。

