// 湖をぐるりと囲む「G」の字の島と街道でできた 28x24(縦24・横28)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「『G』の字の島。遠回りの街道か、近道の峠か」
//   - 陸地は中央の湖をぐるりと囲む輪で、その右中ほどから内側へ横棒が 1 本突き出している。
//     輪 + 横棒で「G」の字を描く形で、街道も同じ「G」の字に引いてある
//     (上 row 5 → 左 col 4 → 下 row 19 → 右 col 23 → 横棒 row 12)。
//   - **「G」の切れ目にあたるのが右上**。街道はここで途切れており、輪をつないでいるのは
//     幅 1〜2 マスの山と森の峠だけ(col 21〜22・row 6〜11)。東は入り江、西は湖で、
//     陸が細く締まった首になっている。
//   - 先手の自軍は島の上の真ん中、後手の敵軍は横棒の先っちょ。**両軍を最短で結ぶのはこの峠**だが、
//     街道が無いので装軌車両は森でコスト 2 と足が鈍り、装輪車両(偵察車・ロケット砲系)は
//     森にも山にも入れず**まったく通れない**。装輪車両は「G」の街道を大きく遠回りするしかない。
//     自軍の陣地から敵軍の本拠地までは、歩兵 25・装軌車両 31 に対して装輪車両は 64 と 2 倍以上。
//   - 峠の真ん中には中立の研究所 (22,9) が 1 個だけあり、**平地へ抜けるまで都市は 1 つも無い**。
//     占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)が、
//     山に挟まれた幅 1 マスの隘路なので、取ったあとはそのまま峠の栓にもなる。
//
// 中央の湖と、左下へ流れる川:
//   - 輪の内側(col 7〜20・row 8〜16)は湖。地上ユニットはまったく入れないので、
//     戦場は「G」の輪の上だけになる。港も空港も 1 つも無いため、船も飛行ユニットも出てこない。
//   - 湖の水は左下の隅から幅 1 マスの川になって西の海へ抜ける
//     ((6,16)→(6,17)→(5,17)→(5,18)→(3,18)→(2,18))。川は歩兵がコスト 2・装軌車両が
//     コスト 3 で渡れるが、装輪車両は渡れない。
//   - **川が街道を横切るところ (4,18) が橋**。「G」の街道で川を渡れるのはこの 1 マスだけ。
//     しかも装輪車両は峠(森と山)も川も通れないので、**装輪車両にとってこの橋が盤面の南北を
//     つなぐ唯一の道**になる。橋を押さえられた装輪車両は、相手の陣地へ一歩も近づけない。
//   - 橋の少し左上、川の北岸に中立の研究所 (3,17) がもう 1 個ある。街道のすぐ隣なので
//     装輪車両でも取りにいけるが、自軍から 21・敵軍から 36 と自軍のほうがはるかに近い。
//
// 先手の自軍(島の上の真ん中):
//   - 本拠地 (14,4) と、それに隣接する工場 3 個 (13,4)/(15,4)/(14,3)。街道(row 5)は
//     本拠地のすぐ下を通っているので、作ったユニットは 1 マスで街道に乗れる。
//   - **開始時から都市を 3 個持っている**((11,3)/(17,3)/(14,7))。どれも工場から 3〜4 マスの
//     位置で、陣地と合わせて 7 拠点・収入 7000 で立ち上がる。
//   - 自軍が先に届く中立拠点は 12 個(都市 10・研究所 2)。上の平地と左の腕、そして
//     橋のまわりが自軍の伸びしろになる。
//
// 後手の敵軍(「G」の横棒の先っちょ):
//   - 本拠地 (9,12) と、それに隣接する工場 3 個 (9,11)/(9,13)/(10,12) の 4 拠点だけ。
//     収入 4000・初期資金 0 と、立ち上がりは自軍より 3000 G 分遅い。
//   - **本拠地の西・北西・南西は湖**なので、攻めるにも守るにも道は横棒 1 本だけ。
//     船も飛行ユニットも出ないこのマップでは、敵軍の陣地は「横棒を抜かれない限り落ちない」
//     最も堅い陣地になる。そのぶん敵軍も外へ出るには横棒を通らなければならない。
//   - 引き換えに、敵軍が先に届く中立都市は 17 個と自軍(10 個)より 7 個多い。とくに
//     横棒の上の 5 個((11,11)/(11,13)/(14,13)/(17,11)/(19,13))は陣地の目の前で、
//     いちばん近い 2 個は歩兵 1 ターン(移動コスト 2)で届く。自軍の最寄り (19,3) も
//     1 ターン(2)なので、収入が伸び始めるターンは両軍そろっている。
//   - **「G」の右下は中立都市 10 個の固まり**((25,13)/(21,14)/(24,14)/(22,16)/(25,16)/
//     (21,18)/(24,18)/(25,19)/(22,20)/(24,20))。街道の右の縦棒(col 23)と下の横棒(row 19)が
//     交わる一帯で、横棒を東へ抜けた敵軍が 13〜22 で届くのに対し、自軍は峠を越えても 15〜23。
//     ここを取り切れるかどうかが、収入で追い抜かれるかどうかの分かれ目になる。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、開始時の拠点と中立拠点の距離で釣り合わせている。
//   先手の自軍へ渡してあるのは、①開始時の都市 3 個ぶんの収入差(7000 対 4000)、
//   ②峠の研究所と左下の研究所(新型戦車 2 両ぶん)への近さ、の 2 つ。
//   後手の敵軍へ渡してあるのは、①三方を湖に守られた本拠地、②先に届く中立都市の数
//   (17 個 対 10 個)、③右下の中立都市 10 個の固まりへの近さ、の 3 つ。
//   ハンデを増減させたいときは、自軍の開始時の都市 (11,3)/(17,3)/(14,7) を平地に戻すか、
//   右下の固まりの都市を増減させて調整する。
//
// 初期ユニットは 0・初期資金も 0(initialFunds)。1 ターン目に使えるのは収入だけで、
// 自軍は 7000 G(歩兵 + 軽戦車、あるいは偵察車 2 両)、敵軍は 4000 G(歩兵 4 体まで)。
// 序盤は「峠へ先に手を伸ばすか、足元の都市を固めるか」の一手が効く。

