// 湖をぐるりと囲む「G」の字の島と街道でできた 28x28(縦28・横28)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「『G』の字の島。遠回りの街道か、近道の峠か」
//   - 陸地は縦長の湖をぐるりと囲む輪で、その右中ほどから内側へ横棒が 1 本突き出している。
//     輪 + 横棒で「G」の字を描く形で、街道も同じ「G」の字に引いてある
//     (上 row 5 → 左 col 4 → 下 row 23 → 右 col 23 → 横棒 row 16)。
//   - **「G」の切れ目にあたるのが右上**。街道はここで途切れており、輪をつないでいるのは
//     幅 2 マスの山と森の峠だけ(col 21〜22・row 6〜15)。東は入り江、西は湖で、
//     陸が細く締まった首になっている。盤面が縦に長いぶん、峠も縦に長い。
//   - 先手の自軍は島の上の真ん中、後手の敵軍は横棒の先っちょ。**両軍を最短で結ぶのはこの峠**だが、
//     街道が無いので装軌車両は森でコスト 2 と足が鈍り、装輪車両(偵察車・ロケット砲系)は
//     森にも山にも入れず**まったく通れない**。装輪車両は「G」の街道を大きく遠回りするしかない。
//     自軍の陣地から敵軍の本拠地までは、歩兵 24・装軌車両 33 に対して装輪車両は 51。
//   - 峠の北寄りには中立の研究所 (22,9) が 1 個だけあり、**平地へ抜けるまで都市は 1 つも無い**。
//     占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)が、
//     山に挟まれた幅 1 マスの隘路なので、取ったあとはそのまま峠の栓にもなる。
//
// 中央の湖と、左下へ流れる川:
//   - 輪の内側(col 7〜20・row 8〜20)は縦長の湖。地上ユニットはまったく入れないので、
//     戦場は「G」の輪の上だけになる。港も空港も 1 つも無いため、船も飛行ユニットも出てこない。
//   - **湖の北岸 (row 7) から敵軍の陣地 (row 15〜17) までは 8 マス以上**あり、
//     射程 3〜5 のロケット砲では湖越しに陣地へ届かない。北から敵軍の陣地を狙うには、
//     湖を回り込んで峠か街道を抜けるしかない(そのロケット砲は装輪車両なので峠も通れない)。
//   - 湖の水は左下の隅から幅 1 マスの川になって西の海へ抜ける
//     ((6,20)→(6,21)→(5,21)→(5,22)→(3,22)→(2,22))。川は歩兵がコスト 2・装軌車両が
//     コスト 3 で渡れるが、装輪車両は渡れない。
//   - **川が街道を横切るところ (4,22) が橋**。「G」の街道で川を渡れるのはこの 1 マスだけ。
//     しかも装輪車両は峠(森と山)も川も通れないので、**装輪車両にとってこの橋が盤面の南北を
//     つなぐ唯一の道**になる。橋を押さえられた装輪車両は、相手の陣地へ一歩も近づけない。
//   - 橋の少し左上、川の北岸に中立の研究所 (3,21) がもう 1 個ある。街道のすぐ隣なので
//     装輪車両でも取りにいけるが、自軍から 25・敵軍から 18 と敵軍のほうが近い。
//
// 先手の自軍(島の上の真ん中):
//   - 本拠地 (14,4) と、それに隣接する工場 3 個 (13,4)/(15,4)/(14,3)。街道(row 5)は
//     本拠地のすぐ下を通っているので、作ったユニットは 1 マスで街道に乗れる。
//   - **開始時から都市を 3 個持っている**((11,3)/(17,3)/(14,7))。どれも工場から 3〜4 マスの
//     位置で、陣地と合わせて 7 拠点・収入 7000 で立ち上がる。
//   - 自軍が先に届く中立拠点は 13 個(都市 12・研究所 1)。北岸の平地と左の腕が自軍の伸びしろで、
//     峠の研究所 (22,9) も自軍 10・敵軍 13 と自軍のほうが近い。
//
// 後手の敵軍(「G」の横棒の先っちょ):
//   - 本拠地 (15,16) と、それに隣接する工場 3 個 (15,15)/(16,16)/(15,17) の 4 拠点だけ。
//     収入 4000・初期資金 0 と、立ち上がりは自軍より 3000 G 分遅い。
//   - **本拠地の西・北西・南西は湖**(col 14)。横棒は以前より 6 マス短く、先っちょは湖に
//     突き出した小さな出島のような形になっている。
//   - 横棒の南 (col 15〜20・row 18〜20) は湖を埋め立てた平地で、**その真ん中を街道 (col 18) が
//     南へ貫いて下の横棒 (row 23) につながる**。敵軍の陣地から外へ出る道は、東へ抜ける
//     横棒 (row 16) と、この埋め立て地を南へ下りる縦棒の 2 本。
//   - 引き換えに、敵軍が先に届く中立拠点は 18 個と自軍(13 個)より 5 個多い。とくに
//     横棒の上の 4 個((17,15)/(19,15)/(17,17)/(19,17))は陣地の目の前で、
//     いちばん近い 2 個は歩兵 1 ターン(移動コスト 2)で届く。自軍の最寄り (18,2)/(19,3) も
//     1 ターン(2)なので、収入が伸び始めるターンは両軍そろっている。
//   - **「G」の右下は中立都市 10 個の固まり**((25,17)/(21,18)/(24,18)/(22,20)/(25,20)/
//     (21,22)/(24,22)/(25,23)/(22,24)/(24,24))。街道の右の縦棒(col 23)と下の横棒(row 23)が
//     交わる一帯で、埋め立て地の街道を下りた敵軍が 7〜16 で届くのに対し、自軍は峠を越えても
//     20〜27。ここを取り切れるかどうかが、収入で追い抜かれるかどうかの分かれ目になる。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、開始時の拠点と中立拠点の距離で釣り合わせている。
//   先手の自軍へ渡してあるのは、①開始時の都市 3 個ぶんの収入差(7000 対 4000)、
//   ②峠の研究所 (22,9) への近さ、③湖に守られて北から撃たれない代わりに北半分がまるごと
//   自軍の庭になること、の 3 つ。
//   後手の敵軍へ渡してあるのは、①三方を湖に守られた本拠地、②先に届く中立拠点の数
//   (18 個 対 13 個)、③右下の中立都市 10 個の固まりと川の研究所 (3,21) への近さ、の 3 つ。
//   ハンデを増減させたいときは、自軍の開始時の都市 (11,3)/(17,3)/(14,7) を平地に戻すか、
//   右下の固まりの都市を増減させて調整する。
//
// 初期ユニットは 0・初期資金も 0(initialFunds)。1 ターン目に使えるのは収入だけで、
// 自軍は 7000 G(歩兵 + 軽戦車、あるいは偵察車 2 両)、敵軍は 4000 G(歩兵 4 体まで)。
// 序盤は「峠へ先に手を伸ばすか、足元の都市を固めるか」の一手が効く。

