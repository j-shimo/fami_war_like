//     分岐点のまわりにも中立都市 2 個((30,10)(32,12))を置いてあり、こちらは自軍のほうが近い
//     (歩兵 16 と 14。敵軍は 33 と 34)。
//   - **線路**: 敵軍の駅 (7,19) から中立の駅 (17,16) を経て、右下の中立の駅 (29,19) までを結ぶ。
