// 盤面の左端だけに海があり、右上の湖から西へ 1 本の川が流れる 35x24(縦24・横35)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「川より上は森、川より下は山。渡れる者と、道を行く者」
//   - 盤面は川(row 7)で上下に分かれる。北側(row 0〜6)は一面の森、南側(row 8〜23)は一面の山で、
//     南の山を刻むのは「くねくね道」「線路とそのまわりの森」「両軍の陣地」だけ。
//   - 川と湖は地上ユニットの進路をまるごと断つ。歩兵はコスト 2・装軌車両はコスト 3 で川を渡れるが、
//     川のすぐ南(row 8)は端から端まで山なので、**川を渡って南へ降りられるのは歩兵だけ**になる
//     (装軌車両は山へ入れず、装輪車両はそもそも川を渡れない)。それでも近道の価値は大きく、
//     自軍の工場 (30,2) からくねくね道 (24,9) までは、川を渡る歩兵なら 15・街道を回る装輪車両は 27。
//   - 車両が南北を行き来する道は、盤面の右端を縦に走る街道(col 33)ただ 1 本。
//     湖(col 27〜31・row 5〜8)の右側を通って下り、湖を越えたあたりの分岐点 (33,11) で
//     「左(くねくね道)」と「下(右下の空間)」の 2 手に分かれる。
//     この 1 本道が、このマップの地上戦のすべての結節点になる。
//
// 先手の自軍(右上)と後手の敵軍(左下):
//   - 自軍は本拠地 (30,1) + 工場 3 + 空港 2 + 港 1 の 7 拠点(収入 7000)。港 (29,4) は湖に面しており、
//     湖 → 川 → 西の海までが 1 本の水路としてつながっているので、艦隊は川を下って盤面の反対側へ
//     回り込める(自軍の港から敵軍の港までは海路 44)。空港が 2 つあるぶん、川も山も飛び越えられる
//     飛行ユニットが自軍の主力になる。
//   - 敵軍は本拠地 (5,20) + 工場 3 + 空港 1 + 港 1 + 駅 1 の 7 拠点(収入 7000)。拠点の数と収入は
//     自軍と同じだが、**開始時に駅を持つのは敵軍だけ**なので、列車砲(30000 G・移動力 15・射程 2〜6)を
//     生産できるのも最初は敵軍だけになる。空港 2 の自軍と駅 1 の敵軍、という非対称な立ち上がり。
//     盤面には中立の駅が 2 つあり、そちらを占領すれば自軍も列車砲を出せるので、
//     線路は最後まで争点であり続ける。
//   - 敵軍の駅 (7,19) は、陣地の生産拠点でただ 1 つ row 19 に置いてある。敵軍AIは生産拠点を
//     上の行から順に回るため、駅を最初に回らせないと初期資金 31000 G を手前の工場で使い切り、
//     列車砲(30000 G)が 1 体も出ないまま試合が進んでしまう。
//
// 北西の「山に囲まれた 3x3」:
//   - 川が海へ出る手前、川の北側の (5〜7,3〜5) が山の輪(col 4〜8・row 2〜6)にすっぽり囲まれた
//     3x3 の窪地になっている。中立の研究所 (6,4)・中立都市 (5,3)/(6,5)・中立空港 (7,3) の 4 拠点があり、
//     山は装軌車両・装輪車両が進入できないので、ここへ入れるのは**歩兵と飛行ユニットだけ**。
//   - 中立のうちに研究所を占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)が、
//     進化した新型戦車は装軌車両なので、山の輪を越えて外へ出ることはできない。
//     窪地の中立空港を先に取って輸送ヘリを出すか、研究所は諦めて空港だけ押さえるか、という選択になる。
//   - 北の森を西へ歩く自軍のほうが近い(研究所まで歩兵 24・空港まで 23。敵軍は 27 と 27)。
//     敵軍は陣地から山を北上するより、港から輸送艦を出して西岸の海岸 (3,4)/(3,5) へ揚陸するほうが速い。
//
// 南の山を刻む 2 本の筋:
//   - **くねくね道**: 分岐点 (33,11) から左へ、山のあいだを曲がりながら 44 マスかけて敵軍の陣地の
//     入口 (8,18) までつながる 1 マス幅の街道。道ぞいに中立都市 4 個((25,9)(18,13)(11,13)(9,18))が並ぶ。
//     1 マス幅では車両が詰まるので、曲がり角のわきには平地の待避所を置いてある。
//   - **線路**: 敵軍の駅 (7,19) から中立の駅 (17,16) を経て、右下の中立の駅 (29,19) までを結ぶ。
//     駅から駅までは 13 と 15、端から端までは 28。移動力 15 の列車砲は中立駅 (17,16) までなら
//     1 ターンで届き、右下の駅 (29,19) までは 2 ターンかかる。
//     線路のまわりは森(一部は平地)にしてあるので、装軌車両は線路ぞいの森を進んで列車砲に随伴できる
//     (装輪車両は森へ入れないため、くねくね道を通るしかない)。
//
// 2 つの中立駅:
//   - 中央の中立駅 (17,16) は森と中立都市 5 個((16,15)(18,15)(15,17)(17,17)(19,17))に囲まれた
//     このマップ最大の争点。くねくね道 (17,14) から支道 (17,15) が 1 マスだけ降りてつながっており、
//     敵軍からは線路(歩兵)で 13・装軌車両で 17 と近いが、自軍からは歩兵 26・装軌車両 41 と遠い。
//   - 右下の中立駅 (29,19) は、山に囲まれた 4x5 の空間(col 28〜31・row 17〜21)にあり、
//     中立都市 4 個((28,17)(31,17)(28,21)(31,21))を従えている。この空間へ入る口は、
//     西から入る線路 (27〜28,19) と、東から街道が降りてくる (32,19) の 2 つだけ。
//     自軍は右端の街道づたいに歩兵・装軌車両・装輪車両のどれでも 24 で着けるので、
//     **線路の終点なのに自軍のほうが近い**(敵軍は歩兵 26・装軌車両 40・装輪車両 59)。
//     敵軍が列車砲で 2 ターンかけて取りに来るか、自軍が先に押さえるかの競争になる。
//
// 中立拠点は 26 個(中立都市 21・中立研究所 1・中立空港 1・中立港 1・中立駅 2)。
// 西岸の中立港 (3,12) は川より南の山に囲まれた入り江にあり、車両はどうやっても近づけない
// (自軍の港からは海路 36、敵軍の港からは陸路でも 13)。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、後手の敵軍に次の 3 つを渡してある。
//   ①開始時に列車砲を生産できるのは敵軍だけ(駅 1)。②敵軍の陣地の隣にだけ中立都市を 2 個
//   ((4,18) と (6,18))置いてあり、歩兵の移動力 3 でどちらも 1 ターンで届く(移動コスト 2)。
//   自軍の最寄りの中立都市 (23,2) は 5 マスあるので 2 ターンかかり、収入が伸び始めるのは
//   後手のほうが 1 ターン早い。③中央の中立駅とそのまわりの中立都市 5 個は敵軍のほうがはるかに近い。
//   引き換えに先手の自軍へ渡してあるのは、①空港 2 つぶんの制空権、②北の森と北西の窪地
//   (研究所・空港を含む 4 拠点)への近さ、③右端の街道づたいに右下の中立駅へ先着できる速さ、の 3 つ。
//   ハンデを増減させたいときは (4,18)/(6,18) の 2 マスで調整する。
//
// 陣地から相手の本拠地までは、自軍発が歩兵 42・装軌車両 60・装輪車両 63、
// 敵軍発が歩兵 43・装軌車両 58・装輪車両 60 とほぼ釣り合っている。
//
// 初期ユニットは 0。初期資金 31000 は列車砲(30000)+ 歩兵(1000)ぶんの額で、
// 敵軍が 1 ターン目から列車砲を出せるようにしてある(敵軍AIは収入を貯め込んで高額ユニットを
// 買うのが苦手なため。三叉鉄橋マップと同じ調整)。自軍は同じ額で戦闘機(20000)や
// 攻撃機(26500)を初手から出せる。

