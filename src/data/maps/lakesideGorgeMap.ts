//   - **くねくね道**: 分岐点 (33,11) から左へ、山のあいだを曲がりながら盤面を横断し、
//     西の海ぎわ (3,16)/(3,17) まで出てから南へ折れて、**敵軍の陣地を上から** (3,18) で
