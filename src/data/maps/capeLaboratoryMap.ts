// 北西に先手の島・南東に後手の島が斜向かいに並ぶ 28x25(縦25・横28)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「拠点は少ないが伸びしろのある先手 vs 先に育ち切った後手」
//   - 北西の島(row 0〜18)が先手の自軍、南東の島(row 10〜24)が後手の敵軍の本土。
//     2 つの島は斜めに向かい合い、あいだを幅の広い海が斜めに走る。陸続きの経路は 1 本も無く、
//     相手の本土へ渡る手段は輸送艦での上陸作戦か、空港で作る飛行ユニットだけになる。
//   - 自軍は本拠地 1・工場 3・空港 1・港 2・都市 3 の 10 拠点(収入 10000)、
//     敵軍は本拠地 1・工場 3・空港 1・港 2・都市 8 の 15 拠点(収入 15000)で始まる。
//     開始時点の収入は敵軍が 1.5 倍だが、盤面に残る中立拠点 21 個のうち 18 個は自軍の島と
//     岬・離島にあり、敵軍の島に残っているのは中立都市 3 個だけ。
//     「先に育ち切った後手を、伸びしろのある先手が追い抜けるか」という組み立てになる。
//   - 初期資金は両軍とも 0(initialFunds)。1 ターン目に使えるのは収入ぶんだけなので、
//     自軍は 10000 G、敵軍は 15000 G から立ち上がる。
//
// 北西の島の本体(自軍の本土。row 0〜8)と両サイドの中立都市:
//   - 自軍の陣地は島の真ん中(col 9〜13、row 1〜3)にまとまっている。
//     本拠地 (11,2) の左右に工場 (10,2)/(12,2)、その下にもう 1 つの工場 (11,3)、
//     真上に空港 (11,1)、両隣に自軍の都市 (9,2)/(13,2) を置き、
//     街道へ降りたところにもう 1 個の都市 (11,6) がある。
//   - 自軍の港 2 つは街道(row 5)の上の (10,5) と (12,5) で、あいだに街道 1 マス (11,5) を
//     挟んで並んでいる。どちらも工場 (11,3) からちょうど 3 マス(歩兵・装軌車両・装輪車両とも)
//     なので、作った地上ユニットは 1 ターンで乗船地点へ出られる。
//     港の下の (10,6)/(12,6) は南の海から切れ込んだ幅 1 マスの入り江で、そのあいだに残った
//     (11,6) が自軍の都市。海岸 (10〜13,7) と (7〜9,8) も積み込みと揚陸に使える。
//   - 中立都市 10 個は陣地を挟んで西側 5 個((6,1)(2,2)(8,3)(1,4)(5,6))と
//     東側 5 個((16,1)(18,2)(14,3)(17,4)(15,6))にきれいに分かれている。
//     どちらへ先に歩兵を送るかで、そのあとの戦線の重心が決まる。
//   - 島を東西に貫く街道(row 5)が両サイドの中立都市と陣地を結び、そこから
//     col 11 の枝道が陣地と港へ、col 3 の枝道が南の岬へ降りる。
//   - 島の東端は col 19 までで、そこから東はすべて海。南東へ向かって段々に細くなり、
//     東の海岸 (14,6)(16,6)(17,6) は離島へ向かう艦隊の通り道になる。
//
// 西の岬(row 9〜18。島が左側だけ南へ伸びて「[」の字を作る部分):
//   - 自軍の島は西側だけが盤面のなかほどより下まで細長く伸び、row 16〜18 でもう一度東へ折れる。
//     島全体を見ると、上の横棒が島の本体・縦棒が岬・下の横棒がその先端という「[」の字になる。
//   - 縦棒(col 0〜5、row 9〜15)には中立都市 2 個 (5,10)/(1,13) が col 3 の街道沿いに並び、
//     東へ折れる角に中立の研究所 (2,16) がある。研究所は中立のうちに占領し切った歩兵が
//     その場で新型戦車へ進化する拠点(docs/GameDesign.md「研究所」)。
//   - 下の横棒(row 16〜18)は縦棒より厚みのある 3 段で、col 11 まで東へ張り出す。
//     角の研究所から東へ折れた先の row 17 に中立都市 (5,17) と中立の空港 (8,17) が並び、
//     先端の下寄り (11,18) に中立の港がある。空港は自軍の陣地から遠い代わりに、
//     取れれば敵軍の本土の目と鼻の先で飛行ユニットを出せる前線の生産拠点になる。
//     自軍の陣地からは歩兵で中立都市 10〜19・研究所 19・空港 22・港 26 マス。
//   - 岬の東岸((7,9)(6,10〜12)(5,13〜15))は上から下まで一面の海岸で、下の横棒の南岸
//     (row 18 の col 0〜8)も海岸。輸送艦への積み込みも揚陸もどこからでもできる。
//   - 下の横棒の北面(row 16 の col 5〜11)は山の壁にしてある。山は装軌車両・装輪車両が
//     進入できず、海岸でもないので輸送艦を横付けして上陸することもできない。
//     先端へ地上から入る道は横棒(row 17〜18)を端まで歩く 1 本だけで、自軍の陣地からは
//     歩兵で 26・装軌車両で 28・装輪車両で 29 マスかかる。いっぽう飛行ユニットは山も海も
//     まっすぐ越えられて 12 マス。「岬をぐるっと回るか、空を飛んで近道するか」を選ばせる形。
//   - 先端の中立港 (11,18) から敵軍の島の西岸((16,19) の海岸)までは海 5 マス、
//     敵軍の港 (17,19) や北岸 (18,18) までは海 6 マスで、盤面最短の渡海地点になる。
//     ただし敵軍の港からも海路 7 マスなので、放っておけば敵軍に取られる前線でもある。
//   - 裏を返すと、敵軍から見ればいちばん近い攻め口でもある。岬の中立拠点 6 個は
//     取りに行く価値が高い反面、守りにくい前線でもある、という位置づけ。
//
// 東の離島(row 4〜6、col 22〜25):
//   - 盤面の右上に浮かぶ 8 マスの小島。自軍の島の東端(col 19)よりさらに東にあり、
//     建物は中立の研究所 2 個 (23,5)/(24,5) だけで、都市も港も空港も無い。
//     まわりはすべて海岸なので、輸送艦を横付けするか輸送ヘリで運ぶかしないと歩兵を上げられない。
//   - 海路は自軍の港から 14・敵軍の港から 19 と自軍のほうが近く、取れば新型戦車が
//     2 両ぶん手に入る。収入で劣る自軍が先に手を伸ばせる褒賞として置いてある。
//
// 南東の島(敵軍の本土。row 10〜24)と残る中立都市:
//   - 敵軍の陣地は島の西端(col 16〜24、row 19〜23)。本拠地 (19,21) を中心に
//     工場 3 個 (18,20)/(20,20)/(19,22)、空港 (21,21)、港 2 個 (17,19)/(16,22) が並ぶ。
//     どちらの港も岬と向かい合う西岸にあり、自軍の上陸ルートを真正面から受け止める位置にある。
//   - 敵軍の都市 8 個は陣地のまわり((18,19)(22,19)(23,20)(17,21)(24,21)(17,23)(19,23)(21,23))に
//     固まっており、開始時点で島の西半分はまるごと敵軍の勢力圏になっている。
//   - 島の右側は北へ長く伸びていて(row 10〜18、col 18〜27)、その細い腕の先端 (24〜27,10) は
//     盤面の上から 4 割ほどの高さまで届く。腕を縦に貫く街道(col 25)が本体の街道(row 22)と
//     つながる。
//   - 島に残っている中立都市 3 個((25,11)(24,13)(26,16))は、その腕にまとめて置いてある。
//     敵軍の陣地からは街道づたいに歩兵で 7〜11 マスあり、取り切るには数ターンかかる。
//     腕の北西岸は海岸((24,10)(24,11)(23,12)(23,13)(22,14)(22,15)(21,16)(20,17)(18,18)(19,18))が
//     続いていて、自軍の港からは海路 17〜20 マス。敵軍が腕を登り切る前に、艦隊で先回りして
//     横取りできるようにしてある。
//
// 先手番のハンデ:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、1 ターンぶん早く動ける先手(自軍)に対して
//   後手の敵軍を有利にしてある。このマップでは中立都市を数個足すのではなく、
//   拠点数そのものを 10 対 15(収入 10000 対 15000)と大きく傾けた。そのぶん自軍には
//   中立拠点 18 個ぶんの伸びしろを用意してあり、取り切れば収入は 28000 まで伸びる
//   (敵軍の伸びしろは島に残る中立都市 3 個ぶんで、取り切っても 18000)。
//   ハンデを増減させたいときは、敵軍の都市 8 個((18,19) など)を中立へ戻す/増やすで調整する。
//
// 盤面の縁について:
//   拠点(本拠地・工場・空港・港・都市・研究所)は盤面の端(row 0 / row 24 / col 0 / col 27)には
//   置かない。上端の row 0 と下端の row 24 は森と山の余白にしてある。
