//     まっすぐ越えられて 18 マス。「岬をぐるっと回るか、空を飛んで近道するか」を選ばせる形。
//   - 裏を返すと、敵軍から見ればいちばん近い攻め口でもある。岬の中立拠点 6 個は
//     取りに行く価値が高い反面、守りにくい前線でもある、という位置づけ。
//
// 東の離島(row 7〜9、col 22〜25):
//   - 盤面の右上寄りに浮かぶ 8 マスの小島。自軍の島の東端(col 19)よりさらに東にあり、
//     建物は中立の研究所 2 個 (23,8)/(24,8) だけで、都市も港も空港も無い。
//     まわりはすべて海岸なので、輸送艦を横付けするか輸送ヘリで運ぶかしないと歩兵を上げられない。
//   - 海路は自軍の港から 13・敵軍の港から 22 と自軍のほうがずっと近く、取れば新型戦車が
//     2 両ぶん手に入る。収入で劣る自軍が先に手を伸ばせる褒賞として置いてある。
//
// 南東の島(敵軍の本土。row 13〜24)と残る中立都市:
//   - 敵軍の陣地は島の西端(col 10〜18、row 19〜23)。本拠地 (13,21) を中心に
//     工場 3 個 (12,20)/(14,20)/(13,22)、空港 (15,21)、港 2 個 (11,19)/(10,22) が並ぶ。
//     どちらの港も岬と向かい合う西岸にあり、自軍の上陸ルートを真正面から受け止める位置にある。
//   - 敵軍の都市 8 個は陣地のまわり((12,19)(16,19)(17,20)(11,21)(18,21)(11,23)(13,23)(15,23))に
//     固まっており、開始時点で島の西半分はまるごと敵軍の勢力圏になっている。
//   - 島の右側は北へ長く伸びていて(row 13〜18、col 13〜27)、その細い腕の先端 (24〜27,13) は
//     盤面の上下のまんなかまで届く。腕を縦に貫く街道(col 25)が本体の街道(row 22)とつながる。
//   - 島に残っている中立都市 3 個((25,13)(24,15)(26,18))は、その腕にまとめて置いてある。
//     敵軍の陣地からは街道づたいに歩兵で 11〜15 マスあり、取り切るには数ターンかかる。
//     腕の北西岸は海岸((24,13)(23,14)(21,15)(19,16)(16,17))が続いていて、自軍の港からは
//     海路 16〜20 マス。敵軍が腕を登り切る前に、艦隊で先回りして横取りできるようにしてある。
//
// 先手番のハンデ:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、1 ターンぶん早く動ける先手(自軍)に対して
//   後手の敵軍を有利にしてある。このマップでは中立都市を数個足すのではなく、
//   拠点数そのものを 10 対 15(収入 10000 対 15000)と大きく傾けた。そのぶん自軍には
//   中立拠点 18 個ぶんの伸びしろを用意してあり、取り切れば収入は 28000 まで伸びる
//   (敵軍の伸びしろは島に残る中立都市 3 個ぶんで、取り切っても 18000)。
//   ハンデを増減させたいときは、敵軍の都市 8 個((12,19) など)を中立へ戻す/増やすで調整する。
//
