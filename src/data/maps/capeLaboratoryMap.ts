// 北西に先手の島・南東に後手の島が斜向かいに並ぶ 28x25(縦25・横28)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「拠点は少ないが伸びしろのある先手 vs 先に育ち切った後手」
//   - 北西の島(row 0〜21)が先手の自軍、南東の島(row 13〜24)が後手の敵軍の本土。
//     2 つの島は斜めに向かい合い、あいだを幅の広い海が斜めに走る。陸続きの経路は 1 本も無く、
//     相手の本土へ渡る手段は輸送艦での上陸作戦か、空港で作る飛行ユニットだけになる。
//   - 自軍は本拠地 1・工場 3・空港 1・港 2・都市 3 の 10 拠点(収入 10000)、
//     敵軍は本拠地 1・工場 3・空港 1・港 2・都市 8 の 15 拠点(収入 15000)で始まる。
//     開始時点の収入は敵軍が 1.5 倍だが、盤面に残る中立拠点 19 個のうち 16 個は自軍の島と
//     岬・離島にあり、敵軍の島に残っているのは中立都市 3 個だけ。
//     「先に育ち切った後手を、伸びしろのある先手が追い抜けるか」という組み立てになる。
//   - 初期資金は両軍とも 0(initialFunds)。1 ターン目に使えるのは収入ぶんだけなので、
//     自軍は 10000 G、敵軍は 15000 G から立ち上がる。
//
// 北西の島の本体(自軍の本土。row 0〜8)と両サイドの中立都市:
//   - 自軍の陣地は島の真ん中(col 9〜13、row 1〜3)にまとまっている。
//     本拠地 (11,2) の左右に工場 (10,2)/(12,2)、その下にもう 1 つの工場 (11,3)、
//     真上に空港 (11,1)、両隣に自軍の都市 (9,2)/(13,2) を置き、
//     街道へ降りたところにもう 1 個の都市 (11,6) がある。
//   - 中立都市 10 個は陣地を挟んで西側 5 個((6,1)(2,2)(8,3)(1,4)(5,6))と
//     東側 5 個((16,1)(18,2)(14,3)(17,4)(15,6))にきれいに分かれている。
//     どちらへ先に歩兵を送るかで、そのあとの戦線の重心が決まる。
//   - 島を東西に貫く街道(row 5)が両サイドの中立都市と陣地を結び、そこから
//     col 11 の枝道が陣地へ、col 3 の枝道が南の岬へ降りる。
//   - 島の東端は col 19 までで、そこから東はすべて海。南東へ向かって段々に細くなり、
//     南岸の海岸((14,6)(16,6)・(10,7)(12,7)(13,7)・(7〜9,8))が
//     輸送艦への積み込みと揚陸に使える。港は (17,6) と (11,7) の 2 つ。
//
// 西の岬(row 9〜21。島が左側だけ南へ長く伸びた部分):
//   - 自軍の島は西側だけが盤面の下端近くまで細長く伸びており、その岬に中立の研究所 1 個 (2,16) と
//     中立都市 3 個((5,10)(1,13)(4,19))が点在する。研究所は中立のうちに占領し切った歩兵が
//     その場で新型戦車へ進化する拠点(docs/GameDesign.md「研究所」)。
//     col 3 の街道が岬を縦に貫いていて、陣地から歩いて降りられる。
//   - 岬の東岸(col 5〜7)は上から下まで一面の海岸で、先端(row 21)も海岸。
//     輸送艦への積み込みも揚陸もどこからでもできる。
//   - そしてこの東岸から東を見ると、海を 5 マスぶん(岸から岸まで 6 マス)隔てただけの近さに
//     敵軍の本土の西岸がある。盤面でいちばん狭い渡海地点であり、しかもその対岸は
//     敵軍の陣地そのもの。自軍の上陸作戦はここが起点になる。
//   - 裏を返すと、敵軍から見ればいちばん近い攻め口でもある。岬の中立拠点 4 個は
//     取りに行く価値が高い反面、守りにくい前線でもある、という位置づけ。
//
// 東の離島(row 7〜9、col 22〜25):
//   - 盤面の右上寄りに浮かぶ 8 マスの小島。自軍の島の東端(col 19)よりさらに東にあり、
//     建物は中立の研究所 2 個 (23,8)/(24,8) だけで、都市も港も空港も無い。
//     まわりはすべて海岸なので、輸送艦を横付けするか輸送ヘリで運ぶかしないと歩兵を上げられない。
//   - 海路は自軍の港からのほうがずっと近く、取れば新型戦車が 2 両ぶん手に入る。
//     収入で劣る自軍が先に手を伸ばせる褒賞として置いてある。
//
// 南東の島(敵軍の本土。row 13〜24)と残る中立都市:
//   - 敵軍の陣地は島の西端(col 10〜18、row 19〜23)。本拠地 (13,21) を中心に
//     工場 3 個 (12,20)/(14,20)/(13,22)、空港 (15,21)、港 2 個 (11,19)/(10,22) が並ぶ。
//     どちらの港も岬と向かい合う西岸にあり、自軍の上陸ルートを真正面から受け止める位置にある。
//   - 敵軍の都市 8 個は陣地のまわり((12,19)(16,19)(17,20)(11,21)(18,21)(11,23)(13,23)(15,23))に
//     固まっており、開始時点で島の西半分はまるごと敵軍の勢力圏になっている。
//   - 島の右側は北へ長く伸びていて(row 13〜18、col 13〜27)、その細い腕の先端 (24〜27,13) は
//     盤面の上下のまんなかまで届く。腕を縦に貫く街道(col 25)が本体の街道(row 22)とつながる。
//   - 島に残っている中立都市 3 個((25,13)(24,15)(26,18))は、その腕にまとめて置いてある。
//     敵軍の陣地からは街道づたいに歩兵で 11〜15 マスあり、取り切るには数ターンかかる。
//     腕の北西岸は海岸((24,13)(23,14)(21,15)(19,16)(16,17))が続いていて、自軍の港からは
//     海路 12〜14 マス。敵軍が腕を登り切る前に、艦隊で先回りして横取りできるようにしてある。
//
// 先手番のハンデ:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、1 ターンぶん早く動ける先手(自軍)に対して
//   後手の敵軍を有利にしてある。このマップでは中立都市を数個足すのではなく、
//   拠点数そのものを 10 対 15(収入 10000 対 15000)と大きく傾けた。そのぶん自軍には
//   中立拠点 16 個ぶんの伸びしろを用意してあり、取り切れば収入は 26000 まで伸びる
//   (敵軍の伸びしろは島に残る中立都市 3 個ぶんで、取り切っても 18000)。
//   ハンデを増減させたいときは、敵軍の都市 8 個((12,19) など)を中立へ戻す/増やすで調整する。
//
// 盤面の縁について:
//   拠点(本拠地・工場・空港・港・都市・研究所)は盤面の端(row 0 / row 24 / col 0 / col 27)には
//   置かない。上端の row 0 と下端の row 24 は森と山の余白にしてある。
//
// 初期ユニットは 0。両軍とも 1 ターン目に陣地の生産拠点でユニットを生産して立ち上げる。

