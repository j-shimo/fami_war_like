// 海を隔てて南北に大きな島が 2 つ並ぶ 28x25(縦25・横28)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「拠点は少ないが伸びしろのある先手 vs 先に育ち切った後手」
//   - 北の島(row 0〜8)が先手の自軍、南の島(row 18〜24)が後手の敵軍の本土で、
//     あいだは幅の広い海(row 13〜17)。陸続きの経路は 1 本も無く、相手の本土へ渡る手段は
//     輸送艦での上陸作戦か、空港で作る飛行ユニットだけになる。
//   - 自軍は本拠地 1・工場 3・空港 1・港 2・都市 3 の 10 拠点(収入 10000)、
//     敵軍は本拠地 1・工場 3・空港 1・港 2・都市 8 の 15 拠点(収入 15000)で始まる。
//     開始時点の収入は敵軍が 1.5 倍だが、盤面に残る中立拠点 19 個のうち 16 個は自軍の島と
//     岬・離島にあり、敵軍の島に残っているのは島の東寄りの中立都市 3 個だけ。
//     「先に育ち切った後手を、伸びしろのある先手が追い抜けるか」という組み立てになる。
//   - 初期資金は両軍とも 0(initialFunds)。1 ターン目に使えるのは収入ぶんだけなので、
//     自軍は 10000 G、敵軍は 15000 G から立ち上がる。
//
// 北の島(自軍の本土。row 0〜8)と両サイドの中立都市:
//   - 自軍の陣地は島の真ん中(col 12〜16、row 1〜3)にまとまっている。
//     本拠地 (14,2) の左右に工場 (13,2)/(15,2)、その下にもう 1 つの工場 (14,3)、
//     真上に空港 (14,1)、両隣に自軍の都市 (12,2)/(16,2) を置き、
//     街道へ降りたところにもう 1 個の都市 (14,6) がある。
//   - 中立都市 10 個は陣地を挟んで西側 5 個((6,1)(2,2)(8,3)(1,4)(5,6))と
//     東側 5 個((21,1)(25,2)(19,3)(23,4)(20,6))にきれいに分かれている。
//     どちらへ先に歩兵を送るかで、そのあとの戦線の重心が決まる。
//   - 島を東西に貫く街道(row 5)が両サイドの中立都市と陣地を結び、そこから
//     col 11 の枝道が港 (11,7) へ、街道の真下が港 (17,6) へ、col 3 の枝道が岬へ降りる。
//   - 島は南へ向かって段々に細くなり、南岸の海岸(row 6〜8 の (18,6)(21,6)(22,6)・
//     (12〜15,7)・(7〜9,8))が輸送艦への積み込みと揚陸に使える。
//
// 西の岬(row 9〜12。島が左側だけ南へ伸びた部分):
//   - 自軍の島は西側だけが南へ細長く伸びており、その岬に中立の研究所 1 個 (2,10) と
//     中立都市 3 個((1,9)(5,10)(4,11))がある。研究所は中立のうちに占領し切った歩兵が
//     その場で新型戦車へ進化する拠点(docs/GameDesign.md「研究所」)。
//   - 岬の先端(row 12)は一面の海岸で、輸送艦への積み込みも揚陸もできる。
//     ここから南を見ると、海を 5 マスぶん(岸から岸まで 6 マス)隔てただけの近さに
//     敵軍の本土の北岸がある。盤面でいちばん狭い渡海地点であり、
//     しかもその対岸は敵軍の陣地そのもの。自軍の上陸作戦はここが起点になる。
//   - 裏を返すと、敵軍から見ればいちばん近い攻め口でもある。岬の中立拠点 4 個は
//     取りに行く価値が高い反面、守りにくい前線でもある、という位置づけ。
//
// 東の離島(row 10〜12、col 23〜26):
//   - 盤面の右側、上下の中央よりやや上に浮かぶ 8 マスの小島。建物は中立の研究所 2 個
//     (24,11)/(25,11) だけで、都市も港も空港も無い。まわりはすべて海岸なので、
//     輸送艦を横付けするか輸送ヘリで運ぶかしないと歩兵を上げられない。
//   - 海路は自軍の港からのほうがずっと近く、取れば新型戦車が 2 両ぶん手に入る。
//     収入で劣る自軍が先に手を伸ばせる褒賞として置いてある。
//
// 南の島(敵軍の本土。row 18〜24)と残る中立都市:
//   - 敵軍の陣地は島の左(西)の海岸側(col 2〜8、row 18〜23)。本拠地 (4,21) を中心に
//     工場 3 個 (3,20)/(5,20)/(4,22)、空港 (6,21)、港 2 個 (4,18)/(2,20) が並ぶ。
//     港 (4,18) は岬と向かい合う北岸に、港 (2,20) は西岸にあり、どちらも
//     自軍の上陸ルートを真正面から受け止める位置にある。
//   - 敵軍の都市 8 個は陣地のまわり((2,19)(6,19)(7,20)(8,21)(2,22)(3,23)(5,23)(7,23))に
//     固まっており、開始時点で島の西半分はまるごと敵軍の勢力圏になっている。
//   - 島に残っている中立都市は東寄りの 3 個((21,19)(24,21)(22,23))だけ。
//     敵軍の陣地からは島を横断する街道(row 22)づたいに歩兵で 15〜16 マスあり、
//     敵軍がここを取り切るには数ターンかかる。自軍が艦隊で先回りして
//     東から食い込むこともできる、という含みを持たせてある。
//
// 先手番のハンデ:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、1 ターンぶん早く動ける先手(自軍)に対して
//   後手の敵軍を有利にしてある。このマップでは中立都市を数個足すのではなく、
//   拠点数そのものを 10 対 15(収入 10000 対 15000)と大きく傾けた。そのぶん自軍には
//   中立拠点 16 個ぶんの伸びしろを用意してあり、取り切れば収入は 26000 まで伸びる
//   (敵軍の伸びしろは島に残る中立都市 3 個ぶんで、取り切っても 18000)。
//   ハンデを増減させたいときは、敵軍の都市 8 個((2,19) など)を中立へ戻す/増やすで調整する。
//
// 盤面の縁について:
//   拠点(本拠地・工場・空港・港・都市・研究所)は盤面の端(row 0 / row 24 / col 0 / col 27)には
//   置かない。上端の row 0 と下端の row 24 は森と山の余白にしてある。
