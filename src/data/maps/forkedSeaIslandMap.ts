// Y 字の海が通る 1 つの大きな島で 4 つの軍勢が戦う 30x26(横30・縦26)の 4P マップ。
// 4Pマップ区分(group: 'four')の 2 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「Y 字の海で島を 3 つに割り、1P は最も不利・4P は最も有利な非対称の陣取り」
//   1P(青)は左上・2P(赤)は右上・3P(緑)は左下・4P(黄)は右下に陣取り、
//   手番は 1P → 2P → 3P → 4P の順に回る。初期の拠点の数から差をつけてある。
//     - 1P: 本拠地 1 + 工場 3 + 空港 2 = 収入 6000(いちばん少ない)
//     - 2P・3P: 本拠地 1 + 工場 4 + 空港 2 = 収入 7000
//     - 4P: 本拠地 1 + 工場 4 + 空港 2 + 都市 4 = 収入 11000(いちばん多い)
//   初期資金は 4 軍とも 0 で、初期ユニットは置かない。
//
// Y 字の海(幅はどこも 2〜3 マス):
//   島の外周は幅 1 マスの海。島を 3 つに割る Y 字の海峡が通っており、
//   3 つの先端はそれぞれ外周の海へつながる。
//     - 上の腕: 上辺の真ん中より左 (9〜11,1) から、右下へ斜めに下って合流点 (13〜14,11〜12) へ
//     - 右の腕: 合流点から右へ、少しずつ上りながら右辺の上寄り (26〜28,8〜10) へ
//     - 下の軸: 合流点から、少しずつ左へ寄りながら下辺の真ん中より左 (10〜12,24) へ
//   この海で陸は 3 つに分かれる。
//     - 西の陸(上の腕と下の軸の西): 1P と 3P が同じ陸に同居する。1P は南の 3P と地続きで、
//       東の 2P の陸とは上の腕の橋 1 本で向き合う
//     - 北東の陸(上の腕と右の腕の間): 2P だけの陸
//     - 南東の陸(右の腕と下の軸の間): 4P だけの陸で、3 つの陸でいちばん広い
//   港は無いので海上ユニットは作れず、海を越えるのは道路の橋か飛行ユニットだけ。
//
// 道路(「日」の字と、2P の「口」の字):
//   4 軍の陣地を「日」の字の道路が結ぶ。「日」の枠は col 4〜25・row 6〜21 で、
//   上の線 row 6・真ん中の線 row 14・下の線 row 21・左の縦線 col 4・右の縦線 col 25。
//   ただし「日」の右上の部分は抜いてあり、代わりに 2P の「口」の字の道路を置く。
//   - 1P: 本拠地 (4,2) から道路がやや下 (4,3〜5) へ伸びてから、「日」の左上の角 (4,6) へ合流する
//   - 2P: 「口」の字の道路(col 18〜25・row 2〜14)の右上の角 (25,2) が本拠地。
//     「口」の左辺 col 18 は真ん中の線の研究所 (16,14) の少し右 (18,14) へつながり、
//     下辺は真ん中の線・右辺は右の縦線と重なる。上の線は「口」の左辺 (18,6) で終わる
//   - 3P: 本拠地 (4,22) が「日」の左下の角 (4,21) のすぐ下
//   - 4P: 本拠地 (25,22) が「日」の右下の角 (25,21) のすぐ下
//   海を渡るところは道路がそのまま橋になる(橋は 5 本で、どれも長さ 2 マス)。
//     - 上の線 (10〜11,6) で上の腕を渡る(1P〜2P)
//     - 「口」の左辺 (18,10〜11) と右辺 (25,9〜10) で右の腕を渡る(2P〜4P)
//     - 真ん中の線 (13〜14,14) と下の線 (11〜12,21) で下の軸を渡る(3P〜4P。真ん中の線は 1P〜4P も)
//
// 陣地:
//   - 1P(左上): 本拠地 (4,2) / 工場 (4,1)(3,2)(5,2) / 空港 (2,2)(6,2)
//   - 2P(右上。「口」の右上の角): 本拠地 (25,2) / 工場 (25,1)(26,2)(24,3)(26,3) / 空港 (24,1)(26,1)
//   - 3P(左下): 本拠地 (4,22) / 工場 (3,22)(5,22)(3,23)(5,23) / 空港 (2,22)(6,22)
//   - 4P(右下): 本拠地 (25,22) / 工場 (24,22)(26,22)(24,23)(26,23) / 空港 (23,22)(27,22) /
//     都市 (26,19)(26,20)(21,22)(22,22)
//   4Pモードで「なし」を選んだ軍勢の陣地は、本拠地が中立の都市に・ほかの拠点が中立になる
//   (src/data/maps/armySlots.ts)。
//
// 地形:
//   道路・拠点のほかは森がいちばん多く、平地と山を混ぜてある。
//   4P の陣地のまわり(南東の陸の南半分)は山地帯で、山の多くが 4P の陣地の近くに集まる。
//   装軌・装輪車両は山を越えられないため、4P の陣地へ車両で攻め込むには道路を通るしかない。
//
// 研究所(中立 2 個。中立のうちに占領し切った歩兵は新型戦車へ進化する):
//   - 上の研究所 (12,6): 「日」の上の線の真ん中。上の腕の橋を東へ渡ったすぐ先で、2P の陸にある。
//     歩兵の移動コストは 1P 11・2P 15 で、最速で向かえば 1P が 1 ターン早く辿り着く
//   - 下の研究所 (16,14): 「日」の真ん中の線の真ん中あたり。下の軸の橋を東へ渡ったすぐ先で、
//     4P の陸にある(歩兵の移動コストは 1P 23・2P 19・3P 19・4P 16)
//
// 中立空港(上・中・下に 1 個ずつ。道路沿いとは限らない):
//   - 上 (14,4): 上の研究所のやや右上(1P 15・2P 11・3P 27・4P 29)
//   - 中 (16,13): 下の研究所のすぐ上(1P 24・2P 18・3P 20・4P 17)
//   - 下 (14,22): 下の線の橋のやや右下(1P 29・2P 29・3P 11・4P 12)
//
// 中立都市 29 個(かっこ内は 1P / 2P / 3P / 4P の最寄りの工場・本拠地からの歩兵の移動コスト):
//   中立都市はどれも道路沿い(道路に隣り合うマス)にあり、1 個か、2 個が隣り合った塊で置いてある。
//   歩兵の移動力は 3 なので、コスト 3 までが 1 ターン・6 までが 2 ターンで届く。
//   手番の遅い 2P・4P は陣地のすぐ隣の都市 2 個へ 1 ターンで届き、1P・3P の近くの都市は
//   2 ターンの距離にある(docs/GameDesign.md「先手番のハンデ」)。
//     - 1P の近く(3 個とも 2 ターン): (3,6)(4/24/16/37)・(3,7)(5/25/15/36)・(7,5)(5/21/19/34)
//     - 2P の近く: (26,5)(26/2/38/18)・(26,6)(26/3/37/17) は 1 ターン、
//       (20,3)(22/4/34/24)・(19,3)(21/5/33/25) は 2 ターン
//     - 3P の近く(4 個とも 2 ターン): (3,18)(16/36/4/25)・(3,17)(15/35/5/26)・
//       (7,20)(20/34/4/19)・(8,20)(21/33/5/18)
//     - 4P の近く: (24,20)(37/19/21/2)・(24,19)(38/18/22/3) は 1 ターン、
//       (22,20)(35/21/19/4)・(21,20)(34/22/18/5) は 2 ターン
//     - 西の陸の真ん中: (5,10)(8/26/12/31)・(5,11)(9/27/11/30) は 1P が、
//       (10,15)(18/26/12/21)・(11,15)(19/25/13/20) は 3P が近い
//     - 北東の陸の上の線沿い: (16,7)(16/12/28/24)・(17,7)(17/11/29/23) は 2P が近い
//     - 南東の陸の北(右の腕の南): (26,12)(31/11/31/11) は 2P と 4P が同じ、(26,13)(32/12/30/10) は 4P が近い
//     - 南東の陸の真ん中の線沿い: (18,15)(26/18/20/15)・(19,15)(27/19/21/15)・
//       (21,15)(29/17/24/13)・(22,15)(30/16/25/12) は 4P が近い
//     - 南東の陸の下の線沿い: (16,22)(31/27/13/10)・(17,22)(32/26/14/9) は 4P が近い
//   最寄りの中立都市の数は 1P 5 個・2P 7 個(4P と同じ距離の 1 個を含む)・3P 6 個・4P 12 個
//   (同じ距離の 1 個を含む)。
//
// 陣地から陣地までの距離(工場・本拠地から相手の本拠地まで。歩兵 / 装軌 / 装輪):
//   1P〜2P 27 / 29 / 29、1P〜3P 20 / 20 / 20、2P〜4P 20 / 20 / 20、3P〜4P 22 / 22 / 22。
//   対角の 1P〜4P は 40・2P〜3P は 39 と遠い。

