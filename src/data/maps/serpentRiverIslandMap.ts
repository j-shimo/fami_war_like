// 1 つの大きな島を、北から東へ回り込んで南へ抜ける川が東西に分ける 38x28(横38・縦28)の激ムズマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
// 区分は extra(激ムズマップ)・マップ区分は new(新マップ)で、
// 2P側で「新マップ」の通常マップをすべてクリアするまで選択画面に出さない。
// 2P側専用のマップ(side: '2p')で、1P側の激ムズマップは鉄河列島マップ(ironRiverIslandsMap)。
// 詳細は docs/GameDesign.md「クリア状況と激ムズマップ」を参照。
//
// ★ このファイルの player / enemy の読み方(重要)
//   2P側は盤面の自軍・敵軍を入れ替えて遊ぶ(src/data/maps/sideSwap.ts の swapMapSides)。
//   このマップは 2P側にしか出さないため、必ず入れ替えられた状態で遊ぶことになる。
//   そのため、このファイルの定義と実際の担当は次のように逆になる。
//     - 定義上の 'enemy'  → 遊ぶ人の自軍(左下の陣地)。後手番
//     - 定義上の 'player' → CPU が動かす敵軍(右上の陣地)。先手番
//   以下のコメントでは、遊ぶ人から見た呼び方(自軍 = 左下、敵軍 = 右上)で説明する。
//
// 設計コンセプト:「くねる 3 本の街道と 3 つの橋で、蛇行する川を越えて攻め上がる」
//   鉄河列島マップ(1P側)は海で割れた 4 つの島だったが、こちらは港の無い 1 つの大きな島。
//   海を渡る手段が要らないかわりに、島の真ん中を川が北から南まで切っており、
//   装輪車両(ロケット砲など)が川を越えられるのは街道の 3 つの橋だけになる。
//   自軍は陣地 7 拠点(収入 7000 G)・初期部隊 0・初期資金 0 の裸一貫で、しかも後手。
//   敵軍は陣地 11 拠点(収入 11000 G)に加えて戦闘機・爆撃機 2・中戦車・ロケット砲・対空戦車を
//   配置済みで、盤面で唯一の駅を持つので列車砲も敵軍しか作れない。
//
// 川(北岸 (18,1) → 南岸 (22,26)):
//   北岸から col 18 を南へ下り、(19,4)〜(23,8) の階段で東へ回り込んでから、
//   col 22〜23 を南岸までまっすぐ下る。幅 1 マスで、海上ユニットはいない(港が無い)ので
//   純粋に陸を分ける壁として働く。歩兵(コスト 2)・装軌車両(コスト 3)は渡れるが、
//   装輪車両は渡れない。川の上に街道が通る 3 マスが橋(道路)になる。
//     - 北の橋 (18,2): 北ルート
//     - 中央の橋 (23,12): 中央ルート
//     - 南の橋 (23,21): 下ルート
//
// 街道(自軍の本拠地 (4,23) から):
//   - 北ルート: 本拠地から西の端 (col 3〜6) をくねりながら北上し、島の北を回って
//     北の橋を渡り、敵軍の本拠地 (32,4) へ西から入る。
//   - 中央の幹: 本拠地から少しだけ東 (8,23) へ進んでから北へ向かい、
//     (9,21)・(11,18)・(13,16) と右へずれながら上がって、中央の T 字路 (15,13) に着く。
//     T 字路の西の腕は (12,13)→(9,12)→(6,11) で北ルートへ合流する。
//   - T 字路の東の腕は少し東へ進んだ (19,13) で 2 本に分かれる。
//     * 中央ルート: 中央の橋 (23,12) で川を渡り、(26,11)・(29,12)・(31,9) と折れながら
//       東へ進み、col 32 を北上して敵軍の本拠地へ南から入る。
//     * 下ルート: 南東へ下って南の橋 (23,21) で川を渡り、row 20〜21 を東へ波打ちながら進み、
//       東の端 (col 33〜34) を北上して (32,12) で中央ルートへ合流する。
//   どのルートも直線を避け、1〜4 マスごとに折れ曲がるくねくね道にしてある。
//   陣地から陣地までの移動コストは歩兵 47・装軌車両 48・装輪車両 50 で、ほぼ変わらない。
//
// 敵軍の駅と線路:
//   駅 (31,6) は盤面でただ 1 つの駅で、敵軍の陣地の一部として開始時から敵軍のもの。
//   線路は駅から西へ伸び、(28,7)・(26,8) と南西へ下って川の東岸 (25,10) で終わる
//   (駅から南端まで軌道コスト 10 = 移動力 15 の列車砲で 1 ターン)。
//   線路の南端から中央の橋 (23,12) までは 4 マスで、列車砲(射程 2〜6)は
//   橋を渡ってくる部隊を線路の上から撃てる。自軍が駅を奪わない限り、列車砲を作れるのは敵軍だけ。
//
// 両軍の陣地:
//   - 自軍(左下・定義上 enemy): 本拠地 (4,23)・工場 4((3,22)/(5,22)/(3,24)/(5,24))・
//     空港 2((2,21)/(7,25))の 7 拠点。都市は 1 個も持たない。
//   - 敵軍(右上・定義上 player): 本拠地 (32,4)・工場 3((31,3)/(33,3)/(33,5))・駅 (31,6)・
//     空港 2((29,2)/(35,6))・都市 4((34,2)/(27,4)/(30,8)/(34,8))の 11 拠点。
//
// 中立都市 45 個:
//   川の西に 25 個・東に 20 個。歩兵で先に届くのは自軍 23 個・敵軍 22 個とほぼ五分だが、
//   敵軍は先手で、しかも初期部隊が前へ出てくる。すべて取れても自軍は 7 + 23 = 30 拠点、
//   敵軍は 11 + 22 = 33 拠点で、収入でも敵軍が上回る。
//
// 敵軍の初期部隊(合計 99000 G ぶん):
//   - 戦闘機 1 は空港 (29,2)、爆撃機 2 は空港 (35,6) と本拠地の東 (34,4)。
//   - 中戦車 1 は中央の橋の東のたもと (24,13) で橋を押さえる。
//   - ロケット砲 1(射程 3〜5)は中央ルートの (27,11) に据え、中央の橋 (23,12) を射程に収める。
//   - 対空戦車 1 は陣地の南の街道 (32,7) で、輸送ヘリや攻撃機の急襲に備える。
//   自軍の初期部隊は 0。初期資金も 0 なので、1 ターン目は収入 7000 G で歩兵を並べるところから始まる。
//
// 勝ち筋(このマップの想定):
//   1. 川の西の 25 都市を歩兵で素早く取る(北ルート沿い・中央の幹沿い・南岸沿いの 3 方向)。
//   2. 爆撃機 2 機が来る前に対空戦車・戦闘機を用意する。空港 2 つを最初から持っているのが救い。
//   3. 中央の橋は列車砲とロケット砲の射程に入っているので、北の橋・南の橋から攻め上がるか、
//      歩兵と装軌車両で橋の無い場所の川を渡って回り込む。
//
// 難易度を調整したいときは、敵軍の初期部隊から爆撃機を 1 機外す、または
// 敵軍の都市 4 個を中立へ戻す。逆に難しくしたいなら、敵軍の初期資金を増やす。

