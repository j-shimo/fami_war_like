// 勝ち筋(このマップの想定):
//   1. 川の西の 25 都市を歩兵で素早く取る(北ルート沿い・中央の幹沿い・南岸沿いの 3 方向)。
//      ただし島の北西には西の駅の前線部隊が陣取っているので、北ルート沿いは取り合いになる。
//   2. 爆撃機 2 機・戦闘ヘリが来る前に対空戦車・戦闘機を用意する。空港 2 つを最初から持っているのが救い。
//   3. 中央の橋は列車砲とロケット砲の射程に入っているので、北の橋・南の橋から攻め上がるか、
//      歩兵で橋の無い場所の川を渡って回り込む。
