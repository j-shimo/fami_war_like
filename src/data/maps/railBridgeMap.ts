// 漢字の「山」の字の形をした陸地を、盤面最上段の線路が一直線に横切る 23x16(縦16・横23)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「線路を渡すか、大きく南へ回るか」
//   - 陸地は「山」の字の両端を上まで伸ばした形をしている。左の縦棒(col 0〜4)が先手の自軍、
//     右の縦棒(col 18〜22)が後手の敵軍の陣地で、どちらも盤面の上端から南岸まで縦に伸びる。
//     中央の縦棒(col 9〜13)は 1 マスぶん背が低く(row 1 から)、3 本の縦棒は
//     南岸の陸地(row 12〜15)でひとつにつながる。
//   - 縦棒のあいだの 2 つの入江(col 5〜8 と col 14〜17、row 1〜11)は海で、
//     地上ユニットはここを渡れない。つまり地上の移動路は、
//     「最上段の線路をまっすぐ渡る」か「南岸までぐるっと回り込む」かの 2 つだけになる。
//   - 線路は最上段(row 0)を一直線に貫き、自軍の駅 (4,0) → 中立の駅 (11,0) → 敵軍の駅 (18,0) を
//     結ぶ。入江の上は鉄橋として渡っており、幅 1 マスの隘路になる。
//     自軍の陣地から敵軍本拠地までは、線路づたいなら歩兵で移動コスト 16(6 ターン)、
//     南岸を回ると 42(14 ターン)。中立駅までは線路で 7(3 ターン)・南岸回りで 34(12 ターン)と、
//     4 倍以上の開きがある。
//   - 線路の上は装軌車両がコスト 2・装輪車両がコスト 4 と重く、敵本拠地までの距離は
//     装軌車両で 28(南岸回りは 43)、装輪車両にいたっては 43 とどちらを通っても変わらない。
//     鉄橋を渡って先陣を切るのは歩兵と列車砲になる。列車砲(移動力 15・軌道コスト 1)は自軍の駅から中立駅まで 1 ターンで
//     届き、射程 2〜6 で鉄橋と中央の陸地を丸ごと射程に収める。線路を押さえた側が
//     盤面の中央を制圧する、というのがこのマップの核になるルール。
//
// 両軍の初期拠点(本拠地 1・工場 3・駅 1・港 1 の計 6 拠点・収入 6000):
//   - 上端に本拠地 (2,0)/(20,0) と工場 3 つを固め、陣地の内側の端に駅、その 1 つ下に港を置く。
//     駅は線路の起点、港は入江に面しており、陸・鉄・海の 3 つの出口が陣地に並ぶ形になる。
//   - 空港は置いていない。飛行ユニットの出ないマップなので、入江も鉄橋も迂回できず、
//     地上・鉄道・海上の 3 つの移動タイプだけで戦線を組み立てることになる。
//
// 中央の陸地(中立駅の高台)と川:
//   - 中立の駅 (11,0) のまわり(col 9〜13、row 1〜3)は森と中立都市 3 個((10,1)(12,1)(11,2))の
//     高台になっている。線路で 3 ターンの距離にあり、取れば列車砲の修理拠点が前線に持てるうえ、
//     相手の列車砲の再生産も止められる、このマップ最大の争点。
//   - 高台の南端(row 4)は幅 1 マスの川で、渡ると下の陸地(row 5〜11 の中央の縦棒)につながる。
//     歩兵はコスト 2・装軌車両はコスト 3 で渡れるが、装輪車両は渡れない
//     (偵察車・ロケット砲が高台へ上がるには、輸送艦で海岸 (9,3)/(13,3) へ揚陸するしかない。
//     海岸の隣は平地にしてあるので、揚陸した装輪車両が浜辺で立ち往生することはない)。
//   - 川は中央の陸地を横断して左右の入江をつないでおり、海上ユニットはここを遡上できる。
//     自軍の港から敵軍の港までの海路(移動コスト 20)は必ずこの川を通るので、
//     川は「陸の切れ目」であると同時に「艦隊の関所」にもなる。高台を占領した側は、
//     川を通る敵の艦隊を上から叩けるという関係になっている。
//
// 南岸(row 12〜15)と中立拠点:
//   - 南岸には端から端まで街道(row 13)が通り、両軍の陣地からは col 2 / col 20 の街道が
//     南北に降りてくる。中央の縦棒にも col 11 の街道があり、南岸から川の手前まで上がれる。
//     車両で回り込むならこの街道づたいが最短になる。
//   - 中立拠点は 24 個(中立都市 21・中立港 2・中立駅 1)。中立港 (9,8)/(13,8) は中央の縦棒の
//     両岸にあり、取れば入江の真ん中で艦隊を生産・修理できる。
//     海岸は入江のふちに 10 マス置いてあり、港が無くても揚陸・乗船ができる。
//
// 先手番ハンデの調整:
//   1 ターンぶん早く動ける先手(自軍)は中立駅にも先に着けるため、docs/GameDesign.md
//   「先手番のハンデ」の方針に従い、後手の敵軍陣地の隣にだけ中立都市を 2 個((19,2) と (22,2))
//   多く置いてある。どちらも敵軍が 1 ターンで届く位置(移動コスト 3)で、
//   自軍側の左右対称の位置((3,2) と (0,2))は平地のままにしてある。
//   これがこのマップ唯一の非対称点で、ハンデを増減させたいときはこの 2 マスで調整する。
//
// 上記のハンデ 2 マスを除けば、盤面は中央の col 11 を軸に左右対称で、地形・拠点の配置は
// 自軍・敵軍で等しい。初期ユニットは 0。初期資金 8000 は歩兵と偵察車で中立駅へ走るための資金で、
// 列車砲(30000)は収入を伸ばしながら数ターンかけて貯める設計にしている。

