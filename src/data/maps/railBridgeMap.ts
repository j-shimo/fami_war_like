// 漢字の「山」の字の形をした陸地を、盤面上端(row 1)の線路が一直線に横切る 29x17(縦17・横29)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「線路を渡すか、大きく南へ回るか」
//   - 陸地は「山」の字の両端を上まで伸ばした形をしている。左の縦棒(col 0〜5)が先手の自軍、
//     右の縦棒(col 23〜28)が後手の敵軍の陣地で、どちらも盤面の上端から南岸まで縦に伸びる。
//     中央の縦棒(col 12〜16)も上端まで伸びており、3 本の縦棒は
//     南岸の陸地(row 13〜16)でひとつにつながる。
//   - 縦棒のあいだの 2 つの入江(col 6〜11 と col 17〜22、row 0〜12)は海で、
//     地上ユニットはここを渡れない。つまり地上の移動路は、
//     「線路をまっすぐ渡る」か「南岸までぐるっと回り込む」かの 2 つだけになる。
//   - 線路は row 1 を一直線に貫き、自軍の駅 (5,1) → 中立の駅 (14,1) → 敵軍の駅 (23,1) を
//     結ぶ。入江の上は幅 6 マスの鉄橋として渡っており、幅 1 マスの隘路になる。
//     自軍の陣地から敵軍本拠地までは、線路づたいなら歩兵で移動コスト 20(7 ターン)、
//     南岸を回ると 46(16 ターン)。中立駅までは線路で 9(3 ターン)・南岸回りで 36(12 ターン)と、
//     4 倍の開きがある。
//   - 線路の上は装軌車両がコスト 2・装輪車両がコスト 4 と重く、敵本拠地までの距離は
//     装軌車両で 36(南岸回りは 47)、装輪車両にいたっては 47 とどちらを通っても変わらない。
//     鉄橋を渡って先陣を切るのは歩兵と列車砲になる。
//   - 列車砲(移動力 15・軌道コスト 1)は自軍の駅から中立駅(距離 9)までなら 1 ターンで届くが、
//     敵軍の駅までは 18 あって 1 ターンでは届かない。射程 2〜6 と合わせると、
//     「中立駅まで走って止まる → 次のターンから鉄橋と中央の陸地を撃つ」という
//     2 段構えの運用になり、線路を押さえた側が盤面の中央を制圧する。
//     線路を伸ばすほど列車砲の機動力が効くので、盤面は横に長く取ってある。
//
// 盤面の縁について:
//   - 拠点(本拠地・工場・駅・港・都市・研究所)は盤面の端(row 0 / row 16 / col 0 / col 28)には
//     置かない。上端の row 0 は森と山、下端の row 16 は山と森、左右の端の col 0 / col 28 は
//     平地と森の余白にしてあり、拠点はすべて 1 マス以上内側に入っている。
//   - 上端 (14,0) の山は中立駅の真上にある物見の山で、駅を取った側が視界を伸ばせる。
//
// 両軍の初期拠点(本拠地 1・工場 3・駅 1・港 1 の計 6 拠点・収入 6000):
//   - 線路の走る row 1 に本拠地 (3,1)/(25,1) と工場を並べ、陣地の内側の端に駅、
//     その 1 つ下に港と 3 つめの工場を置く。
//     駅は線路の起点、港は入江に面しており、陸・鉄・海の 3 つの出口が陣地に並ぶ形になる。
//   - 空港は置いていない。飛行ユニットの出ないマップなので、入江も鉄橋も迂回できず、
//     地上・鉄道・海上の 3 つの移動タイプだけで戦線を組み立てることになる。
//
// 中央の陸地(中立駅の高台)と川:
//   - 中立の駅 (14,1) のまわり(col 12〜16、row 2〜4)は森と中立都市 3 個((13,2)(15,2)(14,3))の
//     高台になっている。線路で 3 ターンの距離にあり、取れば列車砲の修理拠点が前線に持てるうえ、
//     相手の列車砲の再生産も止められる、このマップ最大の争点。
//   - 高台の南端(row 5)は幅 1 マスの川で、渡ると下の陸地(row 6〜12 の中央の縦棒)につながる。
//     歩兵はコスト 2・装軌車両はコスト 3 で渡れるが、装輪車両は渡れない
//     (偵察車・ロケット砲が高台へ上がるには、輸送艦で海岸 (12,4)/(16,4) へ揚陸するしかない。
//     海岸の隣は平地にしてあるので、揚陸した装輪車両が浜辺で立ち往生することはない)。
//   - 川は中央の陸地を横断して左右の入江をつないでおり、海上ユニットはここを遡上できる。
//     自軍の港から敵軍の港までの海路(移動コスト 24)は必ずこの川を通るので、
//     川は「陸の切れ目」であると同時に「艦隊の関所」にもなる。高台を占領した側は、
//     川を通る敵の艦隊を上から叩けるという関係になっている。
//
// 中央の下部(川より南の中央の縦棒):
//   - 街道 col 14 の両脇 (13,8)/(15,8) に中立の研究所を 2 つ置いてある。都市と同じ性能の拠点だが、
//     中立のうちに占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)。
//     2 つとも col 14 を軸に左右対称で、自軍は左の (13,8)、敵軍は右の (15,8) が近い
//     (近いほうが移動コスト 16・遠いほうが 18。歩兵の移動力 3 ならどちらも 6 ターン)。
//     最短路は線路で中立駅まで走り、高台から川を渡って南下する道筋なので、
//     「線路を押さえる → 高台を取る → 研究所まで降りる」という縦の攻め筋がひとつながりになる
//     (線路を使わずに南岸を回ると 27 かかる)。
//   - 研究所のまわりには中立都市 4 個((12,7)(16,7)(13,11)(15,11))と中立港 2 個((12,9)(16,9))を
//     置いてあり、川より南の中央だけで 8 拠点(収入 8000 ぶん)が取れる。
//     中立港は入江の真ん中で艦隊を生産・修理できる位置にあり、中央は南岸を回る側の足場にもなる。
//
// 南岸(row 13〜16)と中立拠点:
//   - 南岸には端から端まで街道(row 14)が通り、両軍の陣地からは col 3 / col 25 の街道が
//     南北に降りてくる。中央の縦棒にも col 14 の街道があり、南岸から川の手前まで上がれる。
//     車両で回り込むならこの街道づたいが最短になる。
//   - 中立拠点は 30 個(中立都市 25・中立研究所 2・中立港 2・中立駅 1)。
//     海岸は入江のふちに 10 マス置いてあり、港が無くても揚陸・乗船ができる。
//
// 先手番ハンデの調整:
//   1 ターンぶん早く動ける先手(自軍)は中立駅にも先に着けるため、docs/GameDesign.md
//   「先手番のハンデ」の方針に従い、後手の敵軍陣地の隣にだけ中立都市を 2 個((24,3) と (27,3))
//   多く置いてある。どちらも敵軍が 1 ターンで届く位置(移動コスト 2 と 3)で、
//   自軍側の左右対称の位置((4,3) と (1,3))は平地のままにしてある。
//   これがこのマップ唯一の非対称点で、ハンデを増減させたいときはこの 2 マスで調整する。
//
// 上記のハンデ 2 マスを除けば、盤面は中央の col 14 を軸に左右対称で、地形・拠点の配置は
// 自軍・敵軍で等しい。初期ユニットは 0。初期資金 31000 は列車砲(30000)を買っても
// 歩兵(1000)が 1 体残る額で、両軍とも 1 ターン目から「列車砲 + 歩兵」で立ち上がれる。
// 敵軍AIが収入を貯め込んで列車砲を買うところまでなかなか到達できないための調整で、
// 線路と列車砲というこのマップの主題を 1 ターン目から成立させることを優先している。
// おつりの 1000 G を切り上げているのは、このマップの収入 6000 が軽戦車の生産コスト 6000 と
// 同額で、列車砲ちょうどの 30000 にすると敵軍AIの手持ちが毎ターン 0 になり、
// 歩兵を買う余りが出ずに中立拠点の占領が止まってしまうため。

