// 海に囲まれた 4 つの島が並ぶ 35x17(縦17・横35)の横長マップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「空だけがつなぐ四つの島」
//   - 盤面には島が 4 つある。左(col 2〜9)が先手の自軍の島、右(col 25〜32)が後手の敵軍の島、
//     そして真ん中の上(col 14〜20・row 1〜3)と下(col 15〜19・row 11〜15)に中立の小島が 1 つずつ。
//     どの島も陸路ではつながっておらず、左右の島のあいだは海が 15 マスもある。
//   - **このマップには港が 1 つも無い**ので、海上ユニットは 1 隻も生産できない。島を渡れるのは
//     飛行ユニットだけで、歩兵を運べるのは空港で作る輸送ヘリ(5500 G・移動力 6・歩兵 1 体)に限られる。
//     つまり**歩兵以外の地上ユニット(戦車・自走砲・対空車両)は、自分の島から一歩も出られない守備専用**になる。
//     攻め手は飛行ユニットと、輸送ヘリで運んだ歩兵だけ。
//   - **道路は 1 本も無い**。陸地は平地と森だけで構成してあり、装輪車両(偵察車・ロケット砲・対空ロケット砲)は
//     森へ入れず、平地も移動コスト 2 と足が鈍る。島の中の機動そのものが遅いので、地上戦は
//     「拠点のまわりで待ち構える」形になりやすい。森(防御 2)は上陸してきた歩兵を迎え撃つ陣地になる。
//   - 中立の小島は北と南に 1 つずつ。**どちらにも中立の空港 1 個と中立都市 3 個**があるが、
//     島の形も都市の並べ方もまったく別物にしてある(後述)。ここを取ると収入が 4000 G 伸びるうえ、
//     前線に飛行ユニットの生産・修理・補給の拠点を持てる。相手の島まで飛んでいく足がかりにもなるので、
//     **中立島をどれだけ早く占領できるかがこのマップの勝負どころ**になる。
//
// 両軍の島(左右で鏡写し):
//   - 島は横長の木の葉型で 42 マス。上下の端(row 5 / row 11)は 3 マスしかなく、いちばん広い
//     row 7〜9 でも 8 マス幅という**細身の島**で、陸戦の余地は小さい。
//   - 陣地は島の中ほどにぎゅっとまとめてある。**本拠地 1・工場 2・空港 2**(収入 5000)で、両軍まったく同じ構成。
//     自軍は本拠地 (6,8)・工場 (5,7)/(5,9)・空港 (7,7)/(7,9) の 3x3 に収まる固まりで、
//     **どの拠点も本拠地から 2 マス以内**。敵軍はその左右対称の位置
//     (本拠地 (28,8)・工場 (29,7)/(29,9)・空港 (27,7)/(27,9))。
//     生産した歩兵をすぐ輸送ヘリに乗せられるよう、工場と空港を隣り合わせにしてある。
//   - 空港 2 つを上下に分けてあるのは、北の中立島と南の中立島へ**同じ距離で**飛び立てるようにするため。
//     北の空港 (7,7) から北の島までも、南の空港 (7,9) から南の島までも、いちばん近い陸のマスまで
//     11 マス・中立空港まで 14 マスでまったく等しい。敵軍の空港からの距離も同じなので、
//     中立島の取り合いは**先に動ける先手のほうがわずかに速い**(そのぶん後述のハンデで釣り合わせる)。
//   - **中立島へは、島のどのマスから飛んでも輸送ヘリで必ず 2 ターンかかる**。島のいちばん外側の
//     マスから数えても中立島の陸まで 9 マスあり、歩兵を降ろせる隣接マスまでで 8 マス。
//     移動力 6 では 1 ターンでは届かないので、**どこから出しても 1 ターン目は海の上で止まる**ことになる。
//     逆に空港から出せば隣接マスまで 10 マスなので、2 ターン目にはきっちり降ろせる。
//   - 中立都市は島の四方の端に 5 個。北の先端 (6,5)・南の先端 (6,11)・西の端 (2,7)/(2,9)・
//     東の先端 (9,8) で、**どれも陣地から歩兵でちょうど 3 マス**。移動力 3 なので 1 ターンで着き、
//     翌ターンから占領にかかれる。陣地の隣で勝手に増える収入は無い。
//   - 相手の島へ攻め込むには、輸送ヘリで歩兵を運んで本拠地を占領するか、飛行ユニットで守備隊を
//     削り切るかの二択になる。戦闘機(移動力 10)は自軍の空港から敵軍の空港まで 20 マス = 2 ターン。
//
// 2 つの中立島(上下で別々の島にしてある):
//   - **北の島(col 14〜20・row 1〜3)は横長の砂州**。19 マスで東西に長い。中立空港 (17,3) は
//     島の南がわの真ん中にあり、中立都市は北の縁に 2 個 (16,1)/(18,1)・空港の真上に 1 個 (17,2)。
//     細長いぶん降ろせる場所が東西に広く、取り合いになると守りにくい。
//   - **南の島(col 15〜19・row 11〜15)は小さな丸い岩島**。21 マスで縦にも横にも 5 マスと厚い。
//     中立空港 (17,13) は島のど真ん中で、中立都市は北の先端に 1 個 (17,11)・空港の左右に 1 個ずつ
//     (15,13)/(19,13)。狭いぶん守りやすく、四隅の森 (15,12)/(19,12)/(15,14)/(19,14) が防御 2 の陣地になる。
//   - どちらの島も左右対称(col c と col 34-c が同じ地形)なので、両軍から見た距離と取りやすさは等しい。
//     上下で違うのは島の形と都市の並べ方だけで、有利不利は付いていない。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、後手の敵軍にだけ中立都市を 1 個多く置いてある。
//   敵軍本拠地 (28,8) のすぐ上 (28,7) の平地を中立都市に置き換えたもので、自軍の対称位置 (6,7) は平地のまま。
//   本拠地の目の前なので敵軍AIが確実に取り切れ、取り切ったあとの収入が自軍より 1000 G ぶん多くなる。
//   中立島へ先着できるのは先手、収入で先行できるのは後手、という釣り合いにしてある。
//   ハンデを増減させたいときは、このマスを平地に戻す/敵軍の島の平地をさらに都市に変える、で調整する。
//   この 1 マスを除けば盤面は左右対称で、島の形も拠点の配置も両軍で等しい。
//
// 初期ユニットは 0・初期資金も 0(initialFunds)。1 ターン目に使えるのは収入の 5000 G だけで、
// 輸送ヘリ(5500 G)にはあと 500 G 足りない。まず歩兵を出して資金を繰り越し、2 ターン目に輸送ヘリを作って
// 歩兵を乗せ、3〜4 ターン目に中立島へ渡す、という立ち上がりになる。戦闘機(20000 G)に手が届くのは
// 中立都市を取り始めたあと。序盤は「どちらの中立島から手を付けるか」の一手が効く。

