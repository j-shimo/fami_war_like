// 海に囲まれた 4 つの小島が並ぶ 27x21(縦21・横27)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「空だけがつなぐ四つの島」
//   - 盤面には島が 4 つある。左(col 1〜7)が先手の自軍の島、右(col 19〜25)が後手の敵軍の島、
//     そして真ん中の上(col 10〜16・row 1〜5)と下(col 10〜16・row 15〜19)に中立の小島が 1 つずつ。
//     どの島も陸路ではつながっておらず、島と島のあいだは海で 2 マス(左右の島のあいだは 11 マス)。
//   - **このマップには港が 1 つも無い**ので、海上ユニットは 1 隻も生産できない。島を渡れるのは
//     飛行ユニットだけで、歩兵を運べるのは空港で作る輸送ヘリ(5500 G・移動力 6・歩兵 1 体)に限られる。
//     つまり**歩兵以外の地上ユニット(戦車・自走砲・対空車両)は、自分の島から一歩も出られない守備専用**になる。
//     攻め手は飛行ユニットと、輸送ヘリで運んだ歩兵だけ。
//   - **道路は 1 本も無い**。陸地は平地と森だけで構成してあり、装輪車両(偵察車・ロケット砲・対空ロケット砲)は
//     森へ入れず、平地も移動コスト 2 と足が鈍る。島の中の機動そのものが遅いので、地上戦は
//     「拠点のまわりで待ち構える」形になりやすい。森(防御 2)は上陸してきた歩兵を迎え撃つ陣地になる。
//   - 中立の小島は北と南に 1 つずつ。**どちらにも中立の空港 1 個と中立都市 3 個**があり、
//     配置は上下の島で同じ(南の島は北の島を上下に反転させた形)。ここを取ると収入が 4000 G 伸びるうえ、
//     前線に飛行ユニットの生産・修理・補給の拠点を持てる。相手の島まで飛んでいく足がかりにもなるので、
//     **中立島をどれだけ早く占領できるかがこのマップの勝負どころ**になる。
//
// 両軍の島(左右で鏡写し):
//   - 陣地は島の中ほどに縦に並ぶ 5 拠点。**本拠地 1・工場 2・空港 2**(収入 5000)で、両軍まったく同じ構成。
//     自軍は本拠地 (4,10)・工場 (3,8)/(3,12)・空港 (5,7)/(5,13)、敵軍はその左右対称の位置。
//     空港 2 つは島の東がわ(中央の海に面した側)に、本拠地は島の内陸に置いてある。
//   - 空港を上下に 2 つ離してあるのは、北の中立島と南の中立島へ**同じ距離で**飛び立てるようにするため。
//     北の空港 (5,7) から北の島の中立空港 (13,3) までは 12 マス、南の空港 (5,13) から南の島の
//     中立空港 (13,17) までも 12 マスで、移動力 6 の輸送ヘリならちょうど 2 ターンぶん。
//     敵軍の空港 (21,7)/(21,13) から中立島までの距離もまったく同じ 12 マスなので、
//     中立島の取り合いは**先に動ける先手のほうがわずかに速い**(そのぶん後述のハンデで釣り合わせる)。
//   - 中立都市は島の北の端に 3 個・南の端に 2 個の計 5 個。どれも陣地から 5 マス以上離してあり、
//     歩兵で 2 ターンかけて取りにいく収入源になる(陣地の隣で勝手に増える収入は置いていない)。
//   - 相手の島へ攻め込むには、輸送ヘリで歩兵を運んで本拠地を占領するか、飛行ユニットで守備隊を
//     削り切るかの二択になる。戦闘機(移動力 10)は自軍の空港から敵軍の空港まで 16 マス = 2 ターン。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、後手の敵軍にだけ中立都市を 2 個多く置いてある。
//   敵軍本拠地 (22,10) のすぐ上 (22,9) と、すぐ下 (22,11) の平地を中立都市に置き換えたもので、
//   自軍の対称位置 (4,9)/(4,11) は平地のまま。どちらも本拠地の目の前なので敵軍AIが確実に取り切れ、
//   取り切ったあとの収入が自軍より 2000 G ぶん多くなる。中立島へ先着できるのは先手、
//   収入で先行できるのは後手、という釣り合いにしてある。
//   ハンデを増減させたいときは、この 2 マスを平地に戻す/敵軍の島の平地をさらに都市に変える、で調整する。
//   この 2 マスを除けば盤面は左右対称(col c と col 26-c が同じ地形)で、島の形も拠点の配置も両軍で等しい。
//
