// 海に囲まれた大きめの島が上下に 2 つ並ぶ 30x32(縦32・横30)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「線路の島と、都市の島」
//   - 上の島(row 1〜16)は先手の自軍、下の島(row 20〜29)は後手の敵軍の島で、
//     あいだの海峡(row 17〜19)を渡れるのは輸送艦だけ(このマップには空港が 1 つも無いので、
//     飛行ユニットは生産できない)。陸路は 1 本も無い。
//   - 開始時に駅を持つのは自軍だけなので、**列車砲(30000 G・移動力 15・射程 2〜6)を
//     生産できるのは先手の自軍だけ**。引き換えに敵軍は都市 4 個ぶんの収入を持って始まる。
//
// 上の島(先手の自軍):
//   - 陣地は島の左上。本拠地 (5,2) + 工場 3 + 港 2 + 駅 (5,1) の 7 拠点(収入 7000)。
//     駅は陣地でただ 1 つ row 1 に置いてある。敵軍AIは生産拠点を上の行から順に回るため、
//     2P側で遊んで自軍を敵軍AIが担当するときも、初期資金 31000 G をまず列車砲に使える。
//   - 線路は陣地の駅 (5,1) から**右下**へ階段状に下り、中間駅 (14,7) に着く。そこから今度は
//     **左下**へ折り返して、下の駅 (8,13) で終わる。駅から駅までは 15 と 12、端から端までは 27。
//     移動力 15 の列車砲は、陣地から中間駅までがちょうど 1 ターンぶん(15)、中間駅から下の駅までも
//     1 ターンぶん(12)で、陣地から下の駅までは 2 ターンかかる。中間駅と下の駅は中立なので、
//     取り返されれば列車砲の修理・再生産の起点も失う。
//   - **線路と街道のあいだは山の壁**で仕切られている。壁は (9,2)(10,2) から線路の外側(北東)を
//     なぞって (15,6) まで下り、中間駅を挟んで (15,8) から今度は線路の南東側を
//     (11,13) までなぞり、(11,15)(11,16) で南岸の海に届く。装軌車両も装輪車両も山へは
//     進入できないので、**車両が壁を越えられるのは、壁の北端と北岸のあいだのすき間 (8,1)(9,1)・
//     中間駅 (14,7)・南の峠 (11,14) の 3 か所だけ**(歩兵だけは山を越えて近道できる)。
//   - 街道は陣地から**島の東側をぐるりと回り込む 1 本道**で、島の下側へは大回りしないと着かない。
//     陣地の駅のすぐ東の踏切 (6,1)(7,1) で線路を渡り、壁の北端をかすめて北岸 (8〜16,1) を東へ走り、
//     col 16 を南下して東の街道(row 3)と中間駅の支道 (15,7)(16,7) に合流する。そこから row 3 を
//     東へ、col 21 を南下して row 14 を西へ戻り、南の峠 (11,14) を抜けて下の駅 (8,13) の下 (8,14) に着く。
//     **陣地から下の駅まで、街道づたいだと 44 マス**もあり、**線路づたいの 27 マス(列車砲で 2 ターン)**に
//     まるで追いつかない。
//   - 線路の西どなり(かつて街道が南下していた谷)には**平地が 1 マスも無い**。陣地の南 (5〜7,3)
//     (4〜8,4) から下の駅の手前 (4,12)(5,12) まで、かつての平地はすべて森か山に置き換えてあり、
//     線路の西がわには (7,3)(6〜8,4)(7〜9,5)(8〜10,6)(9〜11,7)(10〜13,8)(9〜12,9)(8〜11,10)
//     (9,11)(9,12) と**もう一枚の尾根**が線路に沿って立っている。装輪車両は森にも山にも入れないので
//     谷へは 1 マスも踏み込めず、装軌車両も森を踏み分けながら、山を避けて中立都市 (7,11) の鞍部を
//     通るしかない(かつて抜けられた線路ぎわの (9,11)(10,11) は山で塞いだ)。陣地から下の駅までの
//     移動コストは**装軌車両 26・装輪車両 45**で、列車砲の 2 ターンとは比べものにならない。
//     **島の下側へ手早く降りられるのは列車砲だけ**、というのがこのマップの縦の骨格になっている。
