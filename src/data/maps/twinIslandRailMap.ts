// 海に囲まれた大きめの島が上下に 2 つ並ぶ 30x32(縦32・横30)のマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「線路の島と、都市の島」
//   - 上の島(row 1〜16)は先手の自軍、下の島(row 20〜29)は後手の敵軍の島で、
//     あいだの海峡(row 17〜19)を渡れるのは輸送艦だけ(このマップには空港が 1 つも無いので、
//     飛行ユニットは生産できない)。陸路は 1 本も無い。
//   - 開始時に駅を持つのは自軍だけなので、**列車砲(30000 G・移動力 15・射程 2〜6)を
//     生産できるのは先手の自軍だけ**。引き換えに敵軍は都市 4 個ぶんの収入を持って始まる。
//
// 上の島(先手の自軍):
//   - 陣地は島の左上。本拠地 (5,2) + 工場 3 + 港 2 + 駅 (5,1) の 7 拠点(収入 7000)。
//     駅は陣地でただ 1 つ row 1 に置いてある。敵軍AIは生産拠点を上の行から順に回るため、
//     2P側で遊んで自軍を敵軍AIが担当するときも、初期資金 31000 G をまず列車砲に使える。
//   - 線路は陣地の駅 (5,1) から**右下**へ階段状に下り、中間駅 (14,7) に着く。そこから今度は
//     **左下**へ折り返して、下の駅 (8,13) で終わる。駅から駅までは 15 と 12、端から端までは 27。
//     移動力 15 の列車砲は、陣地から中間駅までがちょうど 1 ターンぶん(15)、中間駅から下の駅までも
//     1 ターンぶん(12)で、陣地から下の駅までは 2 ターンかかる。中間駅と下の駅は中立なので、
//     取り返されれば列車砲の修理・再生産の起点も失う。
//   - **線路と街道のあいだは山の壁**で仕切られている。壁は北岸の (8,1) から線路の外側(北東)を
//     なぞって (15,6) まで下り、中間駅を挟んで (15,8) から今度は線路の南東側を
//     (11,13) までなぞり、(11,15)(11,16) で南岸の海に届く。装軌車両も装輪車両も山へは
//     進入できないので、**車両が島の東側へ回れるのは中間駅 (14,7) と南の峠 (11,14) の 2 か所だけ**
//     (歩兵だけは山を越えて近道できる)。
//   - 街道は線路をぐるりと囲む馬蹄形で、2 つの駅でだけ線路とつながる。
//     西側は陣地から (5,3)〜(5,12) を南下して下の駅 (8,13) へ、東側は中間駅の支道 (15,7)(16,7)
//     から北上して row 3 を東へ、col 21 を南下して row 14 を西へ戻り、下の駅で西側の街道と出会う。
//     「駅には道路がつながっている」ので、車両は駅を通って線路側と街道側を行き来する。
//   - 研究所は中間駅のわきの (16,8)(壁 (15,8) の外側)と、下の駅から右へ進んだ (13,15) の 2 つ。
//     中立のうちに占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)。
//   - 下の駅 (8,13) から南へ 3〜4 マス下がるともう海で、南岸の海岸 (5〜10,16) から海峡を
//     3 マス渡れば、下の島の海岸 (7〜9,20) — つまり敵軍の陣地のすぐ北側に着く
//     (揚陸してから敵軍の本拠地まで歩兵で 5)。海岸のわきの中立港 (4,16) を取れば、
//     そこで作った輸送艦が海路 8 で敵軍の浜へ着けられる(自軍の陣地の港からは 25)。
//
// 下の島(後手の敵軍):
//   - 陣地は島の左側。本拠地 (5,22) + 工場 3 + 港 2 + 都市 4 の 10 拠点(収入 10000)で、
//     開始時の収入は自軍の 7000 を上回る。列車砲は作れないが、そのぶん頭数で押せる。
//   - 陣地の港 (3,22)(3,24) は西の海に面していて、自軍の島の南岸 (8,16) までは海路 11。
//     自軍の陣地の港から敵軍の浜までは 25 あるので、**海峡を先に渡れるのは後手のほう**になる。
//   - 島を東西に貫く街道(row 23)が陣地から東へ伸び、北岸 (10,20) と南 (18,26) へ支道が分かれる。
//
// 中立拠点は 25 個(都市 19・研究所 2・港 2・駅 2)。
//   - 都市の内訳は**上の島 12 個・下の島 7 個**で、総数では先手の島のほうが多い。
//     上の島の 12 個は西(線路側)に 5 個・東(街道側)に 7 個で、東側は山の壁の向こうなので
//     取りにいくには駅か峠を抜ける必要がある。
//   - いっぽう下の島の 7 個は敵軍の陣地から歩兵 4〜17 マスで、いちばん近い (9,21) は 2 ターンで届く。
//     自軍の最寄りの中立都市 (4,9) は 7 マスで 3 ターンかかるので、**先に占領を始められるのは後手**。
//     ただし陣地の隣ではないので、どちらの島でも 1 ターン目から占領は始まらない。
//
// 先手番ハンデの調整:
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、後手の敵軍に次の 3 つを渡してある。
//   ①開始時の収入が 10000 と自軍(7000)より多い(陣地の都市 4 個ぶん)。②中立都市を
//   先に占領し始められる(敵軍 2 ターン・自軍 3 ターン)。③海峡を先に渡れる(海路 11 対 25)。
//   引き換えに先手の自軍へ渡してあるのは、①列車砲を生産できる唯一の駅、②中立都市の総数
//   (自軍の島 12 個・敵軍の島 7 個)、③研究所 2 個と中立の駅 2 個、の 3 つ。
//   ハンデを増減させたいときは、陣地の都市 (4,21)(5,21)(5,23)(6,23) の 4 マスで調整する。
//
// 初期ユニットは 0。初期資金 31000 は列車砲(30000)+ 歩兵(1000)ぶんの額で、
// 駅を持つ側が 1 ターン目から列車砲を出しつつ占領も始められるようにしてある
// (三叉鉄橋マップ・湖畔と山峡マップと同じ調整)。

