// 海に囲まれた一本の細長い島を舞台にする 40x10(縦10・横40)の横長マップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「一本しかない街道と、山地帯で性格が変わる東西の島」
//   - 盤面は縦 10・横 40 の 4:1。陸地は col 1〜38 に横たわる 1 つの島だけで、
//     周囲はすべて海。小島は 1 つも置いていないので、上陸できるのはこの島の海岸線だけになる。
//   - 西端 (1,4) が自軍、東端 (38,4) が敵軍の本拠地。両拠点は 1 本の街道だけで結ばれている。
//     街道は 68 マスが 1 本につながった一本道で、途切れも分かれ道もない。
//     どこか 1 マスを敵に押さえられれば、そこから先へ車輪で進む手段は無くなる。
//   - 島の中央 col 18〜21 の山地帯を境に、西と東で島の地形をわざと作り分けてある。
//     鏡写しではないので、自陣側の戦い方と敵陣側の戦い方が別物になる(下記「東西の作り分け」)。
//
// 中央の山地帯(col 18〜21):
//   島の中央を、山が南北の海岸から海岸まで塞ぐ形で 4 列ぶん走っている。ここが盤面唯一の関門で、
//   移動タイプごとに通れるルートがはっきり分かれる。
//     - 峠道(row 4 の街道): すべての移動タイプが通れる唯一のルート。幅 1 マスの隘路で、
//       装輪車両(偵察車・ロケット砲)はここしか通れない。
//     - 北の森の間道(row 1 の森): 森を通れる歩兵と装軌車両だけが通れる迂回路。
//       森はコスト 2 なので峠道より遅いが、峠を固められたときの裏道になる。
//     - 山(コスト 2): 歩兵だけが直接乗り越えられる。夜戦では山に登った歩兵の視界が
//       2 + 3 = 5 に伸びるため、山地帯そのものが監視所として機能する。
//   つまり戦車を敵陣へ送り込むには「峠道を抜く」「森の間道を回る」「輸送艦で海から回り込む」の
//   3 択になる。海と空だけが山地帯を無視できるので、港と空港の使い道がそのまま突破口になる。
//
// 東西の作り分け(山地帯を境に別の島相にする):
//   - 西(自軍側・col 1〜17)は「森と九十九折りの島」。街道が row 2〜6 を 1 マス刻みで
//     細かく折り返し、その折り返しの内側((5,4)・(9,4)・(13,4)・(15,5) など)は森で埋めてある。
//     森へ入れない装輪車両は街道を外れて近道できず、自軍の偵察車・ロケット砲は
//     曲がりくねった道を素直に走るしかない。そのぶん森の防御 2 と細い回廊で守りは固い。
//     海岸線は col 11〜12 の南の入り江のように、細かく入り組んでいる。
//   - 東(敵軍側・col 22〜38)は「平地と大きな階段の島」。街道は row 2 →row 5 →row 7 →row 4 と
//     数マスずつまとめて折れる緩い階段状で、その周りは平地が広い。地上ユニットは街道を外れて
//     自由に迂回でき、進軍は速い。代わりに遮蔽になる森が少なく、守りにくい戦場になる。
//     col 28〜30 には北から大きく食い込む湾があり、(29,4)・(30,4) の山と合わせて
//     北岸沿いの通り抜けを塞いでいるため、車両は湾の南側(街道)を回ることになる。
//   西は「攻めるのは遅いが守りやすい」、東は「攻めるのは速いが守りにくい」という非対称で、
//   同じ島の東西でも戦い方が変わるようにしてある。釣り合いを調整したいときは、
//   西の折り返しの内側の森を平地に戻す(西の機動を上げる)、または東の平地に森を足す
//   (東の守りを固くする)で効き方を変えられる。
//
// 両軍の初期拠点(本拠地 1・工場 2・空港 2・港 1 の計 6 拠点):
//   - 自軍は本拠地 (1,4) の南北に工場、その外側に空港 2 つ、南岸に港 1 つを固めた縦一列の陣地。
//     敵軍は本拠地 (38,4) を中心に、工場・空港を斜めにずらして配置した陣地で、形は揃えていない。
//     拠点の数と種類は両軍まったく同じなので、生産力そのものに差は無い。
//   - 空港が 2 つあるので、飛行ユニットを 1 ターンに 2 機まとめて出せる。山地帯を無視できる
//     飛行ユニットは、このマップでは戦線を一気に飛び越える主力になる。
//   - 港は 1 つずつ。海路は島をぐるりと一周できるので、輸送艦を出せば敵陣の裏の海岸へ
//     直接戦車を揚げられる。海岸は南北の海岸線に 15 マスあり、そこが上陸地点になる。
//
// 初期資金は 0(initialFunds)。開始時の収入は 6 拠点ぶん = 6000 G で、1 ターン目に出せるのは
// 軽戦車 1 両+歩兵、あるいは歩兵 6 体といったところ。序盤は中立拠点を取って収入を伸ばし、
// 街道を進みながら戦力を育てる立ち上がりになる。
//
// 山地帯の両端に置いた中立拠点(峠の争奪をそのまま拠点の争奪にするための配置):
//   - 中立空港 2 つ。山の西の麓 (17,3) と東の麓 (22,5) に 1 つずつ置いてある。
//     どちらも峠道のすぐ隣で、押さえれば峠の上空に前進航空基地を持てる。
//     歩兵の移動コストは自軍から (17,3) まで 17、敵軍から (22,5) まで 17 でぴたりと揃えてある。
//   - 中立港 4 つ。山の西端の北岸 (17,1)・南岸 (17,7) と、東端の北岸 (22,1)・南岸 (22,7)。
//     山地帯は南北の海岸まで届いているので、この 4 港は「峠の裏へ艦隊で回り込むための足場」になる。
//     どれも森か山に囲まれていて装輪車両では入れず、占領は歩兵か装軌車両の仕事になる。
//
// 中立都市 25 個・中立拠点は計 32 個:
//   街道沿いの町と、街道から外れた内陸・海岸沿いの町を混ぜて置いてある。占領できる拠点は
//   両軍の 12 拠点と合わせて 44 個で、取り切れば収入は 44000 G。戦艦(35000 G)や
//   攻撃機(26500 G)といった高額ユニットは、拠点を伸ばして初めて視野に入る。
//
// 先手番ハンデの調整:
//   1 ターンぶん早く生産と占領を始められる先手(自軍)が有利なため、docs/GameDesign.md
//   「先手番のハンデ」の方針に従い、中央の山地帯より後手番側(東)に中立拠点を多く置いた。
//   - 中立都市は西 11 個に対して東 14 個。多く置いた 3 個 (38,3)・(37,5)・(38,6) はいずれも
//     敵軍の生産拠点に隣接していて、生産した歩兵が次のターンにそのまま占領へ入れる。
//   - 中立空港も東だけ 1 個多い(西 1・東 2)。多いぶんの (34,6) は敵軍本拠地から歩兵の
//     移動コスト 6(自軍からは 35)で、実質的に敵軍の 3 つ目の空港として働く。
//   ハンデを増減させたいときは、この 4 拠点を平地に戻す/敵軍陣地寄りの平地を都市に変える、
//   で調整する。山の両端の中立拠点(空港 2・港 4)は両軍から等距離なので触らないこと。
//
// 盤面の広さ(交戦までの距離):
//   横 40 マスは既存マップで最も長い。自軍本拠地から中央の峠 (19,4) までの移動コストは
//   歩兵 18・装軌車両 23・装輪車両 33 で、前線が噛み合うのは中央の山地帯。そこまでは
//   占領と生産で内政を進める時間になる。テンポを詰めたいときは西の街道のくねくねを
//   直線化する(街道 1 マスぶんが移動コスト 1)。
//
// 初期ユニットは 0。ゲーム開始時の収入で 1 ターン目から生産を始める設計とする。

