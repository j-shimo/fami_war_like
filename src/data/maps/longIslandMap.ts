// 海に囲まれた一本の細長い島を舞台にする 40x10(縦10・横40)の横長マップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「一本しかない街道と、島を断ち切る中央の山地帯」
//   - 盤面は縦 10・横 40 の 4:1。陸地は col 1〜38 に横たわる 1 つの島だけで、
//     周囲はすべて海。小島は 1 つも置いていないので、上陸できるのはこの島の海岸線だけになる。
//   - 西端 (1,4) が自軍、東端 (38,4) が敵軍の本拠地。両拠点は 1 本の街道だけで結ばれている。
//     街道は 76 マスが 1 本につながった一本道で、途切れも分かれ道もない。
//     どこか 1 マスを敵に押さえられれば、そこから先へ車輪で進む手段は無くなる。
//   - 街道は真っ直ぐには走らない。col 4〜16(と東の鏡写しの col 23〜35)は
//     row 2〜6 を縫うくねくねした九十九折りで、街道沿いに進むと直線距離の倍近く歩かされる。
//     曲がり角の内側には森と山を置いてあり、待ち伏せる側が有利になるようにしてある。
//
// 中央の山地帯(col 18〜21):
//   島の中央を、山が南北の海岸から海岸まで塞ぐ形で 4 列ぶん走っている。ここが盤面唯一の関門で、
//   移動タイプごとに通れるルートがはっきり分かれる。
//     - 峠道(row 4 の街道): すべての移動タイプが通れる唯一のルート。幅 1 マスの隘路で、
//       装輪車両(偵察車・ロケット砲)はここしか通れない。
//     - 北の森の間道(row 1 の森): 森を通れる歩兵と装軌車両だけが通れる迂回路。
//       森はコスト 2 なので峠道より遅いが、峠を固められたときの裏道になる。
//     - 山(コスト 2): 歩兵だけが直接乗り越えられる。夜戦では山に登った歩兵の視界が
//       2 + 3 = 5 に伸びるため、山地帯そのものが監視所として機能する。
//   つまり戦車を敵陣へ送り込むには「峠道を抜く」「森の間道を回る」「輸送艦で海から回り込む」の
//   3 択になる。海と空だけが山地帯を無視できるので、港と空港の使い道がそのまま突破口になる。
//
// 両軍の初期拠点(本拠地 1・工場 2・空港 2・港 1 の計 6 拠点):
//   - 本拠地を中心に工場 2 つを南北に並べ、空港 2 つをその外側((2,2)・(2,6) と敵軍側の鏡写し)、
//     港を島の南岸((1,7)・(38,7))に置いてある。生産力は両軍まったく同じ。
//   - 空港が 2 つあるので、飛行ユニットを 1 ターンに 2 機まとめて出せる。山地帯を無視できる
//     飛行ユニットは、このマップでは戦線を一気に飛び越える主力になる。
//   - 港は 1 つずつ。海路は島をぐるりと一周できるので、輸送艦を出せば敵陣の裏の海岸へ
//     直接戦車を揚げられる。海岸は南北の海岸線に 14 マスあり、そこが上陸地点になる。
//
// 初期資金は 0(initialFunds)。開始時の収入は 6 拠点ぶん = 6000 G で、1 ターン目に出せるのは
// 軽戦車 1 両+歩兵、あるいは歩兵 6 体といったところ。序盤は中立都市を取って収入を伸ばし、
// 街道を進みながら戦力を育てる立ち上がりになる。
//
// 中立都市 25 個:
//   - 街道沿いの町と、街道から外れた内陸・海岸沿いの町を混ぜて置いてある。
//     街道沿いの町は装輪車両でも護衛に行けるが、外れた町は歩兵と装軌車両でしか守れない。
//   - 占領できる拠点は両軍の 12 拠点と合わせて 37 個。取り切れば収入は 37000 G になり、
//     戦艦(35000 G)や攻撃機(26500 G)といった高額ユニットが視野に入る。
//
// 先手番ハンデの調整:
//   1 ターンぶん早く生産と占領を始められる先手(自軍)が有利なため、docs/GameDesign.md
//   「先手番のハンデ」の方針に従い、中央の山地帯より後手番側(東)に中立都市を 3 個多く置いた。
//   西側 11 個に対して東側 14 個で、増やした 3 マスは (37,3)・(37,5)・(38,6)。
//   どれも敵軍の生産拠点に隣接していて、生産した歩兵が次のターンにそのまま占領へ入れる
//   (敵軍本拠地からの歩兵の移動コストはいずれも 2)。自軍側の左右対称位置((2,3)・(2,5)・(1,6))は
//   平地のままで、これがこのマップ唯一の非対称点。ハンデを増減させたいときは、
//   この 3 マスを平地に戻す/敵軍陣地寄りの平地を都市に変える、で調整する。
//
// 盤面の広さ(交戦までの距離):
//   横 40 マスは既存マップで最も長く、街道を端から端まで走ると移動コストは 53(装輪)になる。
//   自軍本拠地から中央の峠 (19,4) までは歩兵 18・装軌車両 21・装輪車両 26 で、
//   自軍の北工場 (1,3) から峠までは移動コスト 27 なので、偵察車(装輪・移動力 8)でも移動 4 ターンぶんかかる。
//   前線が噛み合うのは中央の山地帯なので、そこまでは占領と生産で内政を進める時間になる。
//   テンポを詰めたいときは街道のくねくねを削って直線化する(街道 1 マスぶんが移動コスト 1)。
//
