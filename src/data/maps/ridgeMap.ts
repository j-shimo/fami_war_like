//
// 収入カーブの想定(調整の目安):
//   - 自軍の 8 個は本拠地から 1〜4 マスの位置にあり、歩兵 3〜4 体で 5 ターンほどあれば取り切れる。
//     取り切った時点で自軍 12 拠点 = 12000 G、敵軍は 10 拠点 = 10000 G のままとなり、
//     「終盤にようやく同等〜少し上回る」ところへ着地する。
//   - 中央の 4 個((9,1)・(10,4)・(9,11)・(10,13))は盤面の中心線(col 9.5)を挟んで
//     左右 2 個ずつに置いてあり、どちらの軍からも等距離。ここを何個取れるかが最終的な収入差になる。
//     半分ずつなら自軍 14000 / 敵軍 12000、敵軍に取り切られると 12000 / 14000 で逆転する。
//   - 収入差を縮めたい(自軍をもっと有利にしたい)ときは自軍側の中立都市を増やす、
//     広げたいときは敵軍の初期所有都市を増やす、で調整する。中央の 4 個は左右対称を保つこと。
//
// 進行ルート:
//   地形そのものは中心線(col 9.5)を挟んでほぼ左右対称で、有利不利は拠点の所有だけで付けてある。
//   盤面中央を東西に貫く稜線(row 6〜10 に広がる山地。うち row 7〜9 は col 6〜13 を隙間なく塞ぐ)が
//   戦場を南北に分断し、進行ルートは 2 本になる。
//     - 北の森ルート(row 0〜5): 中央部が森で埋まっており、装輪車両(偵察車・ロケット砲)は
//       森へ入れないため 1 両も通れない。装軌車両(戦車・自走砲)は通れるが移動コストが 2 で
//       速度が半減する。歩兵はコスト 1 で軽快に進めるうえ森は防御 2 なので、歩兵戦向きの遅いルート。
//     - 南の道路ルート(row 11〜15): row 12 に col 2〜17 を貫く道路が通っており、車両が
//       全力で走れる速攻ルート。ただし道路の防御は 0 で遮蔽もなく、(7,11)(8,11)(11,11)(12,11) と
//       (7,13)(12,13) の山が道路脇を締めるため、col 7〜12 が狭い回廊になる。
//   稜線そのものは山なので車両は 1 両も越えられないが、歩兵はコスト 2 で越えられる。
//   車両が南北を乗り換えられるのは自陣近くの col 0〜4(自軍)と col 15〜19(敵軍)だけで、
//   一度ルートを選ぶと中央では切り替えられない。
//
// 中立都市までの距離(工場・本拠地からの最短マンハッタン距離。生産した歩兵の到達しやすさの目安):
//   - 自軍まわりの 8 個: 自軍の生産拠点から 2〜7 マス、敵軍の生産拠点からは 14〜22 マス。
//     自軍は数ターンで取り切れる一方、敵軍が横取りしに来るには盤面を半分以上渡る必要がある。
