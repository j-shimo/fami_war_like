// 地上ユニットだけで戦う 20x16(縦16・横20)の東西マップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「開幕から大きく優勢な自軍が、内海の 2 ルートを押し切れるか」
//   逆転稜線マップ(ridgeMap)とは逆に、先手の自軍が最初から圧倒的な収入を持つマップ。
//   docs/GameDesign.md「非対称マップ(意図的な劣勢スタート)」の考え方を、優勢側が自軍になるよう
//   裏返して使っている。有利不利は「開始時の所有拠点数」と「中立拠点までの距離」の 2 つで表現する。
//
//   - 西(col 0〜3)が自軍、東(col 15〜18)が敵軍の陣地。港・空港は 1 マスも置かないため、
//     生産できるのは工場・本拠地の地上ユニットだけになる。中央には海があるが、
//     海上ユニットを生産できる港が無いので、海はどの軍も進入できない天然の障壁として働く。
//   - 生産拠点は両軍とも本拠地 1 + 工場 3 の計 4 つで、配置は盤面中心((c,r) → (19-c,15-r) の
//     点対称)で完全に揃えてある。したがって生産力そのものに差は無い。
//   - 差が付くのは都市の所有。自軍は陣地まわりの都市 9 個を開始時から占領済みで持つのに対し、
//     敵軍の所有都市は 0 個。開始時の収入は自軍 13000 G / 敵軍 4000 G と、9000 G の大差が付く。
//     1 ターン目に自軍は中戦車 1 両+歩兵 1 体を出せるが、敵軍は歩兵 4 体が精一杯となる。
//
// 敵軍の巻き返し手段(距離のハンデ):
//   収入差だけを付けると敵軍が何もできずに終わるため、中立拠点の置き方を敵軍側へ大きく寄せてある。
//   - 敵軍陣地のすぐ外に、歩兵が 1 ターンで届く中立拠点を 4 つ置く。中立工場 (15,11) と
//     中立都市 (16,4)・(16,6)・(16,10) で、敵軍の生産拠点からの移動コストはそれぞれ 3・3・2・2。
//     歩兵の移動力は 3 なので、生産した歩兵が 1 ターンの移動でそのまま占領に取りかかれる。
//     取り切ると敵軍は 8 拠点 = 8000 G、生産拠点も 5 つに増えて南ルートに前線工場を持つ。
//   - 対して自軍から最も近い中立拠点は中央の (9,4) で移動コスト 8。歩兵で 3 ターンかかるうえ、
//     道中は内海の岸沿いで敵軍の射程に晒される。自軍は「持っている 13000 G を戦力に変えて押す」
//     以外に伸びしろが無く、内政で差を広げることはできない。
//
// 収入カーブの想定(調整の目安):
//   - 開始時: 自軍 13000 / 敵軍 4000。
//   - 敵軍が足元の 4 拠点を取り切った時点(3〜4 ターン目): 自軍 13000 / 敵軍 8000。
//   - 中央の中立都市 6 個が最終的な差を決める。半分ずつなら 16000 / 11000 で自軍優位のまま、
//     敵軍に 6 個すべてを取られると 13000 / 14000 で収入が逆転する。
//     「自軍がかなり有利だが、放置すれば追いつかれる」ところへ着地させてある。
//   - 有利を弱めたいときは自軍の初期所有都市を減らして中立に戻す、強めたいときは
//     敵軍側の中立拠点 4 つを減らす、で調整する。中央の 6 個は点対称を保つこと。
//
// 進軍ルート:
//   盤面中央にレンズ型の内海(row 5〜10、最大 col 5〜14)が広がり、その岸を海岸(記号 b)が縁取る。
//   海は地上ユニットが 1 マスも進入できないため、戦場は北と南の 2 ルートに完全に分断される。
//   内海は row 7〜8 で col 5〜14 を隙間なく塞いでおり、南北を乗り換えられるのは
//   自軍陣地(col 0〜4)と敵軍陣地(col 15〜19)の岸だけ。中央では歩兵ですら乗り換えできない。
//     - 北の街道ルート(row 0〜4): row 2 に col 2〜17 を貫く街道が通っており、装輪車両を含む
//       すべての地上ユニットが全力で走れる速攻ルート。ただし街道の防御は 0 で、
//       (8,0)(11,0)(9,1)(10,1)(8,3)(11,3)(10,4) の山と両脇の森が col 6〜13 を狭い回廊にする。
//     - 南の森ルート(row 11〜15): 森と山が続く鈍足ルート。col 9 が row 11〜15 まで森と山で
//       埋まっているため、森・山に進入できない装輪車両(偵察車・ロケット砲)は 1 両も通り抜けられない。
//       歩兵はコスト 1、装軌車両はコスト 2 で通れるので、歩兵戦・戦車戦向きの戦場になる。
//   陣地の岸((4,7)(4,8) と (15,7)(15,8))は海岸で、装輪車両は移動コスト 4 と大きく減速する。
//   南北のルートを乗り換えるとき、車輪の部隊だけは自陣の砂浜で足を取られる。
//
// 中立拠点までの距離(生産拠点からの歩兵の移動コスト。低いほど早く占領に着手できる):
//   - 敵軍まわりの 4 個: 敵軍から 2〜3、自軍からは 16〜19。自軍が横取りしに行くには盤面を丸ごと渡る。
//   - 中央の 6 個: 自軍から 9・14・8・11・10・15(合計 67)、敵軍から 15・10・11・9・14・9(合計 68)。
//     中央の 6 個は盤面中心について点対称((7,1)↔(12,14)、(12,1)↔(7,14)、(9,4)↔(10,11))に置いてあり、
//     生産拠点も点対称なのでマンハッタン距離の合計は両軍とも 66 でぴたりと揃う。
//     実移動コストの 1 の差は、敵軍側だけにある南ルートの街道支線(row 11)によるもの。
//
// 初期ユニットは 0。ゲーム開始時の収入で 1 ターン目から生産を始める設計とする。

