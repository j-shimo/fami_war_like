// 4 つの軍勢が 1 つの大きな島で覇を競う 32x24(横32・縦24)の 4P マップ。4Pマップ区分(group: 'four')の 1 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「山と川で仕切られた 4 つの陣地を、3 本の街道と島の真ん中を抜ける 1 本がつなぐ」
//   島の四隅に 4 軍の陣地があり、手番は 1P → 2P → 3P → 4P の順に回る。
//   隣り合う陣地のあいだには、それぞれ性格の違う境目を置いてある。
//     - 1P と 2P の間(北): 山脈。車両は越えられず、歩兵だけが山越えで近道できる。街道も通っていない
//     - 1P と 3P の間(西): 川に囲まれた中州。中立都市の塊が 2 つあり、両軍が奪い合う
//     - 2P と 4P の間(東): 島を東西に横切る川。街道は橋で渡る
//     - 3P と 4P の間(南): 一直線の街道。遮るものの無い、いちばん見通しのよい戦場
//   対角(1P と 4P・2P と 3P)は島の反対側で、どちらからも歩兵で 33〜37 と遠い。
//
// 陣地(4 軍とも本拠地 1 + 工場 3 = 収入 4000・初期資金 0 の対等な立ち上がり):
//   2x2 の拠点の塊を持ち、盤面の角に近い外側の 1 マスが本拠地、残る 3 マスが工場。
//     - 1P(青・左上): 本拠地 (9,3) / 工場 (10,3)(9,4)(10,4)
//       2P へ寄せて島の内側に置いてあり、工場から山脈の山 (13,2)・(14,3) まで歩兵で 2 ターン(コスト 5)
//     - 2P(赤・右上): 本拠地 (27,3) / 工場 (26,3)(26,4)(27,4)
//     - 3P(緑・左下): 本拠地 (5,20) / 工場 (5,19)(6,19)(6,20)
//     - 4P(黄・右下): 本拠地 (27,20) / 工場 (26,19)(27,19)(26,20)
//   4Pモードで「なし」を選んだ軍勢の陣地は、本拠地が中立の都市に・工場が中立の工場になる
//   (src/data/maps/armySlots.ts)。
//
// 左端の海:
//   col 0〜1(ところにより col 2 まで)が海で、海ぎわには砂浜(海岸)が点々と続く。
//   港は無いので海上ユニットは作れない。中州を囲む川は西でこの海へ注ぐ。
//
// 山脈(1P と 2P の間):
//   col 13〜18・row 0〜9 に山 37 マスが連なり、すそ野は森で縁取ってある。
//   装軌・装輪車両はどちらも進入できないため、1P と 2P の車両どうしは山脈の南すそ
//   (row 10〜11 の、山と川に挟まれた狭い通り道)を回らないと出会えない。
//   歩兵だけは山を越えて近道できる(1P の工場から 2P の本拠地まで、歩兵 21・装軌車両 32)。
//
// 川(島を東西に横切る本流と、中州を囲む川):
//   - 本流: 東の端 (31,10) から西へ流れ、山脈の南すそをかすめて中州の東の角 (10,12) で
//     中州を囲む川へ合流する。北の 1P・2P と南の 3P・4P を分ける境目で、
//     歩兵(移動コスト 2)と装軌車両(3)は渡れるが、装輪車両(偵察車・ロケット砲)は渡れない。
//     本流に架かる橋は 2 本だけ。
//       中央の橋 (17,12) … 1P から島の真ん中を抜ける街道
//       東の橋 (26,11) … 2P〜4P の街道
//   - 中州: 1P と 3P の陣地の間に、川で四角く囲まれた中州(col 3〜10・row 8〜14 の川の内側)がある。
//     中には中立都市が 3 個ずつ 2 つの塊で固まっている。
//       北西の塊 (5,9)(4,10)(5,10) … 1P からやや近い
//       南東の塊 (9,12)(8,12)(8,13) … 1P と 3P からほぼ同じ距離
//     中州を越える道は 1P〜3P の街道だけで、北の橋 (7,8) と南の橋 (7,14) で川を渡る。
//     装輪車両はこの 2 本の橋からしか中州へ出入りできない。中州の西側は海に面している。
//
// 道路(4 本):
//   - 3P〜4P: row 19 を col 7〜25 まで一直線(3P の工場 (6,19) から 4P の工場 (26,19) まで)。
//   - 1P〜3P: 1P の工場 (9,4) の南から西へ折れ、中州の真ん中を col 7 で南北に貫いて
//     (北の橋 (7,8)・南の橋 (7,14))、3P の工場 (6,19) の上へ着く。
//   - 2P〜4P: 2P の陣地の南 (26,5) から、西へ振れてから東へ戻りつつ南下し、本流を東の橋 (26,11) で
//     越え、さらに東へ回り込んで 4P の工場 (27,19) の上へ着く。
//   - 1P〜島の真ん中〜3P・4P の街道: 1P の工場 (10,4) から東へ出て、山脈の西すそを南へ下り、
//     山と川に挟まれた通り道(row 11)を東へ抜けて中央の橋 (17,12) で本流を越え、
//     (16,19) で 3P〜4P の街道に T 字でつながる。
//     1P から南の 2 軍へ向かう第 2 の道で、2P の陣地とは道路でつながっていない。
//
// 陣地から陣地までの距離(工場から相手の本拠地まで。歩兵 / 装軌 / 装輪):
//   1P〜2P 21 / 32 / 40、1P〜3P 20 / 20 / 20、2P〜4P 17 / 17 / 20、3P〜4P 21 / 22 / 22。
//   北の 1P と 2P は山脈が、西の 1P と 3P は中州が、南の 3P と 4P は一直線の街道が間にある。
//
// 中立都市 27 個(かっこ内は 1P / 2P / 3P / 4P の最寄り工場からの歩兵の移動コスト):
//   歩兵の移動力は 3 なので、コスト 3 までが 1 ターン・6 までが 2 ターンで届く。
//   都市は 1〜3 個の塊にまとめて置いてある。
//   手番の遅い 2P・4P は陣地のすぐ隣の都市へ 1 ターンで届き、1P・3P の近くの都市は 2 ターンの距離にある
//   (docs/GameDesign.md「先手番のハンデ」)。
//     - 1P の近く(3 個とも 2 ターン): (12,1)(4/20/24/32)・(5,5)(5/26/16/35)・(5,6)(6/26/15/34)
//     - 2P の近く(2 個が 1 ターン・2 個が 2 ターン): (24,4)(18/2/33/17)・(24,5)(19/3/32/16)・
//       (29,6)(24/4/36/16)・(29,8)(26/6/34/14)
//     - 3P の近く(3 個とも 2 ターン): (10,18)(17/30/5/17)・(10,17)(16/29/6/18)・(3,22)(24/41/5/25)
//     - 4P の近く(2 個が 1 ターン・1 個が 2 ターン): (28,18)(32/16/23/2)・(29,18)(33/17/24/3)・
//       (23,21)(30/20/18/4)
//     - 中州の北西の塊: (5,9)(9/29/11/31)・(4,10)(11/29/11/31)・(5,10)(10/28/10/30)
//     - 中州の南東の塊: (9,12)(9/26/10/25)・(8,12)(10/27/9/26)・(8,13)(11/28/8/25)
//     - 北の中間(山脈の両すそ): (13,8)(7/20/19/24)・(13,9)(8/20/18/23) は 1P が、
//       (21,7)(17/8/27/17)・(21,8)(18/9/26/16) は 2P が近い
//     - 島の真ん中(本流の南): (20,14)(20/16/19/11)・(21,14)(21/15/20/10) は 4P が近い
//     - 南の街道の下: (15,21)(23/28/10/12) は 3P が近く、(16,21)(24/27/11/11) は 3P と 4P が同着
//   最寄りの都市の数は 1P 7 個・2P 6 個・3P 6 個・4P 5 個に、同着が 1P・3P で 2 個・3P・4P で 1 個。
//
// 先手番のハンデの調整:
//   手番が遅い軍に都市を寄せるには、陣地のすぐ隣の都市(2P・4P の 1 ターンで届く 2 個ずつ)を
//   増減するのがいちばん効きが読みやすい。1P・3P の近くの都市は 3 個とも 2 ターンの距離に
//   そろえてあるので、どちらかを 1 ターンの距離へ寄せれば差を縮められる。

