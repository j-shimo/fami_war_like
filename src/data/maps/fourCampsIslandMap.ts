// 4 つの軍勢が 1 つの大きな島で覇を競う 26x24(横26・縦24)の 4P マップ。4Pマップ区分(group: 'four')の 1 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「山と川で仕切られた 4 つの陣地を、3 本の街道と島の真ん中を抜ける 1 本がつなぐ」
//   島の四隅に 4 軍の陣地があり、手番は 1P → 2P → 3P → 4P の順に回る。
//   隣り合う陣地のあいだには、それぞれ性格の違う境目を置いてある。
//     - 1P と 2P の間(北): 山脈。車両は越えられず、歩兵だけが山越えで近道できる。街道も通っていない
//     - 1P と 3P の間(西): 川に囲まれた中州。中立都市が 1〜2 個ずつ固まっていて、両軍が奪い合う
//     - 2P と 4P の間(東): 一直線に南北を結ぶ街道。島を東西に横切る川を橋で渡る
//     - 3P と 4P の間(南): 一直線の街道。遮るものの無い、見通しのよい戦場
//   対角(1P と 4P・2P と 3P)は島の反対側で、どちらからも歩兵で 28〜32 と遠い。
//
// 陣地(4 軍とも本拠地 1 + 工場 3 = 収入 4000・初期資金 0 の対等な立ち上がり):
//   2x2 の拠点の塊を持ち、盤面の角に近い外側の 1 マスが本拠地、残る 3 マスが工場。
//     - 1P(青・左上): 本拠地 (9,3) / 工場 (10,3)(9,4)(10,4)
//       工場から山脈の山 (13,2)・(14,3) まで歩兵で 2 ターン(コスト 5)
//     - 2P(赤・右上): 本拠地 (22,3) / 工場 (21,3)(21,4)(22,4)
//       山脈のすぐ東に構え、工場 (21,3) から山 (19,3) まで歩兵で 1 ターン(コスト 3)
//     - 3P(緑・左下): 本拠地 (5,20) / 工場 (5,19)(6,19)(6,20)
//     - 4P(黄・右下): 本拠地 (22,20) / 工場 (21,19)(22,19)(21,20)
//   4Pモードで「なし」を選んだ軍勢の陣地は、本拠地が中立の都市に・工場が中立の工場になる
//   (src/data/maps/armySlots.ts)。
//
// 左側の海:
//   島の西は海で、北ほど広く、3P の陣地へ向かって南へ下るほど段々と狭くなる
//   (row 0〜5 は col 0〜5 の 6 列、row 6〜12 は 5 列、row 13〜15 は 4 列、row 16〜17 は 3 列、
//   row 18 から下は 2 列)。1P の本拠地の西は、海岸までの平地が 2 マスだけ。
//   海ぎわには砂浜(海岸)が点々と続く。港は無いので海上ユニットは作れない。
//   中州を囲む川は西でこの海へ注ぐ。
//
// 山脈(1P と 2P の間):
//   col 13〜19・row 0〜9 に山 43 マスが連なり、すそ野は森で縁取ってある。
//   装軌・装輪車両はどちらも進入できないため、1P と 2P の車両どうしは山脈の南すそ
//   (row 10〜11 の、山と川に挟まれた通り道)を回らないと出会えない。
//   歩兵だけは山を越えて近道できる(1P の工場から 2P の本拠地まで、歩兵 18・装軌車両 25)。
//
// 川(島を東西に横切る本流と、中州を囲む川):
//   - 本流: 東の端 (25,10) から西へ流れ、山脈の南すそをかすめて中州の東の辺 (11,12) で
//     中州を囲む川へ合流する。北の 1P・2P と南の 3P・4P を分ける境目で、
//     歩兵(移動コスト 2)と装軌車両(3)は渡れるが、装輪車両(偵察車・ロケット砲)は渡れない。
//     本流に架かる橋は 2 本だけ。
//       中央の橋 (15,12) … 1P から島の真ん中を抜ける街道
//       東の橋 (21,11) … 2P〜4P の街道
//   - 中州: 1P と 3P の陣地の間に、川で四角く囲まれた中州(col 5〜11・row 9〜15 の川の内側)がある。
//     中の中立都市 6 個は、1〜2 個ずつの塊で置いてある。
//       北の (6,10)(7,10) と (10,12) … 1P からやや近い
//       南の (6,13) と (9,14)(10,14) … 3P からやや近い
//     中州を越える道は 1P〜3P の街道だけで、北の橋 (8,9) と南の橋 (8,15) で川を渡る。
//     装輪車両はこの 2 本の橋からしか中州へ出入りできない。中州の西側は海に面している。
//
// 道路(4 本):
//   - 3P〜4P: row 19 を col 7〜20 まで一直線(3P の工場 (6,19) から 4P の工場 (21,19) まで)。
//   - 2P〜4P: col 21 を row 5〜18 まで一直線(2P の工場 (21,4) から 4P の工場 (21,19) まで)。
//     本流は東の橋 (21,11) で渡る。
//   - 1P〜3P: 1P の工場 (9,4) の南から西へ折れ、中州の真ん中を col 8 で南北に貫いて
//     (北の橋 (8,9)・南の橋 (8,15))、3P の工場 (6,19) の上へ着く。
//   - 1P〜島の真ん中〜3P・4P の街道: 1P の工場 (10,4) から東へ出て、山脈の西すそを南へ下り、
//     山と川に挟まれた通り道(row 11)を東へ抜けて中央の橋 (15,12) で本流を越え、
//     (14,19) で 3P〜4P の街道に T 字でつながる。
//     1P から南の 2 軍へ向かう第 2 の道で、2P の陣地とは道路でつながっていない。
//
// 陣地から陣地までの距離(工場から相手の本拠地まで。歩兵 / 装軌 / 装輪):
//   1P〜2P 18 / 25 / 33、1P〜3P 20 / 20 / 20、2P〜4P 17 / 17 / 17、3P〜4P 16 / 17 / 17。
//   北の 1P と 2P は山脈が、西の 1P と 3P は中州が間にあり、東の 2P と 4P・南の 3P と 4P は
//   一直線の街道で結ばれている。
//
// 中立都市 27 個(かっこ内は 1P / 2P / 3P / 4P の最寄り工場からの歩兵の移動コスト):
//   歩兵の移動力は 3 なので、コスト 3 までが 1 ターン・6 までが 2 ターンで届く。
//   都市はどれも 1 個だけか、2 個が隣り合った塊で置いてある。
//   手番の遅い 2P・4P は陣地のすぐ隣の都市 2 個へ 1 ターンで届き、1P・3P の近くの都市は
//   2 ターンの距離にある(docs/GameDesign.md「先手番のハンデ」)。
//     - 1P の近く(3 個とも 2 ターン): (12,1)(4/16/24/27)・(7,6)(4/20/16/27)・(7,7)(5/21/15/26)
//     - 2P の近く: (23,5)(19/2/31/16)・(24,5)(20/3/32/17) は 1 ターン、
//       (24,1)(21/5/36/21)・(24,8)(21/6/29/14) は 2 ターン
//     - 3P の近く(3 個とも 2 ターン): (10,18)(16/25/5/12)・(10,17)(15/24/6/13)・(3,22)(24/36/5/20)
//     - 4P の近く: (23,18)(27/16/18/2)・(24,18)(28/17/19/3) は 1 ターン、(18,21)(25/20/13/4) は 2 ターン
//     - 中州の北: (6,10)(9/22/10/24)・(7,10)(8/21/11/23)・(10,12)(9/20/11/19) は 1P が近い
//     - 中州の南: (6,13)(12/25/7/21)・(9,14)(11/23/8/18)・(10,14)(11/22/9/17) は 3P が近い
//     - 北の中間(山脈の両すそ): (13,8)(7/15/18/19) は 1P が、(19,8)(16/6/24/13)・(19,9)(16/7/23/12) は
//       2P が近い
//     - 島の真ん中(本流の南): (17,14)(17/14/16/9)・(18,14)(18/13/17/8) と、東の川べりの
//       (24,12)(22/11/25/9) は 4P が近い
//     - 南の街道の下: (12,21)(20/26/7/10)・(13,21)(21/25/8/9) は 3P が近い
//   最寄りの都市の数は 1P 7 個・2P 6 個・3P 8 個・4P 6 個。
//
// 先手番のハンデの調整:
//   手番が遅い軍に都市を寄せるには、陣地のすぐ隣の都市(2P・4P の 1 ターンで届く 2 個ずつ)を
//   増減するのがいちばん効きが読みやすい。1P・3P の近くの都市は 3 個とも 2 ターンの距離に
//   そろえてあるので、どちらかを 1 ターンの距離へ寄せれば差を縮められる。

