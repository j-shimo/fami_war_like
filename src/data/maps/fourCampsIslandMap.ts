// 4 つの軍勢が 1 つの大きな島で覇を競う 32x24(横32・縦24)の 4P マップ。4Pマップ区分(group: 'four')の 1 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「山と川で仕切られた 4 つの陣地を、3 本の街道と島の真ん中を抜ける 1 本がつなぐ」
//   島の四隅に 4 軍の陣地があり、手番は 1P → 2P → 3P → 4P の順に回る。
//   隣り合う陣地のあいだには、それぞれ性格の違う境目を置いてある。
//     - 1P と 2P の間(北): 山脈。車両は越えられず、歩兵だけが山越えで近道できる。街道も通っていない
//     - 1P と 3P の間(西)・2P と 4P の間(東): 島を東西に横切る川。街道は橋で渡る
//     - 3P と 4P の間(南): 一直線の街道。遮るものの無い、いちばん見通しのよい戦場
//   対角(1P と 4P・2P と 3P)は島の反対側で、どちらからも歩兵で 37〜38 と遠い。
//
// 陣地(4 軍とも本拠地 1 + 工場 3 = 収入 4000・初期資金 0 の対等な立ち上がり):
//   2x2 の拠点の塊を持ち、盤面の角に近い外側の 1 マスが本拠地、残る 3 マスが工場。
//     - 1P(青・左上): 本拠地 (4,3) / 工場 (5,3)(4,4)(5,4)
//     - 2P(赤・右上): 本拠地 (27,3) / 工場 (26,3)(26,4)(27,4)
//     - 3P(緑・左下): 本拠地 (5,20) / 工場 (5,19)(6,19)(6,20)
//     - 4P(黄・右下): 本拠地 (27,20) / 工場 (26,19)(27,19)(26,20)
//   4Pモードで「なし」を選んだ軍勢の陣地は、本拠地が中立の都市に・工場が中立の工場になる
//   (src/data/maps/armySlots.ts)。
//
// 左端の海:
//   col 0〜1(ところにより col 2 まで)が海で、海ぎわには砂浜(海岸)が点々と続く。
//   港は無いので海上ユニットは作れない。島を東西に横切る川と、3P の堀は西でこの海へ注ぐ。
//
// 山脈(1P と 2P の間):
//   col 13〜18・row 0〜6 に山 28 マスが連なり、すそ野は森で縁取ってある。
//   装軌・装輪車両はどちらも進入できないため、1P と 2P の車両どうしは山脈の南すそ
//   (row 7 から下)を回らないと出会えない。歩兵だけは山を越えて近道できる
//   (1P の工場から 2P の本拠地まで、歩兵 26・装軌車両 31)。
//
// 川(島を東西に横切る本流と、3P の堀):
//   - 本流: 東の端 (31,9) から島の真ん中を西へ蛇行し、左の海 (3,12) へ注ぐ。
//     北の 1P・2P と南の 3P・4P を分ける境目で、歩兵(移動コスト 2)と装軌車両(3)は渡れるが、
//     装輪車両(偵察車・ロケット砲)は渡れない。本流に架かる橋は 3 本だけ。
//       西の橋 (5,12) … 1P〜3P の街道
//       中央の橋 (17,12) … 1P から島の真ん中を抜ける街道
//       東の橋 (26,11) … 2P〜4P の街道
//   - 3P の堀: 3P の陣地をぐるりと囲む川(col 3〜9・row 17〜22 の四角)。本流から (10,12) で
//     分かれて南へ下り、堀の北東の角 (9,17) へ流れ込む。堀の西側は海に面している。
//     堀を越える道は北の橋 (7,17)(1P〜3P の街道)と東の橋 (9,19)(3P〜4P の街道)の 2 本だけで、
//     装輪車両は 3P の陣地へこの 2 本の橋からしか出入りできない。守りやすいぶん、
//     3P の歩兵は堀の外の都市へ取りに行くのに川を渡るか橋を回る必要がある。
//
// 道路(4 本):
//   - 3P〜4P: row 19 を col 7〜25 まで一直線(3P の工場 (6,19) から 4P の工場 (26,19) まで)。
//     堀の東側を (9,19) の橋で越える。両陣地の工場から街道の真ん中 (16,19) まではどちらも 10。
//   - 1P〜3P: 1P の陣地の南 (4,5) から、西へ東へと折れながら南下し、本流を西の橋 (5,12)、
//     堀を北の橋 (7,17) で越えて 3P の工場 (6,19) の上へ着く。
//   - 2P〜4P: 2P の陣地の南 (26,5) から、西へ振れてから東へ戻りつつ南下し、本流を東の橋 (26,11) で
//     越え、さらに東へ回り込んで 4P の工場 (27,19) の上へ着く。
//   - 1P〜島の真ん中〜3P・4P の街道: 1P の工場 (5,3) から東へ出て、山脈の南すそを回り込みながら
//     島の真ん中へ下り、中央の橋 (17,12) で本流を越え、(16,19) で 3P〜4P の街道に T 字でつながる。
//     1P から南の 2 軍へ向かう第 2 の道で、2P の陣地とは道路でつながっていない。
//   3P〜4P の街道以外はどれも曲がり角が 7〜11 か所あり、ひと目で先が見通せない道にしてある。
//
// 陣地から陣地までの距離(工場から相手の本拠地まで。歩兵 / 装軌 / 装輪):
//   1P〜3P 17 / 18 / 21、2P〜4P 17 / 17 / 20、3P〜4P 22 / 22 / 22、1P〜2P 26 / 31 / 38。
//   北の 1P と 2P は山脈が、南の 3P と 4P は一直線の街道が間にあるので、
//   「近いが川と山で守られた縦の隣」と「遠いが開けた横の隣」を持つ形になる。
//
// 中立都市 24 個(かっこ内は 1P / 2P / 3P / 4P の最寄り工場からの歩兵の移動コスト):
//   歩兵の移動力は 3 なので、コスト 3 までが 1 ターン・6 までが 2 ターンで届く。
//   手番の遅い軍ほど序盤の都市を取りやすくしてあり、1P より 2P、3P より 4P のほうが
//   陣地のすぐ隣の都市へ早く届く(docs/GameDesign.md「先手番のハンデ」)。
//     - 1P の近く(3 個とも 2 ターン): (7,6)(4/23/15/32)・(3,8)(5/27/14/34)・(4,10)(6/28/11/31)
//     - 2P の近く(2 個が 1 ターン・1 個が 2 ターン): (24,4)(24/2/33/17)・(28,6)(27/3/35/15)・
//       (23,7)(21/6/29/15)
//     - 3P の近く(3 個とも 2 ターン。どれも堀の外): (11,18)(21/29/6/16)・(4,15)(12/33/6/26)・
//       (8,15)(14/30/6/23)
//     - 4P の近く(2 個が 1 ターン・1 個が 2 ターン): (28,18)(37/16/23/2)・(25,21)(37/18/21/2)・
//       (23,17)(31/16/19/5)
//     - 北の中間(山脈の南すそ): (10,7)(8/19/17/28)・(13,9)(13/18/18/23) は 1P が、
//       (20,7)(18/9/26/18)・(18,8)(17/12/23/19) は 2P が近い
//     - 島の真ん中: (14,14)(20/22/13/17) は 3P が、(21,13)(25/14/21/11)・(24,14)(29/12/23/7) は 4P が近い。
//       東の川べりの (29,11)(32/10/31/10) は 2P と 4P から同じ距離で、先に動ける 2P が先着する
//     - 南の街道の上下: (13,17)(22/26/9/15)・(14,21)(26/29/10/13) は 3P が、
//       (19,17)(27/20/15/9)・(20,21)(32/23/16/7) は 4P が近い
//   最寄りの都市の数は 1P 5 個・2P 6 個(同着の (29,11) を含む)・3P 6 個・4P 7 個。
//
// 先手番のハンデの調整:
//   手番が遅い軍に都市を寄せるには、陣地のすぐ隣の都市(2P・4P の 1 ターンで届く 2 個ずつ)を
//   増減するのがいちばん効きが読みやすい。1P・3P の近くの都市は 3 個とも 2 ターンの距離に
//   そろえてあるので、どちらかを 1 ターンの距離へ寄せれば差を縮められる。

