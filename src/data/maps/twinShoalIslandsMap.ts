//     - row 7 の道路沿い: (6,6)(4)・(6,8)(6)・(7,8)(7)・(13,6)(11)・(13,8)(13)
//     - 東の港の道路沿い: (9,9)(10)・(11,9)(12)
//   浅瀬のそばの (13,6)(13,8) は、隣の 2P の工場から歩兵で 15 と 17。
//   陣地から取りに行くほうが近いが、浅瀬を渡ってきた相手に真っ先に狙われる都市になる。
