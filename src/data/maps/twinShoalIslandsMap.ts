// 4 つの島に 4 つの軍勢が 1 島ずつ陣取る 20x24(横20・縦24)の 4P マップ。
// 4Pマップ区分(group: 'four')の 3 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「浅瀬でつながる東西、狭い海峡を挟んで撃ち合う南北」
//   1P(青)は左上・2P(赤)は右上・3P(緑)は左下・4P(黄)は右下の島に陣取り、
//   手番は 1P → 2P → 3P → 4P の順に回る。
//   - 島はどれも横 8 マス(西の島は col 1〜8・東の島は col 11〜18)・縦 10 マスの細長い島。
//   - 1P と 2P の島、3P と 4P の島は、幅 2 マス(col 9〜10)の海峡に張り出した
//     **浅瀬(地形「川」)** でつながっている。浅瀬は縦 4 マス(北は row 4〜7・南は row 16〜19)で、
//     歩兵(コスト 2)と装軌車両(コスト 3)は歩いて渡れるが、装輪車両は渡れない。
//     海上ユニットは海と同じく浅瀬の上も進める。
//   - 北の 2 島と南の 2 島のあいだは幅 2 マスの海(row 11〜12)。地上ユニットが渡るには
//     輸送艦か輸送ヘリに乗るしかないが、海岸から向かいの海岸までは 3 マスなので、
//     **ロケット砲(射程 3〜5)や自走砲(射程 2〜3)は海越しに向かいの島を撃てる**。
//   - このマップに山は無い。島の中は平地が主で、都市へ向かう道路と、少しの森がある。
//   - 4 つの島は形も道路も拠点の並びも少しずつ違う(鏡写しにはしていない)。
//
// 陣地(4 軍とも本拠地 1 + 工場 4 + 空港 2 + 港 2 = 収入 9000。初期資金は 0):
//   港は、作った車両をすぐ輸送艦へ積めるよう陣地のそばに置き、どれも工場から 1〜2 マス。
//   1P・3P は島の左側(西の海岸)、2P・4P は島の右側(東の海岸)に港がある。
//   - 1P(左上): 本拠地 (3,2) / 工場 (3,1)(2,2)(2,3)(4,3) / 空港 (2,1)(4,1) / 港 (1,2)(1,4)
//   - 2P(右上): 本拠地 (16,3) / 工場 (16,2)(15,3)(17,3)(16,4) / 空港 (16,1)(17,2) / 港 (18,2)(18,4)
//   - 3P(左下): 本拠地 (3,20) / 工場 (3,19)(2,20)(4,20)(3,21) / 空港 (2,21)(4,21) / 港 (1,19)(1,21)
//   - 4P(右下): 本拠地 (16,20) / 工場 (16,19)(15,20)(17,20)(16,21) / 空港 (15,21)(17,21) / 港 (18,19)(18,21)
//   4Pモードで「なし」を選んだ軍勢の陣地は、本拠地が中立の都市に・ほかの拠点が中立になる
//   (src/data/maps/armySlots.ts)。
//
// 道路(島ごとに形を変えてある):
//   - 1P: 本拠地から東へ出て col 5 を南の海岸まで下る縦の道路。row 5 で東へ分かれて浅瀬へ、
//     row 7 で西へ分かれる
//   - 2P: 島の北の row 2 を西へ走り、col 12 を南の海岸近くまで下る。row 6 で西の浅瀬へ、
//     row 7 で東へ分かれる
//   - 3P: 島の北の row 14 を東西に走り、col 4 を陣地まで下る。row 17 で東の浅瀬へ分かれ、
//     陣地の東 col 5 から南東へ抜ける
//   - 4P: 陣地から col 15 を北の海岸近く (14〜15,14) まで上る。row 18 で西の浅瀬へ分かれる
//
// 中立都市(島ごとに 6 個):
//   陣地の 9 拠点(収入 9000)と合わせて、島を取り切ると収入がちょうど 15000 になる。
//   どれも道路に隣り合うマスにあり、1 島に「陣地のそばの 2 個・島の中ほど・浅瀬のそば・
//   海を挟んだ向かいの島に面した海岸」という散らばり方で置いてある。海岸の都市は、
//   向かいの島のロケット砲の射程に入る。
//   (かっこ内は各軍の工場・本拠地からの歩兵の移動コスト。3 までが 1 ターンで届く)
//     - 1P: (6,3)(2)・(3,5)(3)・(2,7)(4)・(6,7)(6)・浅瀬のそば (8,6)(7)・南の海岸 (6,10)(9)
//     - 2P: (16,6)(2)・(13,4)(3)・(14,6)(4)・(15,8)(5)・浅瀬のそば (11,5)(6)・南の海岸 (12,10)(10)
//     - 3P: (6,20)(2)・(3,16)(3)・(6,22)(4)・(2,15)(5)・浅瀬のそば (7,18)(5)・北の海岸 (7,13)(10)
//     - 4P: (16,17)(2)・(13,19)(3)・(16,15)(4)・(14,17)(4)・浅瀬のそば (11,17)(7)・北の海岸 (14,13)(8)
//   6 個ぶんの移動コストの合計は 1P 31・2P 30・3P 29・4P 28 で、手番の遅い軍ほどわずかに取りやすい
//   (docs/GameDesign.md「先手番のハンデ」)。1 ターンで届く都市は 4 軍とも 2 個。
//
// 陣地から陣地までの距離(工場・本拠地から相手の本拠地まで。歩兵 / 装軌車両):
//   1P→2P 16 / 18・2P→1P 17 / 19・3P→4P 16 / 19・4P→3P 16 / 19。
//   装輪車両は浅瀬を渡れないので、陸路では隣の島へ行けない。

