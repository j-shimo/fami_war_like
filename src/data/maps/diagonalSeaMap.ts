// 盤面を右上から左下へ斜めに横切る海が、2 つの三角形の島に分ける 40x24(縦24・横40)の激ムズマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
// 区分は extra(激ムズマップ)で、2P側で通常マップをすべてクリアするまで選択画面に出さない。
// 2P側専用のマップ(side: '2p')で、1P側の激ムズマップは双大陸マップ(twinContinentsMap)。
// 詳細は docs/GameDesign.md「クリア状況と激ムズマップ」を参照。
//
// ★ このファイルの player / enemy の読み方(重要)
//   2P側は盤面の自軍・敵軍を入れ替えて遊ぶ(src/data/maps/sideSwap.ts の swapMapSides)。
//   このマップは 2P側にしか出さないため、必ず入れ替えられた状態で遊ぶことになる。
//   そのため、このファイルの定義と実際の担当は次のように逆になる。
//     - 定義上の 'enemy'  → 遊ぶ人の自軍(右上の陣地)。後手番
//     - 定義上の 'player' → CPU が動かす敵軍(左下の陣地)。先手番
//   以下のコメントでは、遊ぶ人から見た呼び方(自軍 = 右上、敵軍 = 左下)で説明する。
//
// 設計コンセプト:「斜めの海を挟んで、完成した敵の島へ渡る」
//   双大陸マップ(1P側)は 3 本の橋で East / West がつながっていたが、こちらは陸路が 1 本も無い。
//   自軍の島と敵軍の島は海だけで隔てられており、渡る手段は輸送艦・輸送ヘリ・航空機しかない。
//   さらに 2P側は後手番なので、敵軍が 1 手先に動いた盤面から始まる。
//
// 盤面の骨格:
//   - 横 40・縦 24 の盤面を、幅 9 マスの海が右上(col 27〜35, row 0)から
//     左下(col 4〜12, row 23)へ 45 度でまっすぐ横切る。海は 208 マスあり、
//     両端が盤面の外へ抜けているので、艦隊はこの斜めの水路を端から端まで進める。
//   - 海の左上に「左の島」(372 マス)、右下に「右の島」(372 マス)が残る。
//     どちらも斜辺を海に向けた直角三角形で、面積はまったく同じ。
//   - 左の島(敵軍)は上辺と左辺いっぱいに広がり、南西の先端(左下)に敵軍の陣地がある。
//     右の島(自軍)は右辺と下辺いっぱいに広がり、北東の先端(右上)に自軍の陣地がある。
//     つまり両軍の陣地は、斜めの海のいちばん端どうしで向かい合っている。
//   - 陣地から陣地までは盤面を丸ごと斜めに渡る距離で、陸続きの経路は存在しない。
//
// 海に点在する 4 つの小島(空港と港だけ):
//   斜めの海の中心線に沿って、2 マスだけの小島が 4 つ等間隔に浮かぶ。
//     (29,2)港 +(30,2)空港 / (23,8)港 +(24,8)空港 /
//     (16,15)港 +(17,15)空港 / (9,21)港 +(10,21)空港
//   どの小島も港 1 個と空港 1 個だけでできており、平地も海岸も無い。
//   陸路では絶対に届かないので、取るには輸送艦(港へ横付け)か輸送ヘリで歩兵を運ぶしかない。
//   北の 2 島は自軍寄り、南の 2 島は敵軍寄りで、8 拠点ぶんの収入と前進基地を分け合う形になる。
//   空港を取れば飛行ユニットの修理と生産が海の真ん中でできるようになるため、
//   斜めの海の制空権・制海権はこの 4 島の取り合いで決まる。
//
// 左の島(敵軍・上左の三角形):
//   都市と森が島じゅうに広く分布する、開発の進んだ島(森 109 マス・都市 26 個)。
//   海沿いには階段状の沿岸道路が斜辺に沿って走り、内陸には横 4 本(row 2・6・10・14)と
//   縦 1 本(col 2)のはしご状の道路網が通っていて、26 個の都市はすべて道路に隣接している。
//   島の拠点は都市 26・空港 2・港 2 の 30 個で、そのうち 8 割にあたる 24 個が
//   開始時から敵軍の占領下にある。中立で残っているのは、敵軍の陣地からいちばん遠い
//   北東の端の 6 個((21,1)・(17,1)・(19,3)・(16,3)・(15,5) の都市と (26,0) の港)だけ。
//   この 6 個は海を挟んで自軍の陣地の目の前にあるので、序盤に船か空から手を伸ばせる。
//
// 右の島(自軍・下右の三角形):
//   平地と山ばかりの、開発の遅れた島(平地 159 マス・山 31 マス・都市 14 個)。
//   道路網は左の島と点対称の形(沿岸の階段道路 + row 21・17・13・9 + col 37)で通っているが、
//   拠点は都市 14・空港 1 (32,12)・港 1 (28,8) の 16 個しか無く、しかも全部が中立。
//   自軍の陣地は島の北東の先端にあり、都市はほとんどが南西寄りに散らばっているため、
//   自分の島を取り切るだけでも歩兵を何ターンも歩かせることになる。
//
// 両軍の陣地(本拠地 1・工場 2・空港 2・港 2 の計 7 拠点):
//   - 自軍は右上の (38,1) を本拠地とする先端の陣地。港 (36,0)・(35,1) は北の海に面する。
//   - 敵軍は左下の (1,22) を本拠地とする陣地で、配置は自軍の陣地を盤面ごと点対称にした形。
//   - 拠点の種類と数は両軍でまったく同じなので、生産力そのものに差は無い。
//     差が付くのは所有拠点数(= 収入)と、開始時に配置された部隊、そして手番の順だけ。
//
// 開始時の収入と伸びしろ:
//   自軍は陣地 7 拠点 = 7000 G、敵軍は陣地 7 + 左の島の 24 = 31 拠点 = 31000 G。
//   自軍の伸びしろは、右の島の中立 16 個 + 海の小島 8 個 = 24 個。取り切ってちょうど
//   7 + 24 = 31 拠点となり、敵軍の 31000 G と並ぶ。そこから先へ出るには、
//   左の島の中立 6 個を奪うか、敵軍の拠点を占領するしかない。
//
// 敵軍の初期部隊(合計 135000 G ぶん):
//   歩兵 4・中戦車 2・対空戦車 1・戦闘機 1・爆撃機 1・戦艦 1・護衛艦 1 の 11 体。
//   - 歩兵 4 体は斜辺の海岸((23,3)・(19,7)・(15,11)・(10,16))の真横に立ち、
//     上陸してくる部隊を水際で受け止める。(14,11) は森、(9,16) は山の上なので固い。
//   - 中戦車 2 両は森の中 (20,5)・(9,13) に控え、抜かれた海岸へ横から回り込む。
//   - 対空戦車 1 両は島の中央 (16,9) に据えてあり、輸送ヘリでの強行着陸を妨げる。
//   - 戦闘機は北の空港 (7,5)、爆撃機は中央の空港 (11,11) に置く。どちらも島の内陸なので
//     1 ターン目には海を越えられないが、2 ターン目からは自軍の島へ届く。
//   - 戦艦(射程 3〜6)は陣地の港 (4,22)、護衛艦は島の中ほどの港 (11,15) から
//     斜めの海へ出る。輸送艦は攻撃できないので、護衛を付けずに渡ると沈められる。
//   自軍の初期部隊は 0。1 ターン目に陣地の 7 拠点で生産して戦力を用意する。
//
// 初期資金は 20000 G(initialFunds)。1P側の双大陸マップと同額だが、こちらは海を渡らないと
// 何も始まらないぶん、輸送艦(16500 G)を 1 隻買うか、歩兵を並べて自分の島の占領を急ぐかの
// 二択を最初のターンで迫られる。
//
// 勝ち筋(このマップの想定):
//   1. まず自分の島を取り切る。右の島の中立 16 個を拾って収入を 7000 → 23000 G まで上げる。
//      敵軍の部隊は全部が左の島にいるので、序盤の占領は邪魔されない。
//   2. 並行して海の小島 4 つ(8 拠点)を輸送ヘリ・輸送艦で取り、収入 31000 G で敵軍に並ぶ。
//      小島の空港は前進基地になるので、ここを押さえると航空戦がぐっと楽になる。
//   3. 斜めの海の制海権を取る。敵軍の戦艦・護衛艦を沈めないと、輸送艦が渡れない。
//   4. 攻め込むのは最後。左の島の北東の端(中立の 6 拠点がある一帯)は敵軍の陣地から
//      いちばん遠いので、ここへ橋頭堡を築いてから沿岸道路を南西へ押していく。
//
// 難易度を調整したいときは、左の島の敵軍占領地のうち北寄りの数個を中立に戻す
// (敵軍の初期収入が下がり、自軍の上陸先が増える)、または敵軍の初期部隊から
// 戦艦・爆撃機を減らす。逆に難しくしたいなら、右の島の中立都市を減らす。

