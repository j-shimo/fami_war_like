// 中央を東西に貫く海峡を挟んだ 26x14(縦14・横26)の横長マップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「海と空、二つの機動力が戦線を渡す海峡マップ」
//   - 西端(col 0〜2)が自軍、東端(col 23〜25)が敵軍の陣地。盤面は横に長い 26 マスで、
//     街道を全力で走っても地上ユニットが端から端へ着くには 4〜6 ターンかかる。
//   - 盤面中央を東西に貫く海峡(row 5〜8 の帯。中央部は入り江で row 4・row 9 まで食い込む)が
//     盤面を「北の大陸」と「南の大陸」に分ける。海峡は両軍の陣地の手前で湾になって終わっており、
//     北の大陸と南の大陸がつながっているのは自軍陣地(col 0〜4)と敵軍陣地(col 21〜25)の
//     ただ 2 か所だけ。つまり地上ユニットが北の戦線と南の戦線を移動し直すには、
//     いったん自陣まで戻るしかない(盤面を横断するので 4〜6 ターンかかる)。
//   - これに対して海上ユニットは海峡を通って、飛行ユニットは海峡を飛び越えて、
//     北と南の戦線を自由に行き来できる。「戦線を渡す機動力」が海と空にしかない、
//     というのがこのマップの核となるルールで、海上ユニットと飛行ユニットの
//     どちらもが主役になれるように作ってある。
//
// 両軍の初期拠点(本拠地 1・工場 2・港 1・空港 1 の計 5 拠点):
//   - 陣地は北の大陸と南の大陸をつなぐ地峡そのもので、本拠地を中心に工場 2 つを南北に置いてある。
//     ここを抜かれると南北の連絡路を断たれるため、陣地の防衛がそのまま戦線の維持につながる。
//   - 港は陣地に食い込む 2 マスの湾の奥(自軍 (2,7)・敵軍 (23,6))にある。湾は幅 2 マスと狭く、
//     出入りする艦隊を守りやすい天然の軍港として機能する。
//   - 空港は陣地の最も外側(自軍 (0,5)・敵軍 (25,8))に、港とは反対の端になるよう置いてある。
//     港を敵艦に押さえられても飛行ユニットの生産と修理は続けられる。ただし戦艦の射程は 3〜6 と長く、
//     湾や海岸まで敵艦の侵入を許すと陣地の 5 拠点はすべて艦砲射撃の届く範囲に入る。
//     制海権を失うと生産拠点そのものを削られるため、海を捨てて空だけで戦うことはできない。
//
// 争点となる中立拠点:
//   - 海峡に浮かぶ「双子空港島」(中央の (12,6)・(13,7) が空港、(13,6)・(12,7) が海岸)。
//     盤面のちょうど中心にあり、陸地とは一切つながっていないので輸送艦か輸送ヘリでしか
//     歩兵を送り込めない。空港 2 つを押さえれば海峡の真上に前進航空基地を持てるため、
//     このマップ最大の係争地になる。海岸マスがあるので輸送艦を横付けでき、
//     揚げた歩兵を引き揚げることもできる(island の孤立で詰まないようにするための配置)。
//   - 海峡の中立港を持つ小島 2 つ((7,6)+(8,6)・(18,7)+(17,7))。港を取れば海峡の真ん中で
//     艦艇を修理・生産でき、制海権の維持が一気に楽になる。こちらも海岸マス付きの 2 マス島。
//   - 両大陸の海岸沿いの中立港 4 つ((5,4)・(16,4)・(9,9)・(20,9))。地上部隊でも占領できる港で、
//     ここを取ると本国から遠い戦線でも艦隊を回復・増援できる。
//   - 両大陸の中央にある中立空港 2 つ((12,2)・(13,11))。街道(row 2・row 11)沿いにあり
//     地上部隊で確保できるが、海峡の入り江から 2〜3 マスしかないため敵戦艦の艦砲射撃に晒される。
//   - 中立都市 24 個。港・空港を含めると占領可能な拠点は全 44 個で、取り切れば収入は 44000 G。
//     戦艦 35000 G・攻撃機 26500 G といった高額ユニットを運用するには占領を進める必要がある。
//
// 地上戦のルート:
//   - 北の大陸(row 0〜4)・南の大陸(row 9〜13)にはそれぞれ東西を貫く街道(row 2・row 11)が通っており、
//     車両はここを最速で走れる。ただし (9,2)(17,2)・(8,11)(16,11) は舗装が途切れた平地で、
//     装輪車両(偵察車・ロケット砲)だけがここで減速する(平地の移動コストは 2)。
//   - 街道の南北には山と森を配し、(10,1)(11,1)(14,1) や (7,3)(17,3) などが狭い回廊を作る。
//     装輪車両は森・山に入れないため、街道を外れて迂回できるのは歩兵と装軌車両だけになる。
//   - 海岸線には海岸(記号 b)を 16 マス置いてある。海岸は地上ユニットと海上ユニットが同じマスに
//     入れる地形なので、港を取らなくても輸送艦を着ければ上陸・乗船ができる。敵の街道の裏へ
//     直接戦車を揚げる強襲上陸が、このマップの主要な攻め手のひとつになる。
//
// 先手番ハンデの調整:
//   1 ターンぶん早く生産と占領を始められる先手(自軍)がそのまま収入で先行しやすいため、
//   docs/GameDesign.md「先手番のハンデ」の方針に従い、後手の敵軍陣地の隣にだけ
//   中立都市を 2 個((24,4) と (24,9))多く置いてある。どちらも敵軍本拠地から 2 ターンで
//   取り切れる位置にあり、取り切ったあとの収入が自軍より 2000 G ぶん多くなる。
//   自軍側の点対称位置((1,9) と (1,4))は平地のままで、これがこのマップ唯一の非対称点。
//   ハンデを増減させたいときは、この 2 マスを平地に戻す/敵軍陣地寄りの平地を都市に変える、で調整する。
//
// 初期資金は 20000 G(initialFunds)。開始時の収入 5000 G と合わせると 1 ターン目から
// 護衛艦(22000 G)や戦闘機(20000 G)に手が届く。「まず海を取るか、まず空を取るか」を
// 1 ターン目から選べるようにするための設定で、序盤を歩兵の占領作業だけで終わらせない狙いがある。
//
// 上記のハンデ 2 マスを除けば盤面は中心点対称(180度回転対称)で、地形・拠点の配置は自軍・敵軍で等しい。
