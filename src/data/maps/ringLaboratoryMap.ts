// 地上ユニットだけで戦う 13x11(縦11・横13)の対角マップ。新マップ区分(group: 'new')の 1 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「先手は中央の研究所、後手は中立都市。取るものを分けて釣り合わせる」
//   自軍(先手)と敵軍(後手)の陣地は本拠地 1 + 工場 3 の 4 拠点ずつで完全に対等、盤面も
//   道路の骨格が点対称((c,r) → (12-c,10-r))になっている。docs/GameDesign.md「先手番の有利」の
//   とおり完全対称のままでは先手が得をするので、後手には「中立都市に先に手が届く数が多い」
//   ハンデを与え、先手には「中央の研究所を先に取れる」見返りを残してある。
//     - 研究所は盤面のちょうど中央 (6,5)。両軍の最寄り工場から移動コスト 9 で完全な等距離だが、
//       先に動ける自軍が先着する。中立の研究所を占領し切った歩兵は新型戦車(生産不可・22000 G 相当)へ
//       進化するので、収入 4000 G の序盤では 5 ターンぶん以上の資金に当たる一撃の見返りになる。
//     - 中立都市は 14 個。先着できるのは自軍 6 個・敵軍 8 個で、敵軍のほうが 2 個多い。
//       放っておくと敵軍だけが収入を 4000 → 12000 G へ伸ばす。
//   「一撃の戦力(自軍)」対「伸び続ける収入(敵軍)」の交換が、このマップの主題になる。
//
// 陣地(本拠地 1 + 工場 3 = 収入 4000):
//   両軍とも盤面の角に 2x2 の拠点の塊を持つ。角のいちばん外側が本拠地で、その内側 3 マスが工場。
//     - 自軍(先手): 本拠地 (0,10) / 工場 (1,9)(0,9)(1,10) … 左下の角
//     - 敵軍(後手): 本拠地 (12,0) / 工場 (11,1)(12,1)(11,0) … 右上の角
//   本拠地があるので、勝敗は「相手の本拠地を占領する」か「相手軍を全滅させる」かで決まる
//   (src/core/victory/VictoryConditionChecker.ts)。本拠地は工場 3 つの裏に隠れており、
//   隣接するのは自陣の工場 2 マスだけなので、そこへ辿り着くには必ず陣地を突破することになる。
//   陣地のまわりは森で縁取ってあり(自軍側 (0,8)(2,10)(3,10)・敵軍側 (12,2)(9,0)(10,0))、
//   守る側は防御 2 の遮蔽を、攻める側は装輪車両(偵察車・ロケット砲)が入れない足場を得る。
//
// 道路の骨格(漢字の「日」を横倒しにした形):
//   外周の長方形(row 1 / row 9 / col 1 / col 11)に、中央の縦棒(col 6)を渡した形の街道。
//   長方形の 4 つの角が戦場の要になり、対角の 2 つの角に両軍の陣地が入る。
//     - 左下の角 (1,9) … 自軍(先手)の前線工場
//     - 右上の角 (11,1) … 敵軍(後手)の前線工場
//     - 左上の角 (1,1)・右下の角 (11,9) … どちらも中立都市
//   自軍の角から敵軍の角までは、どのルートを選んでも移動コスト 18 で等しい
//   (外周を左回り・右回り・中央の縦棒を経由、のいずれも 18)。中央の縦棒があるおかげで
//   「外周を大きく回る」か「中央を突っ切る」かを毎ターン選べる。
//
// 3 つの帯(道路の間の地形):
//   街道で仕切られた内側を、縦の帯で 3 つに塗り分けてある。どの移動タイプでどこを通れるかが
//   帯ごとに変わるため、ユニットの組み合わせで通れるルートが決まる。
//     - 左の山帯(col 2〜4): 山が 16 マス。装軌車両・装輪車両はどちらも進入できず、
//       歩兵だけが移動コスト 2 で乗り越えられる。自軍の陣地に接する側が車両の通れない
//       天然の城壁になり、自軍は少ない戦力でも左からの回り込みを歩兵だけに絞れる。
//       山の中に点在する平地 (2,3)(4,4)(4,6)(2,7)(4,8) はすべて街道か中央の平地帯に接しており、
//       車両が入り込めない袋小路にはならない。
//     - 中央の平地帯(col 5〜7): 研究所を挟む幅 3 マスの平地。全移動タイプが通れる唯一の内側ルートで、
//       遮蔽が無いぶん撃ち合いになりやすい。研究所の取り合いはここで起きる。
//     - 右の森帯(col 8〜10): 森が 16 マス。歩兵は移動コスト 1、装軌車両は 2 で通れるが、
//       装輪車両(偵察車・ロケット砲)は 1 マスも入れない(docs/TerrainSpec.md「森」)。
//       敵軍の陣地に接する側は、戦車と歩兵で押し引きする見通しの悪い戦場になる。
//   外周の外側(col 0 / col 12 / row 0 / row 10)も同じ帯の性格を引き継ぎ、左は山・右は森で縁取る。
//
// 中立都市 14 個の配置(かっこ内は「自軍からの移動コスト / 敵軍からの移動コスト」):
//   歩兵の移動力は 3 なので、コスト 3 までが 1 ターン・9 までが 3 ターン。
//     - 陣地のすぐ隣(両軍に 2 個ずつ・点対称): 自軍 (0,7)(2/17)・(4,10)(3/16)、
//       敵軍 (12,3)(17/2)・(8,0)(16/3)。どちらも 1 ターンで届く安全な収入で、
//       開戦前の立ち上がりを 4000 → 6000 G へ揃って伸ばす。取り合いにはならない。
//     - 左上(2 個): (1,1)(8/10) と (2,0)(10/10)。街道の左上の角とその外側で、
//       自軍のほうが近い。同着になる (2,0) も先に動ける自軍が取れる。
//     - 右下の 4 連(4 個): 下辺の街道 row 9 の 1 マス下、row 10 に (9,10)(8/11)・
//       (10,10)(9/10)・(11,10)(10/9)・(12,10)(11/9) と 4 個並べる。街道は col 1〜11 なので、
//       東端の (12,10) だけは街道の外側に出る。西の 2 個は自軍が、東の 2 個は敵軍が先に着くので、
//       下辺の街道の上と下で押し引きする戦場になる。
//     - 盤面を斜めに横切る 4 個: (3,1)(10/8)・(5,3)(10/8)・(8,6)(10/8)・(11,9)(10/8)。
//       街道の角と角を結ぶ対角線(col - row = 2)の上に並び、4 個とも敵軍が 1 ターン早い。
//       「1 ターンぶん敵軍寄りにずれた前線」を作っている。
//   先着できる数は自軍 6 個・敵軍 8 個で、敵軍が 2 個ぶん多く取りやすい。
//
// 距離の設計(歩兵の移動コスト。歩兵の移動力は 3 なので、コスト 9 までが 3 ターン):
//   - 研究所 (6,5): 自軍の最寄り工場 (1,9) から 9、敵軍の最寄り工場 (11,1) からも 9。
//     どちらも「ちょうど 3 ターン」で、マンハッタン距離 9 と一致するため、これより速い経路は無い。
//     街道だけをたどる最短路は (1,9) → row 9 を東へ 5 マス → col 6 を北へ 4 マスで、
//     ぴったり 9 マス。残る拠点からは 10 以上なので、最短は必ず前線工場 (1,9) 起点になる。
//     1 ターン目に生産した歩兵は生産ターンに動けないため、2〜4 ターン目の移動で研究所へ乗り、
//     占領耐久値 20 を HP10 の歩兵が 2 回に分けて削り切って 5 ターン目に進化する。
//   - 自軍の角から敵軍の角までは 18(歩兵 6 ターン・偵察車 3 ターン弱)。
//     docs/GameDesign.md「マップの広さ」の目安どおり、生産した部隊がすぐ前線に噛み合う狭さに収めてある。
//
// 収入カーブの想定(調整の目安):
//   - 開始時: 両軍とも本拠地 1 + 工場 3 = 4000 G。初期資金 0 なので、1 ターン目に出せるのは歩兵 4 体が上限。
//   - 2〜3 ターン目: 陣地の隣の中立都市 2 個を両軍とも取り切って 6000 G。ここまでは完全に対等。
//   - 5〜6 ターン目: 自軍は研究所と左上・右下西側の都市、敵軍は対角線と右下東側の都市へ手が届く。
//     先着ぶんを取り切ると自軍 11000 G(研究所込み)・敵軍 12000 G で、敵軍が 1000 G ぶん上回る。
//   - 自軍は新型戦車と先手の機動で早めに決めるか、敵軍寄りの都市を取り返して収入差を止めるかを選ぶ。
//   - 後手のハンデを弱めたいときは対角線の 4 個を col - row = 1 の側(例: (4,3)(7,6))へ寄せて
//     両軍同数ターンにする、強めたいときは col - row = 3 側へ 1 マスずらす、で調整する。
//     右下の 4 連は 1 マス東へずらすごとに敵軍の取り分が 1 個増えるので、こちらの効きが強い。
//
// 初期ユニットは 0。ゲーム開始時の収入で 1 ターン目から生産を始める設計とする。

