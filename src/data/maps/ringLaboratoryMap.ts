// 地上ユニットだけで戦う 17x15(縦15・横17)の対角マップ。新マップ区分(group: 'new')の 1 枚目。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
//
// 設計コンセプト:「先手は中央の研究所、後手は中立都市。取るものを分けて釣り合わせる」
//   自軍(先手)と敵軍(後手)の陣地は本拠地 1 + 工場 3 の 4 拠点ずつで完全に対等で、道路の骨格も
//   点対称((c,r) → (16-c,14-r))になっている。docs/GameDesign.md「先手番の有利」のとおり
//   完全対称のままでは先手が得をするので、後手には「中立都市を先に取り始められる」ハンデを与え、
//   先手には「中央の研究所を先に取れる」見返りを残してある。
//     - 研究所は盤面のちょうど中央 (8,7)。両軍の最寄り工場から移動コスト 9 で完全な等距離だが、
//       先に動ける自軍が先着する。中立の研究所を占領し切った歩兵は新型戦車(生産不可・22000 G 相当)へ
//       進化するので、収入 4000 G の序盤では 5 ターンぶん以上の資金に当たる一撃の見返りになる。
//     - 中立都市は 14 個。先着できるのは自軍 6 個・敵軍 8 個で、敵軍のほうが 2 個多い。
//       さらに陣地のすぐ隣の都市は敵軍だけが 1 ターンで届き(自軍は 2 ターン)、
//       序盤の収入の立ち上がりが敵軍のほうが 1 ターン早い(後述「立ち上がりの 1 ターン差」)。
//   「一撃の戦力(自軍)」対「先に伸び始める収入(敵軍)」の交換が、このマップの主題になる。
//
// 陣地(本拠地 1 + 工場 3 = 収入 4000):
//   両軍とも盤面の四隅からは 2 マス内側に入った位置に、2x2 の拠点の塊を持つ。塊の外側が本拠地で、
//   残る 3 マスが工場。
//     - 自軍(先手): 本拠地 (2,12) / 工場 (3,11)(2,11)(3,12) … 左下
//     - 敵軍(後手): 本拠地 (14,2) / 工場 (13,3)(14,3)(13,2) … 右上
//   本拠地があるので、勝敗は「相手の本拠地を占領する」か「相手軍を全滅させる」かで決まる
//   (src/core/victory/VictoryConditionChecker.ts)。本拠地に隣接するのは自陣の工場 2 マスと、
//   陣地を縁取る森 2 マスだけなので、装輪車両(偵察車・ロケット砲)は森へ入れず、
//   必ず工場のある側から陣地を突破することになる。歩兵と装軌車両は森を回り込めるが、
//   森は移動コストが重く(装軌車両は 2)、遠回りになる。
//   陣地のまわりの森は自軍側 (2,10)(4,12)(5,12)(1,12)(2,13)・敵軍側 (14,4)(12,2)(11,2)(15,2)(14,1) で、
//   守る側は防御 2 の遮蔽を、攻める側は装輪車両が入れない足場を得る。
//
// 盤面の縁(幅 2 マス):
//   四隅に拠点が貼り付かないよう、街道の外側にさらに幅 2 マスの縁を設けてある。
//     - 西・北西(col 0〜1 と row 0〜1 の西半分): 山。左の山帯をそのまま盤外まで伸ばした壁で、
//       車両は 1 両も入れない。
//     - 東・南東(col 15〜16 と row 13〜14 の東半分): 森。右の森帯を伸ばした縁で、装輪車両は入れない。
//     - 南北の中央(col 7〜9 の row 0〜1 と row 13〜14): 平地。中央の平地帯を伸ばした、
//       全移動タイプが通れる裏道になる。
//     - 両軍の陣地の外側(自軍なら左下・敵軍なら右上)は森と平地の小さな懐。
//       平地は (1,11)(3,13)(15,3)(13,1) の 4 マスで、いずれも自陣の工場に接しているため
//       装輪車両も出入りできる。陣地の裏へ回り込む道はここだけで、しかも森ごしの遠回りになる。
//
// 道路の骨格(漢字の「日」を横倒しにした形):
//   長方形(row 3 / row 11 / col 3 / col 13)に、中央の縦棒(col 8)を渡した形の街道。
//   長方形の 4 つの角が戦場の要になり、対角の 2 つの角に両軍の前線工場が入る。
//     - 左下の角 (3,11) … 自軍(先手)の前線工場
//     - 右上の角 (13,3) … 敵軍(後手)の前線工場
//     - 左上の角 (3,3)・右下の角 (13,11) … どちらも中立都市
//   自軍の角から敵軍の角までは、どのルートを選んでも移動コスト 18 で等しい
//   (外周を左回り・右回り・中央の縦棒を経由、のいずれも 18)。中央の縦棒があるおかげで
//   「外周を大きく回る」か「中央を突っ切る」かを毎ターン選べる。
//
// 3 つの帯(街道の内側の地形。row 4〜10):
//   街道で仕切られた内側を、縦の帯で 3 つに塗り分けてある。どの移動タイプでどこを通れるかが
//   帯ごとに変わるため、ユニットの組み合わせで通れるルートが決まる。
//     - 左の山帯(col 4〜6): 山が 16 マス。装軌車両・装輪車両はどちらも進入できず、
//       歩兵だけが移動コスト 2 で乗り越えられる。自軍の陣地に接する側が車両の通れない
//       天然の城壁になり、自軍は少ない戦力でも左からの回り込みを歩兵だけに絞れる。
//       山の中に点在する平地 (4,5)(6,6)(6,8)(4,9)(6,10) はすべて街道か中央の平地帯に接しており、
//       車両が入り込めない袋小路にはならない。
//     - 中央の平地帯(col 7〜9): 研究所を挟む幅 3 マスの平地。全移動タイプが通れる唯一の内側ルートで、
//       遮蔽が無いぶん撃ち合いになりやすい。研究所の取り合いはここで起きる。
//     - 右の森帯(col 10〜12): 森が 16 マス。歩兵は移動コスト 1、装軌車両は 2 で通れるが、
//       装輪車両(偵察車・ロケット砲)は 1 マスも入れない(docs/TerrainSpec.md「森」)。
//       敵軍の陣地に接する側は、戦車と歩兵で押し引きする見通しの悪い戦場になる。
//
// 中立都市 14 個の配置(かっこ内は「自軍からの移動コスト / 敵軍からの移動コスト」):
//   歩兵の移動力は 3 なので、コスト 3 までが 1 ターン・9 までが 3 ターン。
//     - 陣地のすぐ隣(両軍 2 個ずつ・後手だけが 1 ターンで届く): 自軍 (2,8)(4/16)・(7,12)(4/15)、
//       敵軍 (10,2)(16/3)・(14,5)(17/2)。取り合いにはならない安全な収入だが、
//       敵軍の 2 個は 1 ターンで、自軍の 2 個は 2 ターンで届く距離に置いてある。
//     - 左上(2 個): (3,3)(8/10) と (4,2)(10/10)。街道の左上の角とその外側で、
//       自軍のほうが近い。同着になる (4,2) も先に動ける自軍が取れる。
//     - 右下の 4 連(4 個): 下辺の街道 row 11 の 1 マス下、row 12 に (11,12)(8/11)・
//       (12,12)(9/10)・(13,12)(10/9)・(14,12)(11/9) と 4 個並べる。街道は col 3〜13 なので、
//       東端の (14,12) だけは街道の外側に出る。西の 2 個は自軍が、東の 2 個は敵軍が先に着くので、
//       下辺の街道の上と下で押し引きする戦場になる。
//     - 盤面を斜めに横切る 4 個: (5,3)(10/8)・(7,5)(10/8)・(10,8)(10/8)・(13,11)(10/8)。
//       街道の角と角を結ぶ対角線(col - row = 2)の上に並び、4 個とも敵軍が 1 ターン早い。
//       「1 ターンぶん敵軍寄りにずれた前線」を作っている。
//   先着できる数は自軍 6 個・敵軍 8 個で、敵軍が 2 個ぶん多く取りやすい。
//
// 立ち上がりの 1 ターン差(後手のハンデの中心):
//   陣地の隣の都市までの距離を、後手だけ 1 ターンぶん近くしてある。占領は「移動 → 占領」の順で、
//   都市の占領耐久値 20 を HP10 の歩兵が 2 回に分けて削るので、次のように 1 ターンずれる。
//     - 敵軍(後手): 移動コスト 2〜3 = 1 ターン。1 ターン目に生産 → 2 ターン目に到着して占領開始 →
//       3 ターン目に占領完了。4 ターン目の収入から 6000 G。
//     - 自軍(先手): 移動コスト 4 = 2 ターン。1 ターン目に生産 → 3 ターン目に到着して占領開始 →
//       4 ターン目に占領完了。5 ターン目の収入から 6000 G。
//   自軍が先手ぶん常に半手番早く動けることを踏まえても、収入が伸び始めるのは敵軍のほうが
//   まるまる 1 ターン早い。逆に研究所は等距離なので、先手ぶんの半手番で自軍が先着する。
//
// 距離の設計(歩兵の移動コスト。歩兵の移動力は 3 なので、コスト 9 までが 3 ターン):
//   - 研究所 (8,7): 自軍の最寄り工場 (3,11) から 9、敵軍の最寄り工場 (13,3) からも 9。
//     どちらも「ちょうど 3 ターン」で、マンハッタン距離 9 と一致するため、これより速い経路は無い。
//     街道だけをたどる最短路は (3,11) → row 11 を東へ 5 マス → col 8 を北へ 4 マスで、
//     ぴったり 9 マス。残る拠点からは 10 以上なので、最短は必ず前線工場 (3,11) 起点になる。
//     1 ターン目に生産した歩兵は生産ターンに動けないため、2〜4 ターン目の移動で研究所へ乗り、
//     占領耐久値 20 を HP10 の歩兵が 2 回に分けて削り切って 5 ターン目に進化する。
//   - 自軍の角から敵軍の角までは 18(歩兵 6 ターン・偵察車 3 ターン弱)。
//     docs/GameDesign.md「マップの広さ」の目安どおり、生産した部隊がすぐ前線に噛み合う狭さに収めてある。
//
// 収入カーブの想定(調整の目安):
//   - 開始時: 両軍とも本拠地 1 + 工場 3 = 4000 G。初期資金 0 なので、1 ターン目に出せるのは歩兵 4 体が上限。
//   - 3〜4 ターン目: 敵軍だけが陣地の隣の都市 2 個を取り切って 6000 G。自軍が 6000 G に届くのは
//     1 ターン遅れる。ここが後手のハンデの中心になる。
//   - 5〜6 ターン目: 自軍は研究所と左上・右下西側の都市、敵軍は対角線と右下東側の都市へ手が届く。
//     先着ぶんを取り切ると自軍 11000 G(研究所込み)・敵軍 12000 G で、敵軍が 1000 G ぶん上回る。
//   - 自軍は新型戦車と先手の機動で早めに決めるか、敵軍寄りの都市を取り返して収入差を止めるかを選ぶ。
//   - 後手のハンデを弱めたいときは、自軍の陣地の隣の都市 (2,8)(7,12) を 1 マスずつ陣地へ寄せて
//     移動コストを 3 に戻す(立ち上がりが両軍とも 1 ターンになり、差は先着数だけになる)。
//     強めたいときは対角線の 4 個を col - row = 3 の側へ 1 マスずらす。
//     右下の 4 連は 1 マス東へずらすごとに敵軍の取り分が 1 個増えるので、こちらの効きが強い。
//
// 初期ユニットは 0。ゲーム開始時の収入で 1 ターン目から生産を始める設計とする。

