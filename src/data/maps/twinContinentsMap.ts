// 中央を縦断する海峡で東西に分かれた 42x26(縦26・横42)の激ムズマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
// 区分は extra(激ムズマップ)で、通常マップをすべてクリアするまで選択画面に出さない。
// 詳細は docs/GameDesign.md「クリア状況と激ムズマップ」を参照。
//
// 設計コンセプト:「開拓されていない西の島から、完成した東の帝国へ攻め上がる」
//   これまでのマップで最大の盤面(横 42・縦 26 = 1092 マス)を、中央の海峡が東西に断ち切る。
//   西(col 1〜17)が自軍の島、東(col 24〜40)が敵軍の島で、盤面の外周はすべて外洋。
//   自軍は陣地 8 拠点だけ・都市は 1 個も持たずに始まり、敵軍は島の 21 拠点をすべて
//   占領済みで持ったうえ、10 体の部隊を配置した状態から始まる。
//   開始時の収入は自軍 8000 G / 敵軍 29000 G で、これまでのどのマップよりも大きい差がある。
//   docs/GameDesign.md「非対称マップ(意図的な劣勢スタート)」の劣勢スタートを、
//   逆転稜線マップ(ridgeMap)よりさらに一段厳しくしたものが、このマップの位置づけになる。
//
// 盤面の骨格:
//   - 中央の海峡(col 18〜23)が盤面を縦に貫き、両島を完全に分断する。海峡は北と南で
//     外洋につながっており、row 11〜14 だけ両島が張り出して幅 2 マス(col 20〜21)に狭まる。
//   - 海峡には 3 本の橋(道路)が架かる。北の橋(row 8)・中央の橋(row 12)・南の橋(row 17)で、
//     地上ユニットが東西を行き来できるのはこの 3 本だけ。1 本を敵に押さえられても、
//     残り 2 本があれば往来できる(3 本すべてを塞ぐと歩兵でも渡れなくなる)。
//   - 中央の橋だけは海峡が狭まった場所に架かるため、海の上を渡るのは 2 マスだけ。
//     北・南の橋は 6 マスを渡る長い桟橋で、渡っている間は防御 0 の道路の上に晒される。
//
// 海峡の 4 つの水域(橋は海上ユニットが通れないことに注意):
//   橋は道路なので海上ユニットは通り抜けられない。海峡は 3 本の橋で 4 つに割れており、
//   北口(row 1〜7)と南口(row 18〜24)は外洋につながっているが、橋と橋に挟まれた
//   row 9〜10 と row 15〜16 の水域(計 30 マス)はどこからも入れない内海になる。
//   艦隊が海峡へ入れるのは北口と南口だけで、外洋は島をぐるりと一周してつながっているため、
//   輸送艦は敵島の裏側の海岸へ回り込める。上陸できる海岸(記号 b)は両島の海岸線に 31 マスある。
//
// 海峡の 2 つの島(北の島・南の島):
//   海峡の北口(col 19〜22, row 3〜6)と南口(col 19〜22, row 19〜22)に、4x4 の島が 1 つずつ浮かぶ。
//   どちらも中立都市 3・中立空港 1・中立港 1 の 5 拠点を持ち、上陸用の海岸が 1 マスある。
//   橋とはつながっていないので、渡る手段は輸送艦(港・海岸へ着ける)か輸送ヘリだけ。
//   海峡のど真ん中に前進航空基地と補給港が浮かんでいる形なので、ここを取れるかどうかが
//   航空戦の主導権を左右する。両軍から等距離にあり、先に手を伸ばしたほうが得をする。
//
// 西の島(自軍・col 1〜17):
//   山・森・平地をバランスよく混ぜた守りやすい島(平地 39%・森 15%・山 7%)。
//   中立都市 19・中立空港 1・中立港 2(北の (9,1)・南の (11,24))の計 22 拠点が
//   すべて中立のまま置いてある。自軍は 1 つも占領していないので、ここを取り切るのが最優先。
//   島には縦 2 本(col 5・col 12)・横 5 本(row 2・8・12・17・22)のはしご状の道路網が通っており、
//   19 個の中立都市はすべて道路に隣接している。歩兵は道路をコスト 1 で走れるので、
//   陣地から近い順に (6,11) コスト 6、(9,13) 7、(4,7)・(4,19)・(7,16) 8 と、
//   1〜3 ターンで次々に占領へ入れる。中立空港 (14,11) は山に囲まれた盆地にあり、
//   陣地から歩兵でコスト 14。中央の橋のすぐ手前なので、取れば海峡の上空を押さえられる。
//
// 東の島(敵軍・col 24〜40):
//   平地が 67% を占める開けた島(森 6%・山 5%)。都市 17・空港 2・港 2 の 21 拠点が
//   すべて敵軍の占領下で、加えて敵陣地の 8 拠点があるため、敵軍は 29 拠点で開始する。
//   道路は 3 本の橋の東詰から東へ伸び、(29,12) で 1 つに合流してから敵陣地へ向かう。
//   合流後は (34,12) で北へ折れ、row 9 を東進して敵陣地の北口へ入る遠回りの経路で、
//   これは敵陣地の西を塞ぐ山地(col 35〜36, row 11〜14)を避けるため。
//   17 個の都市のうち 8 個((26,3)・(30,4)・(34,6)・(37,3)・(38,7)・(26,21)・(33,21)・(37,20))は
//   道路から離れた平地に点在しており、攻め込む側は街道から外れて拾いに行くことになる。
//
// 両軍の陣地(本拠地 1・工場 3・空港 2・港 2 の計 8 拠点):
//   - 自軍は西端の (2,13) を本拠地とする 4x5 の陣地。工場 3・空港 2 に加えて、
//     西岸に港を 2 つ((1,12)・(1,14))持つ。
//   - 敵軍は東端の (39,13) を本拠地とする同じ構成の陣地で、港は東岸の (40,12)・(40,14)。
//   - 拠点の種類と数は両軍でまったく同じなので、生産力そのものに差は無い。
//     差が付くのは所有拠点数(= 収入)と、開始時に配置された部隊だけ。
//   - 空港 2・港 2 を最初から持っているため、両軍とも 1 ターン目から航空機・艦艇を出せる。
//
// 敵軍の初期部隊(合計 86000 G ぶん):
//   戦闘機 1・爆撃機 1・歩兵 5・中戦車 2・ロケット砲 1 の 10 体を東の島に配置する。
//   - 歩兵 3 体は 3 本の橋を渡り切った先((24,8)・(24,12)・(24,17))に立ち、渡ってくる部隊を
//     真正面から受け止める。残り 2 体は北と南の都市((26,7)・(26,21))を守る。
//   - 中戦車 2 両は橋の後方 (27,11)・(27,15) に控え、抜かれた橋へ横から回り込む。
//   - ロケット砲 1 門は 3 ルートの合流点 (29,12) に据えてある。射程 3〜5 なので、
//     中央の橋を渡り切った先 (24,12)〜(26,12) を初期位置のまま射程に収めている。
//   - 戦闘機は北の空港 (33,3)、爆撃機は南の空港 (33,22) に置く。戦闘機は移動力 10、
//     爆撃機は 8 あるので、2 機とも 1 ターン目から海峡を越えて西の島へ届く。
//     自軍は対空戦車を早めに用意しないと、占領に出た歩兵を上から刈られる。
//
// 初期資金は 20000 G(initialFunds)。両軍に同額入るが、収入 29000 G の敵軍にとっては
// 誤差でしかなく、収入 8000 G の自軍にとっては 2 ターン半ぶんの生産力になる。
// 1 ターン目に自軍が出せるのは、対空戦車 1 両+歩兵数体、あるいは歩兵を並べて占領を急ぐ形。
//
// 勝ち筋(このマップの想定):
//   1. 3 本の橋を渡らせない。橋は幅 1 マスの道路(防御 0)なので、西詰の森・山に
//      自走砲やロケット砲を据えれば、渡ってくる敵を一方的に叩ける。
//   2. その間に西の島の 22 拠点を取り切る。取り切れば収入は 8000 → 30000 G になり、
//      敵軍の 29000 G に並ぶ。ここまで来て初めて高額ユニットを撃ち合える。
//   3. 海峡の 2 島(計 10 拠点)を輸送艦・輸送ヘリで取り、収入 40000 G と前進航空基地を得る。
//   4. 攻め込むのは最後。敵本拠地までは自軍本拠地から歩兵の移動コスト 40(敵軍から
//      自軍本拠地までもちょうど 40)で、盤面を丸ごと渡る遠征になる。
//
// 難易度を調整したいときは、東の島の都市のうち道路から離れた 8 個を中立に戻す
// (敵軍の初期収入が 21000 G に下がる)、または敵軍の初期部隊から中戦車・ロケット砲を減らす。
// 逆に難しくしたいなら、西の島の中立都市を減らして自軍の伸びしろを削る。

