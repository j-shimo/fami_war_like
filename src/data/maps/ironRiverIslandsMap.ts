// 上の「 の形をした小島と、下の大きな島が向かい合う 40x26(横40・縦26)の激ムズマップ。
// CLAUDE.md の方針に従い、地形配置・拠点配置はすべてオリジナルとする。
// 区分は extra(激ムズマップ)・マップ区分は new(新マップ)で、
// 1P側で「新マップ」の通常マップをすべてクリアするまで選択画面に出さない。
// 1P側専用のマップ(side: '1p')で、2P側の激ムズマップには別のマップを用意する。
// 詳細は docs/GameDesign.md「クリア状況と激ムズマップ」を参照。
//
// 設計コンセプト:「細い鉄橋 1 本で島を渡り、川をさかのぼって帝国の喉元を突く」
//   新マップの追加要素(駅・線路・列車砲 / 川 / 研究所)を、激ムズマップの
//   非対称スタートに重ねた 1 枚。盤面は 4 つの島に割れており、陸路で相手へ届く道は無い。
//   自軍は上の「 の形をした小島の陣地 9 拠点(収入 9000 G)だけ、
//   敵軍は下の大きい島の 4 割を中立に残したまま 24 拠点(収入 24000 G)を占領済みで、
//   さらに戦闘機・爆撃機・戦艦・護衛艦・輸送艦(中戦車と対空戦車を搭載済み)を
//   配置した状態から始まる。
//   初期資金は両軍 30000 G ちょうど — 列車砲 1 門ぶんの値段で、1 ターン目に
//   「列車砲を出すか、守りと占領を並べるか」を選ばせるための額にしてある。
//
// 盤面の骨格(4 つの島 + 右端の小島):
//   1. 自軍の島(上・152 マス): rows 1〜4 の横棒(cols 3〜30)と、その左端から下がる
//      rows 5〜12 の縦棒(cols 3〜7)でできた「 の字。横棒の真ん中が自軍の陣地で、
//      縦棒の左下の端 (4,12) に中立の研究所が 1 個ある。
//   2. 真ん中の島(50 マス・rows 8〜12 / cols 14〜23): 中立の駅 1・都市 5・空港 1・港 1。
//      自軍の線路がここまで伸びており、陸で取りにいけるのは自軍だけ。
//   3. 敵軍の島(下・257 マス・rows 14〜24): 北の海岸線が東へ向かって階段状に上がる大きな島。
//      右下が敵軍の陣地で、川 2 本と線路 2 本が陣地から放射状に伸びる。
//   4. 左下の島(42 マス・rows 18〜24 / cols 1〜6): 中立の空港 1・都市 4。
//   5. 右端の小島(15 マス・rows 2〜4 / cols 34〜38): 中立都市 3 だけの小島。
//      「 の右上 (30,1) から輸送ヘリ(移動力 6)で 5 マス — ちょうど 1 ターンで届く。
//
// 自軍の線路と、真ん中の島(このマップの最重要地点):
//   - 自軍の駅 (18,2) から線路が真下(本拠地 (17,2) の 1 列右)へ一直線に伸びる。
//     rows 5〜7 の 3 マスは海の上を渡る幅 1 マスの鉄橋で、ここが自軍の島と
//     真ん中の島をつなぐ唯一の陸路になる。線路は真ん中の島を縦断し、
//     中立の駅 (18,9) を通って島の南端 (18,12) で終わる。
//   - 線路は地上ユニットも歩ける(歩兵コスト 1・装軌車両 2・装輪車両 4)ので、
//     鉄橋は歩兵の通り道でもある。幅 1 マス・防御 0 なので、敵の航空機や艦砲に
//     狙われると渡るだけで削られる。
//   - 敵軍の島から真ん中の島への陸路は無い。敵軍が取りにくるには輸送艦か輸送ヘリが要る。
//     いっぽう自軍は本拠地から歩兵コスト 8(3 ターン)で中立の駅へ届く。
//     開幕のいちばん確実な伸びしろがこの島の 8 拠点になる。
//   - 自軍の港 2 つは線路をはさんで左 (17,4)・右 (19,4) にあり、面している海が別々。
//     右の港からは真ん中の島の港 (23,10) まで海路 12、敵の島の北岸へもそのまま出られるが、
//     左の港から東の海域へ回るには島をぐるりと回ることになる。
//
// 敵軍の線路 2 本と、列車砲の撃ち合い:
//   - 敵軍の駅 (35,20) から線路が「上」と「左」へ伸びる。上の線は col 35 を 5 マス上がって
//     北の海岸の駅 (35,15) へ、左の線は row 20 を西へ 15 マス走ってから col 20 を
//     3 マス上がり、西の駅 (20,16) へ着く(駅から駅まで軌道コスト 5 と 19)。
//   - 西の駅 (20,16) と、自軍の線路の南端 (18,12) はちょうど 6 マス離れている。
//     列車砲の射程は 2〜6 なので、**両軍の列車砲は線路の端どうしで撃ち合える**。
//     西の駅から真ん中の島 (20,12) までも 4 マスで、敵軍の列車砲は
//     真ん中の島の占領部隊を線路の上から叩ける。
//   - 敵軍の線路は 2 本とも敵軍の島に閉じており、自軍の線路とはつながっていない。
//     列車砲は線路と駅から降りられないので、どちらの列車砲も相手の島へは入れない。
//
// 敵軍の陣地へ通じる 2 本の川(艦隊の侵入路):
//   - 川は海上ユニットが移動コスト 1 で遡上できる(装輪車両は渡れない)。
//     このマップでは、敵軍の陣地へ北と西から幅 1 マスの川が 1 本ずつ流れ込んでいる。
//     * 北の川: 島の北岸 (29,14) から南下し、(29,19) で東へ折れて (34,19) まで。
//     * 西の川: 島の西岸 (9,22) から東へ row 22 をまっすぐ (33,22) まで。
//   - どちらの川の末端も敵軍の本拠地 (35,21) から 3 マス。戦艦の射程は 3〜6 なので、
//     **川をさかのぼった戦艦は動かずに敵の本拠地を砲撃できる**。
//     ただし川は幅 1 マスなので、敵艦 1 隻・沈めた船 1 隻でも栓になる。
//   - 川は敵軍の島を内側から仕切る壁でもある。北の川は島の北東の一角を、
//     西の川は南岸の細長い帯を切り離しており、どちらも陣地のそばでしか渡れない。
//
// 中立拠点 46 個の内訳(自軍の伸びしろ):
//   - 自軍の島 14(都市 12・縦棒の左下の研究所 (4,12) 1・西岸の港 (3,11) 1)
//   - 真ん中の島 8(駅 1・都市 5・空港 1・港 1)
//   - 右端の小島 3(都市 3)
//   - 左下の島 5(空港 1・都市 4)
//   - 敵軍の島の西半分 16(駅 (20,16)・研究所 2・空港 1・港 2・都市 10)
//   自軍の島から敵軍の島へ渡らずに取り切れるのは 30 個で、そこまでで収入は 39000 G。
//   敵軍の 24000 G を超えるが、そこへ届くころには敵軍も生産を回している。
//   敵軍の島の西半分に残る 16 個(研究所 2 個を含む)を奪うところからが本当の反攻になる。
//
// 自軍の島の中立研究所((4,12)・縦棒の左下の端):
//   自軍が敵軍の島へ渡らずに手に入れられる、ただ 1 つの研究所。
//   中立のうちに占領し切った歩兵はその場で新型戦車へ進化する(docs/GameDesign.md「研究所」)ので、
//   **開幕の劣勢を埋める 1 両**になる。ただし本拠地からは縦棒の街道づたいに歩兵の移動コスト 23
//   (8 ターン)と遠く、真ん中の島の中立駅(コスト 8)とは正反対の方向にある。
//   同じ縦棒の下には中立港 (3,11) と中立都市 (6,12) もあるので、
//   1 体を南へ下ろす遠征で研究所・港・都市をまとめて拾えるかどうかが序盤の分かれ目になる。
//   進化した新型戦車は、そのまま中立港 (3,11) で作った輸送艦に乗せて前線へ運べる。
//
// 敵軍の初期部隊(合計 135500 G ぶん):
//   戦闘機 1・爆撃機 1・戦艦 1・護衛艦 1・輸送艦 1(中戦車 1・対空戦車 1 を搭載済み)。
//   - 戦闘機は陣地の空港 (33,21)、爆撃機は南の空港 (35,23) に置く。どちらも 1 ターン目から
//     北へ飛び出せるので、自軍は対空戦車を用意しないと占領に出た歩兵を上から刈られる。
//   - 艦隊 3 隻は真ん中の島と敵軍の島にはさまれた row 13 の海に浮かべてある。
//     戦艦 (27,13) は射程 3〜6 で真ん中の島の東半分を初期位置のまま射程に収めており、
//     護衛艦 (31,13) がその傘になり、輸送艦 (33,13) が中戦車と対空戦車を積んだまま控える。
//     自軍がのんびり占領していると、真ん中の島に敵の上陸部隊が降りてくる。
//
// 勝ち筋(このマップの想定):
//   1. まず真ん中の島を取り切る(8 拠点)。鉄橋 1 本で歩兵を送り込めるのは自軍だけなので、
//      ここは速さで勝てる。港 (23,10) と空港 (15,9) を取れば前線の生産拠点になる。
//   2. 自分の島の 14 拠点(縦棒の左下の研究所を含む)と、右端の小島・左下の島の 8 拠点を
//      輸送ヘリ・輸送艦で拾う。収入 39000 G に届けば、生産力では敵軍を上回る。
//   3. 制海権を取る。敵の艦隊を沈めない限り、川をさかのぼる反攻は始まらない。
//   4. 北の川か西の川に艦隊をねじ込み、戦艦で敵の本拠地を叩きながら歩兵を上陸させる。
//      敵軍の島の西半分は中立のまま残っているので、上陸後はそこを足場にできる。
//
// 難易度を調整したいときは、敵軍の初期部隊から輸送艦(と積荷)を外す、または
// 敵軍の占領済み拠点のうち島の西寄りの 3 個((23,18)・(25,21)・(26,23))を中立へ戻す。
// 逆に難しくしたいなら、敵軍の島の中立拠点を敵軍の占領済みに変えて伸びしろを削る。

