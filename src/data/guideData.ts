// 図(キャプチャ)の描き分けは capture 種別で指定して rendering/guideCapture.ts が担う。

/**
 * スライドごとに描くキャプチャ(ゲーム画面風のイラスト)の種別。
 * 実際のスクリーンショット画像は持たず、本編と同じくコードで盤面を描き起こす。
 */
export type GuideCaptureKind =
  | 'objective' // ゲームの目的(本拠地の占領・敵の全滅)
  | 'income' // 収入と生産(拠点から資金、工場でユニット生産)
  | 'move' // ユニットの移動(青い移動範囲)
  | 'attack' // 攻撃(射程内の敵を攻撃・戦闘予測)
  | 'capture' // 占領(歩兵で拠点を奪う)
  | 'endTurn'; // ターン終了と勝敗(CPU の手番・決着)

/** ゲーム説明のスライド 1 枚ぶんの内容 */
export interface GuideSlide {
  /** 内部識別子(テストやページ管理に使う) */
  readonly id: string;
  /** スライドの見出し */
  readonly title: string;
  /** 説明本文(1 要素 = 1 行ぶん。箇条書きのように順に表示する) */
  readonly body: readonly string[];
  /** このスライドで描くキャプチャの種別 */
  readonly capture: GuideCaptureKind;
}

